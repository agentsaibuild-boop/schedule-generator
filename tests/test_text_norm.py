def test_техническите_означения_остават_латински():
    """Кирилизация на PEHD би счупила съпоставянето по материал."""
    for означение in ("PEHD", "DN160", "HDPE", "CCTV", "L=150м", "Q=10.00 l/s",
                      "PVC", "MS Project"):
        assert cyrillize(означение) == означение, означение


def test_смесен_ред_поправя_само_смесената_дума():
    assert cyrillize("Kл.7 a 110 PEHD") == "Кл.7 a 110 PEHD"
    # ...освен ако редът е обявен за български — тогава и
    # самостоятелната наставка се кирилизира, за да не стане
    # един клон на два (`Кл.8 a` и `Кл.8а`).
    assert cyrillize("Kл.7 a 110 PEHD", whole_line=True) == "Кл.7 а 110 PEHD"
    assert cyrillize("Q=10.36 l/s L=225м PEHD", whole_line=True) == "Q=10.36 l/s L=225м PEHD"


def test_чиста_кирилица_не_се_мени():
    ред = "Кл.48 от РШ 36 до Пр. Ш 1"
    assert cyrillize(ред) == ред


def test_празното_остава_празно():
    assert cyrillize("") == ""
    assert cyrillize(None) is None


