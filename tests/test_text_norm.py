def test_описание_със_смесена_азбука_съвпада_с_чистото():
    """Ред от КСС с латинско K трябва да намери задачата си, не да увисне."""
    from src.provenance import similarity

    чисто = "Полагане на тръби по клон Кл.48 водопровод"
    смесено = "Полагане на тръби по клон Kл.48 водопровод"
    assert similarity(чисто, смесено) == 1.0


def test_техническото_означение_не_се_слива_при_съпоставяне():
    from src.provenance import similarity

    # PEHD и PVC не бива да станат едно и също заради кирилизация.
    assert similarity("тръби PEHD DN160", "тръби PVC DN160") < 1.0
