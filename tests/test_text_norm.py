def test_смесеното_се_разпознава():
    assert has_mixed_script("Kл.8а") is True
    assert has_mixed_script("Кл.8а PEHD DN160") is False


def test_кои_думи_са_смесени():
    assert mixed_words("Kл.7 a 110 PEHD Бaлчо") == ["Kл", "Бaлчо"]


