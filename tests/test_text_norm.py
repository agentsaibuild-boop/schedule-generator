def test_латинско_k_в_етикет_на_клон_става_кирилско():
    assert cyrillize("Kл.8 a 160 ПЕВП-същ.").startswith("Кл.")


def test_реалните_пет_етикета_от_чертежа_се_поправят():
    """Точно редовете, които четецът изпускаше преди 31.08.2026."""
    от_чертежа = [
        "Kл.8 a 160 ПЕВП-същ.",
        "Kл.20 a  110 ПЕВП",
        "Kл.7 a  110 ПЕВП Q=10.00 l/s  L=150м",
        "Kл.20 a  110 ПЕВП Q=10.36l/s  L=225м",
        "Kл.8a  160 ПЕВП Q=10.48 l/s  L=165м",
    ]
    for ред in от_чертежа:
        assert cyrillize(ред).startswith("Кл."), ред


def test_името_на_улица_с_латинско_a():
    assert cyrillize("ул. Бaлчо Нейков") == "ул. Балчо Нейков"


def test_поправят_се_и_възли_и_части():
    assert cyrillize("OТ 86") == "ОТ 86"
    assert cyrillize("TП") == "ТП"
    assert cyrillize("РP") == "РР"


