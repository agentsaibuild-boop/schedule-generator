def test_административна_таблица_не_се_чете_като_ксс(tmp_path):
    """Свиленград: адресите на инстанциите даваха „14 дни" и „30 копия“ за
    количества, шест реда оставаха без верига и гейтът за запазване падаше."""
    редове = [{"Адрес": "Община Свиленград", "Работно време": "08:30-17:30",
               "Законов срок за съгласуване": 14, "__excel_row__": 2},
              {"Адрес": "РДПБЗН", "Работно време": "08:30-17:30",
               "Законов срок за съгласуване": 30, "__excel_row__": 3}]
    проект = _проект(tmp_path, ["Адрес", "Работно време",
                                "Законов срок за съгласуване"], редове)
    assert build_quantity_index(проект) == []


def test_истинската_таблица_с_количества_се_чете(tmp_path):
    """Същата спецификация, таблицата с 701 м — тя ТРЯБВА да мине."""
    редове = [{"Водопроводна мрежа": "Главни водопроводни клонове",
               "Ед. мярка": "m", "Дължина L /m/": 701, "__excel_row__": 2}]
    проект = _проект(tmp_path, ["Водопроводна мрежа", "Ед. мярка",
                                "Дължина L /m/"], редове)
    индекс = build_quantity_index(проект)
    assert len(индекс) == 1
    assert индекс[0].quantity == 701


def test_липсващите_заглавия_се_вадят_от_редовете(tmp_path):
    """Не всеки източник дава `headers`; редовете са ключувани по колона."""
    редове = [{"Наименование": "изкоп", "Ед. мярка": "м3", "Количество": 12,
               "__excel_row__": 2}]
    проект = _проект(tmp_path, [], редове)
    assert len(build_quantity_index(проект)) == 1
