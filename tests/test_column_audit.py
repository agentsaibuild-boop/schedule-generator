"""Непозната колона в КСС се ОБЯВЯВА, вместо да се чете като празна.

FAILURE означава: разпознаването на колони в src/provenance.py е счупено — или
речникът пак не хваща реално срещано заглавие (тогава цял КСС се чете с празни
мерки и графикът излиза без метри), или проверката мълчи, когато не е
разпознала нищо, и същият тих провал може да се повтори с ново оформление.

Мерилото са ДВЕ реални процедури с различни заглавия:

    Илиянци    „Ед. мярка"   „Количество"
    Дамяново   „М-КА"        „К-ВО"        ← 3148 реда се четяха с празна мярка

Речникът винаги ще е непълен.  Затова тестовете тук пазят не списъка, а
ПОВЕДЕНИЕТО: късият ключ да не съвпада вътре в чужда дума, и непоетата колона
да се вижда.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.provenance import (  # noqa: E402
    _DESC_KEYS, _QTY_KEYS, _UNIT_KEYS, _заглавието_пасва, audit_columns,
    build_quantity_index, describe_column_audit)


def _проект(tmp_path: Path, headers: list[str], rows: list[dict],
            име: str = "КСС") -> Path:
    (tmp_path / "converted").mkdir(exist_ok=True)
    (tmp_path / "converted" / f"{име}.json").write_text(json.dumps({
        "source_file": f"{име}.xlsx", "type": "excel",
        "sheets": [{"name": "КСС", "headers": headers, "rows": rows}],
    }, ensure_ascii=False), encoding="utf-8")
    return tmp_path


# ---------------------------------------------------------------------------
# Реалните заглавия на двете процедури
# ---------------------------------------------------------------------------

def test_съкратената_мярка_на_дамяново_се_чете():
    """„М-КА" — заглавието, заради което 3148 реда останаха без мярка."""
    assert _заглавието_пасва("М-КА", _UNIT_KEYS)
    assert _заглавието_пасва("К-ВО", _QTY_KEYS)


def test_пълните_заглавия_на_илиянци_продължават_да_се_четат():
    assert _заглавието_пасва("Ед. мярка", _UNIT_KEYS)
    assert _заглавието_пасва("Количество", _QTY_KEYS)
    assert _заглавието_пасва("Наименование", _DESC_KEYS)


# ---------------------------------------------------------------------------
# Късият ключ не бива да се крие в чужда дума
# ---------------------------------------------------------------------------

def test_късият_ключ_иска_цяла_дума():
    """„ме" вътре в „НаиМЕнование" направи описанието да мине за мярка."""
    assert not _заглавието_пасва("Наименование", ("ме",))
    assert _заглавието_пасва("МЕ", ("ме",))
    assert _заглавието_пасва("Ед. МЕ", ("ме",))


def test_дългият_ключ_си_остава_парче():
    """„количеств" в „Количество" трябва да пасва — иначе речникът се удвоява."""
    assert _заглавието_пасва("Количество на СМР", ("количеств",))


def test_описанието_не_попада_в_колоната_за_мярка(tmp_path):
    проект = _проект(
        tmp_path, ["Наименование", "Ед. мярка", "Количество"],
        [{"Наименование": "УО единичен", "Ед. мярка": 100,
          "Количество": 12, "__excel_row__": 2}])
    ред = build_quantity_index(проект)[0]
    assert ред.unit == "", "число или описание не е мярка"


# ---------------------------------------------------------------------------
# Мълчанието е невъзможно
# ---------------------------------------------------------------------------

def test_неразпозната_колона_за_мярка_вдига_тревога(tmp_path):
    """Точният случай на Дамяново, но с заглавие, което речникът НЯМА."""
    редове = [{"Наименование": f"позиция {i}", "Обозначение": "м",
               "Количество": 10 + i, "__excel_row__": i + 2}
              for i in range(6)]
    проект = _проект(tmp_path, ["Наименование", "Обозначение", "Количество"],
                     редове)

    доклад = audit_columns(проект)
    тревоги = [т for з in доклад for т in з["тревога"]]
    assert тревоги, "шест реда с количество и нито един с мярка минаха мълчаливо"
    assert any("мярка" in т for т in тревоги)

    # И непоетата колона се назовава поименно, за да се добави в речника.
    непоети = [н for з in доклад for н in з["непоети"]]
    assert "Обозначение" in непоети


def test_разпознатият_лист_не_вдига_шум(tmp_path):
    """Гейт, който вика винаги, спира да се чете."""
    редове = [{"Наименование": f"позиция {i}", "М-КА": "м",
               "К-ВО": 10 + i, "__excel_row__": i + 2} for i in range(6)]
    проект = _проект(tmp_path, ["Наименование", "М-КА", "К-ВО"], редове)

    доклад = audit_columns(проект)
    assert not [т for з in доклад for т in з["тревога"]]
    описание = describe_column_audit(доклад)
    assert описание and "разпознати" in описание[0]


def test_цените_не_се_броят_за_непоети(tmp_path):
    """„Ед.цена" и „Ст-ст" нямат роля НАРОЧНО — не бива да пълнят доклада."""
    редове = [{"Наименование": "позиция", "М-КА": "м", "К-ВО": 5,
               "ЕД.ЦЕНА": 12.5, "СТ-СТ": 62.5, "__excel_row__": 2}]
    проект = _проект(tmp_path, ["Наименование", "М-КА", "К-ВО",
                                "ЕД.ЦЕНА", "СТ-СТ"], редове)
    непоети = [н for з in audit_columns(проект) for н in з["непоети"]]
    assert непоети == []


