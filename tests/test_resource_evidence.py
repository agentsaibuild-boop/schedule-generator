sys.path.insert(0, str(Path(__file__).parent.parent))

from src.resource_evidence import (  # noqa: E402
    СЪСТОЯНИЯ, _без_наставка, binding, describe, state_of)


def _задача(ид, н, к, ресурси, пакет="P1") -> dict:
    return {"id": ид, "name": ид, "start_day": н, "end_day": к,
            "resources": ресурси, "parent_id": пакет, "chain_step": "laying"}


