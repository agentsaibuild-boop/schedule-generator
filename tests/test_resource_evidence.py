def test_състоянията_са_подредени_от_силно_към_слабо():
    assert СЪСТОЯНИЯ[0] == "confirmed"
    assert СЪСТОЯНИЯ[-1] == "assumed"


def test_измереният_връх_се_разпознава():
    състояние, бройка = state_of("Багер универсален")
    assert състояние == "observed_peak"
    assert бройка and бройка > 0


def test_предположената_бройка_се_разпознава():
    състояние, _ = state_of("Автокран")
    assert състояние == "assumed"


def test_наставката_по_дисциплина_не_крие_произхода():
    """„Багер универсален (съоръжения)" е същата машина."""
    assert _без_наставка("Багер универсален (съоръжения)") == "Багер универсален"
    assert state_of("Багер универсален (съоръжения)")[0] == "observed_peak"


def test_потвърденото_бие_измереното(tmp_path):
    cfg = {"capacity": {"Тест": 2},
           "произход": {"по_ресурс": {"Тест": {"observed_peak": 2,
                                               "confirmed": 5}}}}
    assert state_of("Тест", cfg) == ("confirmed", 5)


