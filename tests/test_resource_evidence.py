def test_ресурс_под_тавана_не_държи_срока():
    задачи = [_задача("A", 1, 5, ["Автокран"])]
    о = binding(задачи)
    авто = [р for р in о["ресурси"] if р["ресурс"] == "Автокран"]
    assert авто, "ресурсът трябва да се вижда"
    assert о["държат_срока"] == [] or авто[0]["пик"] >= авто[0]["таван"]


def test_непотвърдена_бройка_прави_срока_необвързващ():
    """Автокранът е 1 — една задача вече опира тавана."""
    о = binding([_задача("A", 1, 5, ["Автокран"])])
    assert о["държат_срока"], "един автокран при таван 1 държи срока"
    assert о["срокът_е_обвързващ"] is False
    текст = " ".join(describe(о))
    assert "НЕ Е ОБВЪРЗВАЩ" in текст
    assert "НЕ е потвърдил" in текст


def test_без_натоварени_ресурси_се_казва_ясно():
    о = binding([])
    assert о["държат_срока"] == []
    assert "Никой ресурс" in describe(о)[0]


def test_обобщаващите_и_празните_не_чупят():
    задачи = [{"id": "S", "is_summary": True, "resources": ["Автокран"]},
              {"id": "X", "resources": ["Автокран"]}]
    assert binding(задачи)["ресурси"] == []


