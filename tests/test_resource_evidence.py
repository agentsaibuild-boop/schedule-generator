def test_нищо_не_е_потвърдено_от_изпълнителя_още():
    """Докато не е питан, `confirmed` трябва да е празно навсякъде."""
    cfg = json.loads((Path(__file__).parent.parent / "config" /
                      "resource_capacity.json").read_text(encoding="utf-8"))
    по_ресурс = cfg["произход"]["по_ресурс"]
    assert по_ресурс, "произходът трябва да е записан за всеки ресурс"
    assert all(з.get("confirmed") is None for з in по_ресурс.values())
    измерени = [и for и, з in по_ресурс.items() if з.get("observed_peak")]
    предположени = [и for и, з in по_ресурс.items() if з.get("assumed")]
    assert измерени and предположени, "двете състояния трябва да са различими"
