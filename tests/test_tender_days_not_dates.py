def _текст_на_pdf(данни: bytes) -> str:
    fitz = __import__("fitz")
    with fitz.open(stream=данни, filetype="pdf") as документ:
        return "\n".join(страница.get_text() for страница in документ)


def _редове_на_pdf(данни: bytes) -> str:
    """Текстът, събран ПО РЕДОВЕ — заглавие от няколко думи не се къса."""
    fitz = __import__("fitz")
    редове: dict[tuple[int, int], list] = {}
    with fitz.open(stream=данни, filetype="pdf") as документ:
        for номер, страница in enumerate(документ):
            for x0, y0, _x1, _y1, дума, *_ in страница.get_text("words"):
                редове.setdefault((номер, round(y0)), []).append((x0, дума))
    return "\n".join(" ".join(д for _, д in sorted(редове[к]))
                      for к in sorted(редове))


