def test_pdf_axis_counts_days():
    """Оста е разграфена ДЕН ПО ДЕН — от първия до последния, като еталона."""
    график = _примерен_график()
    текст = _текст_на_pdf(export_to_pdf(график, "Проба"))
    последен = max(t["end_day"] for t in график)

    assert "ден 1" in текст, "началото на обекта не е отбелязано на оста"
    числа = set(текст.replace(chr(10), " ").split(" "))
    for ден in ("1", "2", str(последен // 2), str(последен)):
        assert ден in числа, f"ден {ден} го няма на скалата"
    for месец in ("Ян", "Фев", "Мар", "Апр", "Май", "Юни", "Юли"):
        assert месец not in текст, f"календарен месец „{месец}“ в оста"


