def _задача(ид, име, ден, дни, родител=None, **още):
    задача = {"id": ид, "name": име, "start_day": ден, "duration": дни,
              "end_day": ден + дни - 1, "type": "construction"}
    if родител:
        задача["parent_id"] = родител
    задача.update(още)
    return задача


