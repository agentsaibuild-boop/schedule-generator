def test_design_comes_before_construction():
    """Проектирането започва на ден 1 — то е първото и в списъка."""
    задачи = [
        _задача("СТР", "СТРОИТЕЛСТВО", 58, 197),
        _задача("СТР1", "Етап 1", 58, 40, родител="СТР"),
        _задача("ПРО", "ПРОЕКТИРАНЕ", 1, 45),
        _задача("ПРО1", "Водоснабдяване", 13, 23, родител="ПРО"),
    ]
    имена = [t["id"] for t in order_chronologically(задачи)]
    assert имена == ["ПРО", "ПРО1", "СТР", "СТР1"]


def test_children_stay_with_their_parent_and_run_in_order():
    """Детето остава под своя родител — И вътре в клона върви по ден.

    Изпълнителят, 25.08.2026: „НЕ трябва в същия клон дейност да е на по-долен
    ред, а да стартира по-рано от по-горен ред".  Затова „Б1" (ден 100) стои
    НАД „Б2" (ден 105), макар във входа да е под него.
    """
    задачи = [
        _задача("Б", "Втора фаза", 100, 10),
        _задача("Б2", "втора стъпка", 105, 5, родител="Б"),
        _задача("Б1", "първа стъпка", 100, 5, родител="Б"),
        _задача("А", "Първа фаза", 1, 10),
        _задача("А1", "стъпка", 1, 10, родител="А"),
    ]
    редът = [t["id"] for t in order_chronologically(задачи)]
    assert редът == ["А", "А1", "Б", "Б1", "Б2"], "детето се е откъснало"


def test_no_later_row_starts_earlier_inside_a_branch():
    """Правилото, както го каза изпълнителят — проверено на целия клон."""
    задачи = [_задача("К", "клон", 10, 20)]
    задачи += [_задача(f"К{n}", f"стъпка {n}", ден, 2, родител="К")
               for n, ден in enumerate((18, 10, 14, 12), start=1)]
    деца = [t for t in order_chronologically(задачи) if t.get("parent_id") == "К"]
    начала = [t["start_day"] for t in деца]
    assert начала == sorted(начала), f"редът не върви по дни: {начала}"


def test_nothing_is_lost():
    """Задача със счупен родител не изчезва — излиза накрая."""
    задачи = [
        _задача("А", "фаза", 1, 5),
        _задача("Х", "сирак", 3, 2, родител="НЯМА ТАКОВА"),
    ]
    изход = order_chronologically(задачи)
    assert {t["id"] for t in изход} == {"А", "Х"}
    assert len(изход) == 2


def test_order_is_stable_for_equal_starts():
    """Еднакво начало → редът от входа се пази (без разбъркване)."""
    задачи = [_задача("А", "а", 1, 1), _задача("Б", "б", 1, 1),
              _задача("В", "в", 1, 1)]
    assert [t["id"] for t in order_chronologically(задачи)] == ["А", "Б", "В"]


