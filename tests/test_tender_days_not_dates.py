def test_pdf_carries_no_calendar_dates():
    """Никъде в графика не се появява дата — нито в оста, нито в редовете."""
    данни = export_to_pdf(_примерен_график(), "Проба")
    assert данни, "експортът не върна нищо"
    текст = _текст_на_pdf(данни)
    редове = [ред for ред in текст.splitlines()
              if not ред.startswith("Проект:")]      # там стои датата на съставяне
    дати = [ред for ред in редове
            if re.search(r"\d{2}\.\d{2}\.\d{4}|\d{4}-\d{2}-\d{2}", ред)]
    assert not дати, f"остатъчни календарни дати: {дати[:3]}"


