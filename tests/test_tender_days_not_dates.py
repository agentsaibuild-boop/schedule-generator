def test_pdf_shows_predecessors_as_row_numbers():
    """„Последователност" сочи НОМЕРА на реда, не вътрешния ключ."""
    график = _примерен_график()
    график[3]["dependencies"] = [{"predecessor_id": "СТР", "type": "FS",
                                  "lag_days": 0}]
    редове = _редове_на_pdf(export_to_pdf(график, "Проба")).splitlines()
    # Дребните колони (мярка, диаметър, к-во, Послед., ЕКИП) са с по-малък
    # шрифт и излизат като свой ред при извличането — това е артефакт на
