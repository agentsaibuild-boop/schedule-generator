def test_xml_carries_the_day_numbers():
    """MSPDI не може без дати, но денят пътува в свои колони и се чете."""
    from src.export_xml import (FIELD_ID_NUMBER4, FIELD_ID_NUMBER5,
                                export_to_mspdi_xml)

    данни = export_to_mspdi_xml(_примерен_график(), "Проба")
    assert данни, "експортът не върна нищо"
    текст = данни.decode("utf-8") if isinstance(данни, bytes) else данни
    assert "Начало (ден)" in текст and "Край (ден)" in текст
    for поле in (FIELD_ID_NUMBER4, FIELD_ID_NUMBER5):
        assert текст.count(поле) > 1, f"полето {поле} е дефинирано, но не се пише"
