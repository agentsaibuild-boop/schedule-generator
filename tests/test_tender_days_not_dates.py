def _текст_на_pdf(данни: bytes) -> str:
    fitz = __import__("fitz")
    with fitz.open(stream=данни, filetype="pdf") as документ:
        return "\n".join(страница.get_text() for страница in документ)


def _примерен_график():
    return [
        _задача("ПРО", "ПРОЕКТИРАНЕ", 1, 45, type="design"),
        _задача("ПРО1", "Изготвяне на проект по част „Водоснабдяване“",
                13, 23, родител="ПРО", type="design", team="Проектант"),
        _задача("СТР", "СТРОИТЕЛСТВО", 58, 100),
        _задача("СТР1", "Полагане на водопроводни тръби", 58, 20,
                родител="СТР", team="Екип В1", diameter="110", length_m=1458.0),
    ]


def test_pdf_carries_no_calendar_dates():
    """Никъде в графика не се появява дата — нито в оста, нито в редовете."""
    данни = export_to_pdf(_примерен_график(), "Проба")
    assert данни, "експортът не върна нищо"
    текст = _текст_на_pdf(данни)
    редове = [ред for ред in текст.splitlines()
              if not ред.startswith("Проект:")]      # там стои датата на съставяне
    дати = [ред for ред in редове
            if re.search(r"\d{2}\.\d{2}\.\d{4}|\d{4}-\d{2}-\d{2}", ред)]
    assert not дати, f"остатъчни календарни дати: {дати[:3]}"


def test_pdf_has_the_human_columns():
    """Колоните са като в човешкия тръжен график."""
    текст = _текст_на_pdf(export_to_pdf(_примерен_график(), "Проба"))
    for колона in ("ID", "Вид дейност / Участък", "Срок", "Начало", "Край",
                   "Ресурси", "Продукт"):
        assert колона in текст, f"липсва колона „{колона}“"


def test_pdf_prints_day_numbers():
    """Началото и краят са ДНИ: проектирането е 1–45, полагането 58–77."""
    текст = _текст_на_pdf(export_to_pdf(_примерен_график(), "Проба"))
    сбито = текст.replace("\n", " ")
    assert "45 д" in сбито and "1 45" in сбито.replace("  ", " ")
    assert "20 д" in сбито and "58 77" in сбито.replace("  ", " ")


def test_pdf_axis_counts_days():
    """Оста е разграфена на дни, не на месеци."""
    текст = _текст_на_pdf(export_to_pdf(_примерен_график(), "Проба"))
    assert "дни 1" in текст, "оста не брои дни"
    for месец in ("Ян", "Фев", "Мар", "Апр", "Май", "Юни", "Юли"):
        assert месец not in текст, f"календарен месец „{месец}“ в оста"


