#: Цветовете са тези от реалния чертеж — легендата ги ползва за същото.
ЗЕЛЕН = (0.75, 1.0, 0.0)      # инвестиционна програма → ВЛИЗА
РОЗОВ = (1.0, 0.64, 0.73)     # следващ етап → не влиза
МАВОВ = (1.0, 0.0, 1.0)       # друг проект → не влиза

#: Стандартните шрифтове на PDF нямат кирилица — без този текстът излиза като
#: точки и тестът би „минавал" върху чертеж, който всъщност не се чете.
_ШРИФТ = str(Path(__file__).parent.parent / "fonts" / "DejaVuSans.ttf")


def _пиши(page, x: float, y: float, текст: str, размер: float = 7) -> None:
    page.insert_text(fitz.Point(x, y), текст, fontsize=размер,
                     fontfile=_ШРИФТ, fontname="deja")


def _ситуация(път: Path) -> Path:
    """Мъничък ситуационен чертеж: легенда, три линии в три цвята, три етикета."""
    doc = fitz.open()
    page = doc.new_page(width=600, height=400)

    # --- легенда: мостра вляво, текст вдясно, на един ред ---
    for i, (цвят, текст) in enumerate((
        (ЗЕЛЕН, "Инвестиционна програма за смесен канал"),
        (РОЗОВ, "Инвестиционна програма за битов канал - следващ етап"),
        (МАВОВ, "Канализация по друг проект"),
    )):
        y = 40 + i * 20
        page.draw_line(fitz.Point(30, y), fitz.Point(60, y), color=цвят, width=2)
        _пиши(page, 70, y + 3, текст)

    # --- трасета: всяко със своя цвят, добре раздалечени ---
    трасета = ((ЗЕЛЕН, 150), (РОЗОВ, 250), (МАВОВ, 350))
    for цвят, y in трасета:
        page.draw_line(fitz.Point(60, y), fitz.Point(560, y), color=цвят, width=2)

    # --- улици и етикети: етикетът стои ПЛЪТНО до своята линия ---
    _пиши(page, 300, 140, "ул.Грозден")
    _пиши(page, 300, 240, "ул.Комета")
    _пиши(page, 300, 340, "ул.Лале")

    for (_, y), (клон, dn, L) in zip(трасета, (
            ("Кл.48", 700, "618.74"),
            ("Кл.73", 300, "145.00"),
            ("Кл.91", 400, "77.50"))):
        _пиши(page, 100, y - 12, клон)
        _пиши(page, 100, y - 4, f"DN {dn}")
        _пиши(page, 100, y + 4, f"L={L}м")

    doc.save(str(път))
    doc.close()
    return път


_КОЛОНИ = [(40, "КЛОН №"), (110, "Начална"), (190, "Крайна"),
           (260, "действ."), (330, "коеф."), (400, "q транз."),
           (470, "D [mm]"), (530, "v [m/s]")]
_ВТОРИ_РЕД = {110: "точка", 190: "точка", 260: "дължина",
              330: "на редукция", 400: "[l/s]"}

_СТРАНИЦА_1 = [
    ["ГЛ.КЛ. I", "ОТ 43", "ОТ 57", "159,31", "1", "16,62", "225", "0,56"],
    ["КЛ.30-И", "OT 124A", "OT 26b", "395,34", "1", "1,25", "110", "0,17"],
]
#: Продължението на таблицата — БЕЗ заглавен ред, както е в реалния документ.
_СТРАНИЦА_2 = [
    ["КЛ.31-И", "OT 124A", "OT 124B", "12,30", "1", "0,05", "90", "0,01"],
]


def _данни(page, редове: list[list[str]], y0: float) -> None:
    for i, ред in enumerate(редове):
        for (x, _), стойност in zip(_КОЛОНИ, ред):
            _пиши(page, x, y0 + i * 20, стойност)


def _таблица(път: Path, продължение: bool = False) -> Path:
    """Оразмерителна таблица: хедър на два реда и редове с данни.

    С `продължение=True` се добавя втора страница БЕЗ заглавен ред — точно
    както е сканирана реалната тритомна таблица.
    """
    doc = fitz.open()
    page = doc.new_page(width=600, height=300)

    for x, текст in _КОЛОНИ:
        _пиши(page, x, 40, текст)
        if x in _ВТОРИ_РЕД:
            _пиши(page, x, 50, _ВТОРИ_РЕД[x])
    _данни(page, _СТРАНИЦА_1, 80)

    if продължение:
        _данни(doc.new_page(width=600, height=300), _СТРАНИЦА_2, 40)

    doc.save(str(път))
    doc.close()
    return път


