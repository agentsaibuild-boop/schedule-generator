"""Отсечките се четат от чертежа детерминистично — без модел, без vision.

Тръжните ситуации са ВЕКТОРНИ: текстът е машинно четим с координати, линиите
носят цвят, а легендата казва кой цвят какво значи.  Затова участъците не се
познават — четат се.

Двете твърдения, които тези тестове пазят:

    ЧЕТЕНЕ    „Кл.48" / „DN 700" / „L=618.74м" до линията е една отсечка,
              а най-близката улица ѝ дава името, както в еталонния график.
    ОБХВАТ    Инвестиционният чертеж показва И съседните мрежи — следващ етап,
              друг проект, съществуващи.  Цветът на линията под етикета,
              сверен с легендата, ги отделя.  Върху реалния търг филтърът сваля
              DN 300 от 2736 м (+131 % спрямо спецификацията) на 1152 м
              (−2.5 %), а отсечките от 68 на 46 — колкото канализационни
              участъка има човешкият еталон.

FAILURE означава: участъците пак ще идват от предположение вместо от чертежа.
Или четенето е спряло (тогава графикът се връща към „етапи" вместо трасета),
или филтърът е спрял (тогава в графика влизат мрежи от ДРУГА процедура и
срокът се раздува с чужда работа).

Чертежите тук се СЪЗДАВАТ от теста.  Клиентски файлове в репото не влизат, а и
тест, който зависи от нечий диск, не е тест.
"""

