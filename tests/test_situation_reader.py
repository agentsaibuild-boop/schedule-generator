def test_legend_maps_pen_to_scope(ситуация: Path):
    """Всяка мостра дава цвят → влиза ли, и КОЯ позиция го е решила."""
    with fitz.open(str(ситуация)) as doc:
        легенда = read_legend(doc[0])

    assert легенда[ЗЕЛЕН][0] is True
    assert легенда[РОЗОВ][0] is False
    assert легенда[МАВОВ][0] is False


def test_next_stage_beats_investment_programme(ситуация: Path):
    """„Инвестиционна програма … — СЛЕДВАЩ ЕТАП" съдържа и двете думи.

    Редът на правилата решава: изключващото трябва да надделее, иначе цял
    бъдещ етап влиза в срока на тази процедура.
    """
    with fitz.open(str(ситуация)) as doc:
        влиза, причина = read_legend(doc[0])[РОЗОВ]

    assert влиза is False
    assert "следващ етап" in причина.lower()


