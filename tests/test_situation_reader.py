def test_water_table_gives_segments_with_both_nodes(tmp_path: Path):
    отсечки = read_water_table(_таблица(tmp_path / "таблица.pdf"))

    assert len(отсечки) == 2
    първа = отсечки[0]
    assert първа.branch == "ГЛ.КЛ. I"
    assert първа.start_node == "ОТ 43"
    assert първа.end_node == "ОТ 57"
    assert първа.length_m == pytest.approx(159.31)
    assert първа.dn == 225
    assert първа.network == "В"


def test_water_diameter_is_not_a_neighbouring_column(tmp_path: Path):
    """Регресия: границите на колоните се четат по ПЪЛНИЯ обхват на заглавието.

    По левите краища „D [mm]" поемаше всичко след „действ. дължина" и в
    диаметъра влизаше оразмерителният дебит — DN излизаше 16, 27, 63.
    """
    отсечки = read_water_table(_таблица(tmp_path / "таблица.pdf"))

    assert [о.dn for о in отсечки] == [225, 110]


def test_wrapped_header_is_matched_by_word(tmp_path: Path):
    """„действ." и „дължина" са на два реда и се слепват в обратен ред.

    Затова заглавието се сравнява по ДУМИ, а не по началото на слепения надпис.
    """
    отсечки = read_water_table(_таблица(tmp_path / "таблица.pdf"))

    assert [о.length_m for о in отсечки] == pytest.approx([159.31, 395.34])


def test_table_continues_where_the_header_does_not(tmp_path: Path):
    """Заглавният ред е само на първата страница; таблицата — не.

    Реалната оразмерителна таблица е 3 страници.  Докато колоните се търсеха
    на всяка страница поотделно, 50 от 89 отсечки се изхвърляха МЪЛЧАЛИВО —
    водопроводът излизаше с една трета от мрежата си и никой не разбираше.
    """
    отсечки = read_water_table(_таблица(tmp_path / "три.pdf", продължение=True))

    assert len(отсечки) == 3
    последна = отсечки[-1]
    assert последна.branch == "КЛ.31-И"
    assert последна.length_m == pytest.approx(12.30)
    assert последна.dn == 90


