# Измерено 21.08.2026 върху реалния чертеж: от 77 етикета се четяха 68.  Девет
# отсечки (577 м) изпадаха по три различни начина, а следствието се виждаше
# чак в сверката с търга — DN500 излизаше −14 %, DN1000 −58 %.

ЧЕРЕН = (0.0, 0.0, 0.0)       # мастилото на подложката, НЕ мрежа


def _труден(път: Path) -> Path:
    """Чертеж с трите начина, по които етикет изпадаше."""
    doc = fitz.open()
    page = doc.new_page(width=600, height=460)

    _пиши(page, 200, 30, "ЛЕГЕНДА")
    page.draw_line(fitz.Point(30, 50), fitz.Point(60, 50), color=ЗЕЛЕН, width=2)
    _пиши(page, 70, 53, "Инвестиционна програма за смесен канал")
    page.draw_line(fitz.Point(30, 70), fitz.Point(60, 70), color=ЧЕРЕН, width=2)
    _пиши(page, 70, 73, "Съществуваща смесена канализация")

    # трасето е ЗЕЛЕНО; кадастралната подложка е черна и минава ПО-БЛИЗО
    for y in (150, 250, 350):
        page.draw_line(fitz.Point(60, y), fitz.Point(560, y), color=ЗЕЛЕН, width=2)
        page.draw_line(fitz.Point(60, y - 6), fitz.Point(560, y - 6),
                       color=ЧЕРЕН, width=1)

    # 1) съставен номер на клон
    _пиши(page, 120, 138, "Кл.3-1")
    _пиши(page, 120, 146, "DN 500")
    _пиши(page, 120, 154, "L=71.64м")
    # 2) ДВЕ тройки, долепени една до друга
    _пиши(page, 300, 238, "Кл.3-2")
    _пиши(page, 300, 246, "DN 600")
    _пиши(page, 300, 254, "L=58.48м")
    _пиши(page, 360, 238, "Кл.3-3")
    _пиши(page, 360, 246, "DN 300")
    _пиши(page, 360, 254, "L=66.88м")
    # 3) етикет БЕЗ име на клон
    _пиши(page, 200, 346, "DN 1000")
    _пиши(page, 200, 354, "L=95.70м")

    doc.save(str(път))
    doc.close()
    return път


@pytest.fixture()
def трудни(tmp_path: Path) -> list[Segment]:
    return read_sewer_situation(_труден(tmp_path / "труден.pdf"))


def test_every_length_label_becomes_a_segment(трудни):
    """Четири етикета L= са четири отсечки — нито един не изпада."""
    assert len(трудни) == 4


def test_composite_branch_number_is_read(трудни):
    """„Кл.3-1" е клон, разбит на подучастъци — чест случай, не изключение."""
    имена = {о.branch for о in трудни}

    assert "Кл.3-1" in имена


def test_two_labels_in_one_block_are_two_segments(трудни):
    """Долепени тройки не бива да се слепват в една отсечка."""
    по_име = {о.branch: о for о in трудни if о.branch.startswith("Кл.")}

    assert по_име["Кл.3-2"].dn == 600
    assert по_име["Кл.3-2"].length_m == pytest.approx(58.48)
    assert по_име["Кл.3-3"].dn == 300
    assert по_име["Кл.3-3"].length_m == pytest.approx(66.88)


def test_a_nameless_label_is_still_pipe(трудни):
    """Етикет без име на клон пак е тръба — с диаметър и дължина."""
    безименни = [о for о in трудни if not о.branch.startswith("Кл.")]

    assert len(безименни) == 1
    assert безименни[0].dn == 1000
    assert безименни[0].length_m == pytest.approx(95.70)


def test_base_ink_does_not_decide_the_scope(трудни):
    """Черната подложка минава по-близо от трасето, но не решава нищо.

    На реалния чертеж черното перо има 4365 линии срещу 240 за най-натоварената
    мрежа — кадастър, сгради, чертички под самите етикети — и печели по
    близост почти навсякъде.  Мрежите се маркират с ЦВЯТ; каквото е оставено
    черно или сиво, е основата на чертежа.
    """
    assert all(о.in_scope for о in трудни), \
        "подложката пак изяжда отсечките и те отпадат като „съществуващи\""
