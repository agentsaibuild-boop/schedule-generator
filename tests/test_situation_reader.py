def test_only_the_investment_network_is_in_scope(отсечки):
    в_обхват = [о.branch for о in отсечки if о.in_scope]

    assert в_обхват == ["Кл.48"]


def test_dropped_segments_say_which_legend_entry_dropped_them(отсечки):
    """Отпадането се обяснява — иначе човек не може да провери преценката."""
    отпаднали = {о.branch: о.scope_reason.lower() for о in отсечки if not о.in_scope}

    assert "следващ етап" in отпаднали["Кл.73"]
    assert "друг проект" in отпаднали["Кл.91"]


def test_summary_counts_only_what_is_in_scope(отсечки):
    обобщение = summarize(отсечки)

    assert обобщение["segments"] == 1
    assert обобщение["dropped"] == 2
    assert обобщение["by_dn"] == {700: {"count": 1, "length_m": 618.74}}
    assert обобщение["total_m"] == pytest.approx(618.74)


