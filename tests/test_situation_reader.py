def test_drawing_without_legend_yields_nothing(tmp_path: Path):
    """Без легенда обхватът е неизвестен — по-добре нищо, отколкото догадка."""
    doc = fitz.open()
    page = doc.new_page()
    page.draw_line(fitz.Point(10, 10), fitz.Point(200, 10), color=ЗЕЛЕН)
    _пиши(page, 50, 30, "Кл.5", 8)
    _пиши(page, 50, 40, "DN 300", 8)
    _пиши(page, 50, 50, "L=10.00м", 8)
    път = tmp_path / "без_легенда.pdf"
    doc.save(str(път))
    doc.close()

    assert read_sewer_situation(път) == []
