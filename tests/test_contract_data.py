"""Договорните срокове идват от документите на ТАЗИ процедура.

FAILURE означава: src/contract_data.py е счупен — или приложението с договорни
данни не се разпознава (тогава срокове, работна седмица и срокът за дефекти пак
се приемат по подразбиране, вместо да се четат), или обратното: чете се нещо,
което го няма, и графикът твърди договорни условия, каквито възложителят не е
поставял.

Изпълнителят, 31.08.2026: „При FIDIC е по-специфично, за всеки е различно и
трябва внимателно да се прочете тръжната документация, предоставена от
инвеститора."

Двете процедури от корпуса се различават точно по това:

    Свиленград (ВиК Хасково)   FIDIC — има приложение „Под-Клауза | Данни"
    Илиянци (Столична община)  национален договор — такова приложение НЯМА

Затова празният отговор е също толкова важен, колкото намереният.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.contract_data import (  # noqa: E402
    _дни_от, describe, read_appendix, read_contract)

docx = pytest.importorskip("docx", reason="python-docx липсва")


def _документ(tmp_path: Path, редове: list[list[str]],
              име: str = "Специфични условия.docx") -> Path:
    """Docx с таблица като приложението за договорни данни."""
    d = docx.Document()
    t = d.add_table(rows=len(редове), cols=len(редове[0]))
    for i, ред in enumerate(редове):
        for j, клетка in enumerate(ред):
            t.rows[i].cells[j].text = клетка
    (tmp_path / име).parent.mkdir(parents=True, exist_ok=True)
    d.save(str(tmp_path / име))
    return tmp_path / име


# ---------------------------------------------------------------------------
# Числата се четат
# ---------------------------------------------------------------------------

def test_дни_се_четат_и_с_изписаното_число():
    assert _дни_от("365 дни") == 365
    assert _дни_от("56 (петдесет и шест) дни") == 56
    assert _дни_от("30 календарни дни") == 30
    assert _дни_от("Неприложимо") is None


def test_месеците_стават_дни_по_трийсет():
    assert _дни_от("19 месеца") == 570


def test_приложението_се_разпознава_по_заглавието(tmp_path):
    п = _документ(tmp_path, [
        ["Под-Клауза", "Данни за попълване", "Данни"],
        ["1.1.27", "Срок за съобщаване на дефекти (ССД):", "365 дни"],
        ["6.5", "установено работно време на Площадката:",
         "8-17 понеделник-петък"],
    ])
    редове = read_appendix(п)
    assert len(редове) == 2
    assert редове[0]["дни"] == 365
    assert редове[0]["роля"] == "срок_за_дефекти"


# ---------------------------------------------------------------------------
# Работната седмица — тя мени всички календарни дни
# ---------------------------------------------------------------------------

def test_петдневната_седмица_се_разпознава(tmp_path):
    _документ(tmp_path, [
        ["Под-Клауза", "Данни за попълване", "Данни"],
        ["6.5", "установено работно време:", "8-17 понеделник-петък"],
    ])
    данни = read_contract(tmp_path)
    assert данни["работна_седмица"] == "5/5"
    assert any("1.4 пъти" in б for б in данни["бележки"])


def test_срокът_за_дефекти_излиза_наименувано(tmp_path):
    _документ(tmp_path, [
        ["Под-Клауза", "Данни за попълване", "Данни"],
        ["1.1.27", "Срок за съобщаване на дефекти (ССД):", "365 дни"],
    ])
    assert read_contract(tmp_path)["срок_за_дефекти_дни"] == 365


def test_непопълненото_време_за_завършване_се_обявява(tmp_path):
    """В реалното приложение то стои като „…. календарни дни“ — попълва се от
    офертата.  Празно не бива да мине за нула."""
    _документ(tmp_path, [
        ["Под-Клауза", "Данни за попълване", "Данни"],
        ["1.1.86", "Време за завършване:", ".... календарни дни"],
    ])
    данни = read_contract(tmp_path)
    assert данни["време_за_завършване_дни"] is None
    assert any("непопълнено" in б for б in данни["бележки"])


