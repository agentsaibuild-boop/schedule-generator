def test_процедура_без_приложение_казва_че_няма(tmp_path):
    """Илиянци е по национален договор — няма FIDIC приложение."""
    d = docx.Document()
    d.add_paragraph("Проект на договор без приложение с договорни данни.")
    d.save(str(tmp_path / "Проект на договор.docx"))

    данни = read_contract(tmp_path)
    assert данни["приложение"] == []
    assert данни["работна_седмица"] == ""
    assert any("не е намерено" in б for б in данни["бележки"])


def test_несъществуваща_папка_не_гърми(tmp_path):
    данни = read_contract(tmp_path / "няма")
    assert данни["приложение"] == []
    assert describe(данни)
