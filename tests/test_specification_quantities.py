def test_deterministic_empty_allocation_says_what_happened():
    """Празно разпределение = съобщение, не UnboundLocalError.

    Детерминистичният клон не задава `system_prompt`; двата цикъла за повторно
    питане обаче го ползваха.  Резултатът беше краш точно когато входът е
    най-неразбираем — тоест тогава, когато на човека му трябва обяснение.
    """
    import json as _json

    from src.ai_processor import AIProcessor
    from src.provenance import QuantityRow, SourceRef

    class _Router:
        def __init__(self):
            self.calls: list[dict] = []

        def chat(self, messages, system_prompt, **kw):
            self.calls.append({"messages": messages})
            return {"content": _json.dumps({"packages": []}), "model": "fake",
                    "cost": 0.0}

    неразпознат = QuantityRow(
        description="Непредвидени разходи по преценка на възложителя",
        quantity=5.0, unit="бр.",
        source=SourceRef("СПЕЦИФИКАЦИЯ.docx", "таблица 1", 2, "Количество"),
        raw={},
    )
    router = _Router()
    proc = AIProcessor(router=router, knowledge_manager=None)

    out = proc.generate_packages({"analysis": "{}"}, [неразпознат])

    assert out["status"] == "error"
    assert "верига" in out["message"], out["message"]
    assert router.calls == [], "детерминистичният режим не бива да пита модела"
