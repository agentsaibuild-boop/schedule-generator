def test_docx_table_lands_in_full_text(проект: Path):
    """Числата от таблицата трябва да се четат и от текста, не само от `tables`."""
    файл = next(проект.glob("*.docx"))
    данни = FileManager()._convert_docx(str(файл))["data"]

    assert "1 182,00" in данни["full_text"]
    assert "Изграждане на канализационни клонове Ф300 РР" in данни["full_text"]
    assert "Ед. мярка" in данни["full_text"]


def test_docx_table_stays_structured_too(проект: Path):
    """Текстът е ДОПЪЛНЕНИЕ — структурираната таблица не бива да изчезва."""
    файл = next(проект.glob("*.docx"))
    данни = FileManager()._convert_docx(str(файл))["data"]

    assert len(данни["tables"]) == 1
    assert данни["tables"][0]["headers"] == ["№", "СМР", "Ед. мярка", "Количество"]
    assert len(данни["tables"][0]["rows"]) == len(_РЕДОВЕ) - 1


def test_paragraphs_are_not_polluted_by_the_table(проект: Path):
    """Абзаците си остават проза — таблицата влиза в текста, не в абзаците."""
    файл = next(проект.glob("*.docx"))
    данни = FileManager()._convert_docx(str(файл))["data"]

    assert all("Ед. мярка" not in p for p in данни["paragraphs"])


