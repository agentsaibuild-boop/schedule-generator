#: Извадка по образеца на реална техническа спецификация: римски раздел със
#: слети клетки, после позиции с мярка и количество.  Числата са измислени —
#: тестът пази механизма, не конкретен търг.
_РЕДОВЕ = [
    ["№", "СМР", "Ед. мярка", "Количество"],
    ["I", "Канализационна мрежа", "Канализационна мрежа", "Канализационна мрежа"],
    ["1", "Изграждане на канализационни клонове Ф300 РР", "m'", "1 182,00"],
    ["2", "Изграждане на канализационни клонове Ф400 РР", "m'", "260"],
    ["3", "Сградно канализационно отклонение", "Бр.", "180"],
    ["II", "Водопроводна мрежа", "Водопроводна мрежа", "Водопроводна мрежа"],
    ["1", "Реконструкция на разпределителната мрежа с Ф 90 РЕ", "m'", "538,63"],
    ["2", "Водомерна шахта", "Бр.", "1"],
    ["III", "Пътни работи", "Пътни работи", "Пътни работи"],
    ["1", "Възстановяване на асфалтова настилка", "кв.м.", "10 824"],
]

_ПРОЗА = (
    "Настоящата техническа спецификация определя изискванията към "
    "изпълнението на строително-монтажните работи по обекта.  Изпълнителят "
    "следва да спазва действащата нормативна уредба и одобрения проект.  "
    "Всички материали подлежат на входящ контрол от строителния надзор.\n"
) * 12


def _спецификация(папка: Path, име: str = "ТЕХНИЧЕСКА СПЕЦИФИКАЦИЯ.docx") -> Path:
    """Създай DOCX по образеца на техническа спецификация: проза + една таблица."""
    from docx import Document

    doc = Document()
    for абзац in _ПРОЗА.splitlines():
        if абзац.strip():
            doc.add_paragraph(абзац)

    таблица = doc.add_table(rows=len(_РЕДОВЕ), cols=4)
    for ri, ред in enumerate(_РЕДОВЕ):
        for ci, клетка in enumerate(ред):
            таблица.cell(ri, ci).text = клетка

    път = папка / име
    doc.save(str(път))
    return път


@pytest.fixture()
def проект(tmp_path: Path) -> Path:
    """Папка на проект, в която единственият документ е спецификацията."""
    _спецификация(tmp_path)
    return tmp_path


