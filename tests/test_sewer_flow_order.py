"""Каналът тръгва от заустването и от едрите тръби към дребните.

FAILURE означава: графикът пак може да започне с най-горния клон Ф300 и да
стигне до колектора Ф1000 накрая — тоест обратното на гравитацията, по която
се строи канализация.  Правилото е основно знание за предмета, а не настройка
по проект: долният участък приема водата на горния, изкопът му е най-дълбок и
отводняването по време на строителството върви надолу.

Изразено е като ПРИОРИТЕТ (редът в списъка, който изравняването уважава), не
като зависимост — иначе обектът се сериализира и графикът твърди чакане,
каквото на място няма.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.work_package import (  # noqa: E402
    PackageItem,
    SpatialWorkPackage,
    order_sewer_by_flow,
)


def _канал(id_: str, dn: int, откъде: str = "", докъде: str = ""):
    return SpatialWorkPackage(
        id=id_, network="К", chain="sewer_section",
        name=f"Кл.{id_} DN{dn}", dn=dn,
        start_node=откъде, end_node=докъде,
        items=(PackageItem(source_ref=f"СПЕЦ!{id_}", activity_class="laying",
                           quantity=100.0, unit="м", dn=dn),))


def _вода(id_: str, dn: int):
    return SpatialWorkPackage(
        id=id_, network="В", chain="water_section",
        name=f"Кл.{id_} DN{dn}", dn=dn,
        items=(PackageItem(source_ref=f"СПЕЦ!{id_}", activity_class="laying",
                           quantity=100.0, unit="м", dn=dn),))


class TestРедПоЗаустване:
    """Когато документите дават свързаност между шахтите."""

    def test_най_долният_участък_е_пръв(self):
        # РШ5 → РШ3 → РШ1 → заустване; входният ред е нарочно обърнат.
        пакети = [
            _канал("P3", 300, "РШ 5", "РШ 3"),
            _канал("P1", 800, "РШ 1", "Пр.Ш 1"),
            _канал("P2", 500, "РШ 3", "РШ 1"),
        ]
        подредени, бележки = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["P1", "P2", "P3"], (
            "участъците не са подредени от заустването нагоре — "
            f"{[p.id for p in подредени]}")
        assert "заустването" in бележки[0], бележки

    def test_при_равно_разстояние_печели_едрият_диаметър(self):
        # Два клона се вливат в една и съща шахта — еднакво далеч от изхода.
        пакети = [
            _канал("A", 400, "РШ 9", "РШ 2"),
            _канал("B", 1000, "РШ 8", "РШ 2"),
            _канал("C", 600, "РШ 2", "Заустване"),
        ]
        подредени, _ = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["C", "B", "A"], (
            "при еднакво разстояние до заустването редът не следва диаметъра — "
            f"{[p.id for p in подредени]}")

    def test_участък_без_възли_отива_накрая_а_не_напред(self):
        # Едрият диаметър НЕ купува място напред, щом не се знае къде е в
        # мрежата: непознатото не бива да изпревари доказаното.
        пакети = [
            _канал("БЕЗ_ВЪЗЛИ", 1200),
            _канал("DOWN", 300, "РШ 1", "Пр.Ш 1"),
            _канал("UP", 300, "РШ 2", "РШ 1"),
        ]
        подредени, _ = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["DOWN", "UP", "БЕЗ_ВЪЗЛИ"], (
            "участък извън графа изпревари доказаните — "
            f"{[p.id for p in подредени]}")

    def test_два_водосбора_имат_две_зауствания(self):
        # Обект с ДВЕ заустващи точки е нормален случай, не дефект: всяка
        # терминална шахта е изход на своя водосбор.  И двата долни участъка
        # са първи, а помежду си се редят по диаметър.
        пакети = [
            _канал("ГОРЕ_А", 300, "РШ 5", "РШ 4"),
            _канал("ДОЛУ_А", 600, "РШ 4", "Заустване А"),
            _канал("ДОЛУ_Б", 1000, "РШ 9", "Заустване Б"),
        ]
        подредени, бележки = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["ДОЛУ_Б", "ДОЛУ_А", "ГОРЕ_А"], (
            "второто заустване не е разпознато като изход — "
            f"{[p.id for p in подредени]}")
        assert "заустване" in бележки[0].lower(), бележки


class TestБезСвързаност:
    """Ситуационният чертеж дава клон, диаметър и дължина, но не и възли."""

    def test_редът_е_по_диаметър_низходящо(self):
        пакети = [_канал("S", 300), _канал("L", 1000), _канал("M", 600)]

        подредени, бележки = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["L", "M", "S"], (
            "без възли редът не следва диаметъра — "
            f"{[p.id for p in подредени]}")
        assert "по диаметър" in бележки[0], бележки

    def test_диаметърът_се_чете_и_от_редовете_на_пакета(self):
        без_dn = SpatialWorkPackage(
            id="X", network="К", chain="sewer_section", name="Кл.X",
            items=(PackageItem(source_ref="СПЕЦ!X", activity_class="laying",
                               quantity=50.0, unit="м", dn=1000),))
        подредени, _ = order_sewer_by_flow([_канал("Y", 400), без_dn])

        assert [p.id for p in подредени] == ["X", "Y"], (
            "диаметърът от редовете на пакета не се брои")


class TestДругитеВеригиНеСеПипат:
    def test_водопроводните_пакети_си_остават_по_местата(self):
        пакети = [_канал("K1", 300), _вода("V1", 200),
                  _канал("K2", 800), _вода("V2", 100)]

        подредени, _ = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["K2", "V1", "K1", "V2"], (
            "пренареждането на канала размести и другите вериги — "
            f"{[p.id for p in подредени]}")

    def test_един_канализационен_пакет_не_се_пипа(self):
        пакети = [_канал("K1", 300), _вода("V1", 200)]

        подредени, бележки = order_sewer_by_flow(пакети)

        assert [p.id for p in подредени] == ["K1", "V1"]
        assert not бележки, "обявен е ред там, където няма какво да се реди"
