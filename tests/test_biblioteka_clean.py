def test_обработката_отделя_чистото_от_за_преглед():
    библиотека = {"операции": [
        {"операция": "Изкоп", "ключ": "изкоп", "знаци": 40,
         "текст": "Изкопът се извършва механизирано с багер."},
        {"операция": "Трасиране", "ключ": "трасиране", "знаци": 40,
         "текст": "Трасето се отлага в гр. Севлиево по одобрен проект."},
    ]}
    р = обработи(библиотека)
    статуси = [з["статус"] for з in р["операции"]]
    assert статуси == ["чисто", "за_преглед"]
    assert р["обобщение"]["чисти"] == 1
    assert р["обобщение"]["за_преглед"] == 1
    # Обозначеният текст е готов за попълване от човек, не изтрит.
    assert "{НАСЕЛЕНО_МЯСТО}" in р["операции"][1]["текст_обозначен"]


def test_находките_се_описват_а_не_само_броят():
    библиотека = {"операции": [
        {"операция": "Т", "ключ": "т", "знаци": 20,
         "текст": "по ул. „Балчо Нейков“ в гр. Русе"},
    ]}
    р = обработи(библиотека)
    видове = {н["вид"] for н in р["операции"][0]["находки"]}
    assert "улица" in видове and "населено място" in видове
