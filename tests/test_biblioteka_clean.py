from tools.biblioteka_clean import (  # noqa: E402
    ОБЩИ_В_КАВИЧКИ, _обектно_ли_е, обработи, почисти)


def _видове(текст: str) -> set[str]:
    _, находки = почисти(текст)
    return {н["вид"] for н in находки}


# ---------------------------------------------------------------------------
# Хваща се това, което издава чуждия обект
# ---------------------------------------------------------------------------

def test_съоръжението_с_име_се_хваща():
    """Точният низ, с който започна цялата проверка."""
    текст = ('реконструкция на водопровод Ø100 етернит от ПС „Образцов Чифлик“ '
             'до НКР „Образцов Чифлик“')
    изход, находки = почисти(текст)
    assert находки
    assert "Образцов" not in изход
    assert "{СЪОРЪЖЕНИЕ}" in изход


def test_населено_място_и_община():
    assert "населено място" in _видове("трасето минава през гр. Севлиево")
    assert "община" in _видове("възложител е община Харманли")


def test_улица_и_квартал():
    assert "улица" in _видове("по ул. „Балчо Нейков“ до кръстовището")
    assert "улица" in _видове("в кв. Колхида")


def test_размери_и_дати_също_са_обектни():
    assert "размер" in _видове("тръби Ø160 ПЕВП")
    assert "дата" in _видове("подписан на 03.03.2025 г.")


def test_заглавието_на_процедура_се_хваща():
    текст = '„Реконструкция и доизграждане на вътрешна водопроводна мрежа“'
    изход, находки = почисти(текст)
    assert находки and "{ОБЕКТ}" in изход


