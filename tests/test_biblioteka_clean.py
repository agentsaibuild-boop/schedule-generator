def test_проектните_части_не_са_обектни():
    """233× „Водоснабдяване“ и 107× „Геодезия“ са имена на части, не на обекти."""
    for част in ("„Водоснабдяване“", "„Геодезия“", "„Конструктивна“",
                 "„ПБЗ“", "„ПУСО“", "„Сметна документация“"):
        assert not _обектно_ли_е(част), част
        assert "име в кавички" not in _видове(f"проект по част {част}")


def test_ролите_по_договор_не_са_обектни():
    for роля in ("„Възложителя“", "„Изпълнителя“", "„Инженера“"):
        assert not _обектно_ли_е(роля), роля


def test_името_на_възложителя_нарочно_НЕ_е_в_белия_списък():
    """„Водоснабдяване и канализация“ ООД – <град> е възложител, не част."""
    assert "водоснабдяване и канализация" not in ОБЩИ_В_КАВИЧКИ
    assert _обектно_ли_е("„Водоснабдяване и канализация“")


def test_чист_технологичен_текст_остава_недокоснат():
    текст = ("Изкопът се извършва механизирано с багер, като последните 20 см "
             "се доизкопават ръчно за запазване на основата.")
    изход, находки = почисти(текст)
    assert not находки
    assert изход == текст


