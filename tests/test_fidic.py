def test_стойността_на_процедурата_надделява(tmp_path):
    """ССД е 365 по общите условия; ако процедурата каже 730, важи 730.

    Условието носи РАЗЛИЧЕН номер на двете места: 11.1 в общите условия и
    1.1.27 в приложението (така го дава и Свиленград).  Без връзката между
    двата номера прочетената стойност не надделява — точно това пропуснах в
    първата версия.
    """
    п = _процедура(tmp_path, [
        ["Под-Клауза", "Данни за попълване", "Данни"],
        ["1.1.27", "Срок за съобщаване на дефекти (ССД):", "730 дни"],
    ])
    по_клауза = {и["клауза"]: и for и in intervals(п)["интервали"]}
    ссд = по_клауза["11.1"]
    assert ссд["дни"] == 730, "стойността на процедурата бие общите условия"
    assert ссд["източник"] == "процедурата"
    assert ссд["потвърдено_срещу_документ"] is True


def test_общите_условия_се_маркират_като_непроверени(tmp_path):
    п = _процедура(tmp_path, [["Под-Клауза", "Данни за попълване", "Данни"]])
    данни = intervals(п)
    assert данни["книга"] == "жълта"
    от_общите = [и for и in данни["интервали"]
                 if и["източник"] == "общи условия"]
    assert от_общите, "жълтата книга има интервали"
    assert all(not и["потвърдено_срещу_документ"] for и in от_общите)
    assert any("НЕ са сверени" in б for б in данни["бележки"])


def test_описанието_разделя_прочетеното_от_приетото(tmp_path):
    п = _процедура(tmp_path, [["Под-Клауза", "Данни за попълване", "Данни"]])
    текст = "\n".join(describe(intervals(п)))
    assert "общи условия" in текст
    assert "непроверено срещу твоите документи" in текст


def test_не_фидик_не_връща_интервали(tmp_path):
    d = docx.Document()
    d.add_paragraph("Договор по ЗОП, без договорни условия на международна форма.")
    d.save(str(tmp_path / "Договор.docx"))
    данни = intervals(tmp_path)
    assert данни["интервали"] == []
    assert "не е разпозната" in данни["бележки"][0]


