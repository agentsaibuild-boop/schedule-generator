"""Договорните интервали по FIDIC: прочетени → показани → чак после ползвани.

FAILURE означава: src/fidic.py е счупен — или процедура по FIDIC не се
разпознава (тогава договорните интервали не влизат и графикът пропуска седмици
чакане, които реално съществуват), или обратното: стойност от ОБЩИТЕ УСЛОВИЯ
минава за прочетена от документите на процедурата.

Изпълнителят, 01.09.2026: „За FIDIC четеш внимателно процедурата и изкарваш на
човека събраната информация; ако има корекции, той ще ти каже, иначе приемаш
указанията от тръжната документация и/или общите условия на FIDIC (в съответния
цвят) за основни."

Оттам следват трите правила, които тестовете пазят:
  * стойност от приложението на ПРОЦЕДУРАТА надделява над общите условия;
  * стойност от общите условия се маркира като непроверена и се ПОКАЗВА;
  * книгата се РАЗПОЗНАВА (жълта за инженеринг, червена за чужд проект), а не
    се приема — интервалите им се различават.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.fidic import describe, detect_book, intervals  # noqa: E402

docx = pytest.importorskip("docx", reason="python-docx липсва")


def _процедура(tmp_path: Path, редове: list[list[str]]) -> Path:
    d = docx.Document()
    d.add_paragraph("Договорни условия FIDIC за проектиране и строителство.")
    t = d.add_table(rows=len(редове), cols=3)
    for i, ред in enumerate(редове):
        for j, к in enumerate(ред):
            t.rows[i].cells[j].text = к
    d.save(str(tmp_path / "Специфични условия.docx"))
    return tmp_path


