def test_жълтата_книга_по_изричен_текст():
    книга, как = detect_book("FIDIC Жълта книга, Под-Клауза 8.1")
    assert книга == "жълта" and "думите" in как


def test_червената_книга_не_се_бърка_с_жълтата():
    книга, _ = detect_book("FIDIC Червена книга — Construction, Под-Клауза 4.2")
    assert книга == "червена"


def test_инженерингът_дава_жълта_но_се_КАЗВА_че_цветът_не_е_изписан():
    книга, как = detect_book(
        "Инженеринг (проектиране, авторски надзор и строителство). Под-Клауза 1.1")
    assert книга == "жълта"
    assert "НЕ е изписан" in как, "догадката трябва да се обявява като догадка"


def test_процедура_без_фидик_не_се_обявява_за_фидик():
    assert detect_book("Обикновена документация по ЗОП") == ("", "")


