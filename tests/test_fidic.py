def test_всички_стойности_в_конфига_са_обявени_за_непроверени():
    """Числата в config/fidic.json са по общите условия, не от документ."""
    cfg = json.loads((Path(__file__).parent.parent / "config" / "fidic.json")
                     .read_text(encoding="utf-8"))
    assert cfg["интервали"]
    assert all(not и["потвърдено_срещу_документ"] for и in cfg["интервали"])
    assert all(и.get("мени_графика") for и in cfg["интервали"]), (
        "всеки интервал казва КАК мени графика — иначе не му е мястото тук")
