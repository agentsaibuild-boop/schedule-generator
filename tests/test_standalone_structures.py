def test_a_structure_is_not_split_across_batches():
    """Една осма от шахта не е нищо на обекта — само осемкратен под от ден."""
    по = _по_вериги([ТРАСЕ, _Ред("Преливна шахта", 1.0)], етапи=8)

    съоръжения = по["structure"]
    assert len(съоръжения) == 1
    assert съоръжения[0]["items"][0]["quantity"] == 1.0


def test_the_route_is_still_split_into_batches():
    по = _по_вериги([ТРАСЕ, _Ред("Преливна шахта", 1.0)], етапи=8)

    assert len(по["sewer_section"]) == 8


def test_the_sum_still_equals_the_boq():
    """Изнасянето на съоръженията не бива да губи количество."""
    редове = [ТРАСЕ, _Ред("Преливна шахта", 1.0), _Ред("УО единичен", 100.0)]

    пакети = allocate_execution_batches(редове, 8)["packages"]
    сбор: dict[str, float] = {}
    for p in пакети:
        for i in p["items"]:
            сбор[i["source_ref"]] = сбор.get(i["source_ref"], 0.0) + i["quantity"]

    for ред in редове:
        assert сбор[str(ред.ref)] == pytest.approx(ред.quantity, abs=1e-6)


