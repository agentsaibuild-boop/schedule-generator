"""Съоръженията ги прави ОТДЕЛЕН екип, успоредно на трасето.

FAILURE означава: или шахтите пак ще държат заета бригадата, която полага
тръбите, или уличният отток пак ще получи кофраж и армировка.

ДВЕТЕ ГРЕШКИ СА ОГЛЕДАЛНИ и се допуснаха една след друга на 19.08.2026:
  * точковите стояха в стъпката за полагане и ЕДНА преливна шахта, разцепена
    на осемте етапа, изяждаше 8 × 17 = 136 бригадо-дни от екипа на тръбите;
  * после ВСИЧКИ точкови отидоха по веригата за съоръжение и излезе
    „Декофриране дъно, вътрешен кофраж стени — УО двоен".

Разделението идва от еталона: СКО и УО ги няма там като отделни задачи —
правят се в съставната стъпка на участъка — а „Водомерна шахта" стои като
своя задача от 5 работни дни.
"""

from __future__ import annotations

