"""Съоръженията ги прави ОТДЕЛЕН екип, успоредно на трасето.

FAILURE означава: или шахтите пак ще държат заета бригадата, която полага
тръбите, или уличният отток пак ще получи кофраж и армировка.

ДВЕТЕ ГРЕШКИ СА ОГЛЕДАЛНИ и се допуснаха една след друга на 19.08.2026:
  * точковите стояха в стъпката за полагане и ЕДНА преливна шахта, разцепена
    на осемте етапа, изяждаше 8 × 17 = 136 бригадо-дни от екипа на тръбите;
  * после ВСИЧКИ точкови отидоха по веригата за съоръжение и излезе
    „Декофриране дъно, вътрешен кофраж стени — УО двоен".

Разделението идва от еталона: СКО и УО ги няма там като отделни задачи —
правят се в съставната стъпка на участъка — а „Водомерна шахта" стои като
своя задача от 5 работни дни.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.execution_batches import allocate_execution_batches  # noqa: E402


class _Ред:
    def __init__(self, описание, количество, мярка="брой", ref=None):
        self.description = описание
        self.quantity = количество
        self.unit = мярка
        self.ref = ref or f"КСС!Kanalizaciya!{abs(hash(описание)) % 90 + 4}"


ТРАСЕ = _Ред("Изграждане на смесена канализационна мрежа", 1182.0, "m")


def _по_вериги(редове, етапи=8):
    пакети = allocate_execution_batches(редове, етапи)["packages"]
    по = {}
    for p in пакети:
        по.setdefault(p["chain"], []).append(p)
    return по


# ---------------------------------------------------------------------------
# Кое отива при отделния екип
# ---------------------------------------------------------------------------


@pytest.mark.parametrize("описание", [
    "Преливна шахта",
    "Индивидуална монолитна РШ",
    "Водомерна шахта",
])
def test_a_cast_in_place_structure_gets_its_own_package(описание):
    по = _по_вериги([ТРАСЕ, _Ред(описание, 1.0)])

    съоръжения = по.get("structure") or []
    assert len(съоръжения) == 1, f"{описание} не отиде при отделния екип"
    assert съоръжения[0]["name"] == описание


@pytest.mark.parametrize("описание,количество", [
    ("СКО смесена канализационна мрежа", 180.0),
    ("УО единичен", 100.0),
    ("УО двоен", 60.0),
])
def test_route_connections_stay_with_the_pipe_crew(описание, количество):
    """Еталонът ги прави в съставната стъпка на участъка, не в кофраж."""
    по = _по_вериги([ТРАСЕ, _Ред(описание, количество)])

    assert "structure" not in по, f"{описание} получи верига за съоръжение"


