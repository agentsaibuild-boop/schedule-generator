from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.deadline_pace import (  # noqa: E402
    ДОКАЗАНО_ТЕМПО, _какво_да_се_смени, feasibility)


def test_темпо_в_диапазона_е_изпълнимо():
    присъда, _ = feasibility("water_section", 6.0)
    assert присъда == "FEASIBLE"


def test_на_самата_граница_още_е_изпълнимо():
    присъда, _ = feasibility("water_section", ДОКАЗАНО_ТЕМПО["p75"])
    assert присъда == "FEASIBLE"


def test_над_75_ия_персентил_иска_надбавка():
    присъда, обяснение = feasibility("water_section", 12.0)
    assert присъда == "REQUIRES_UPLIFT"
    assert "над медианата" in обяснение


def test_над_наблюдавания_връх_не_се_подкрепя_от_данните():
    присъда, обяснение = feasibility("sewer_section", 23.24)
    assert присъда == "NOT_SUPPORTED_BY_DATA"
    assert "14.4" in обяснение
    # Числото на надбавката е ЧАСТ ОТ ПРИСЪДАТА, не украса.
    assert "%" in обяснение


def test_казва_се_и_какво_трябва_да_се_смени():
    """Присъда без изход е оплакване; одиторът иска да се каже какво помага."""
    съвет = _какво_да_се_смени(4184.0, 90, 2)
    assert "екипа повече" in съвет
    assert "дни вместо 90" in съвет
    assert "метод" in съвет


def test_когато_екипите_стигат_съветът_не_иска_още():
    съвет = _какво_да_се_смени(1000.0, 210, 5)
    assert "екипа повече" not in съвет


def test_границите_са_подредени():
    assert (ДОКАЗАНО_ТЕМПО["p25"] < ДОКАЗАНО_ТЕМПО["median"]
            < ДОКАЗАНО_ТЕМПО["p75"] < ДОКАЗАНО_ТЕМПО["max"])
    assert ДОКАЗАНО_ТЕМПО["_източник"]
