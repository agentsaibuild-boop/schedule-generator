"""Старият двоичен Word се чете — включително таблиците в него.

Тръжните документи в България масово са `.doc`.  Проба 24.08.2026: в „ВиК
Хасково — Харманли довеждащ" ЦЯЛАТА техническа спецификация е един `.doc` от
649 KB, и количеството в нея е ЕДИНСТВЕНИЯТ вход за графика.  Приложението не
само не можеше да го прочете — `.doc` дори не беше сред поддържаните
разширения, тоест файлът не се и виждаше.

Тук се проверява НАЙ-КРЕХКОТО: превръщането на текстовия поток в таблици.
Разчитането на самия OLE контейнер и на заглавния блок е измерено срещу
истинския документ (758 абзаца, 86 101 знака чиста кирилица) — тук се пазят
правилата, които се извеждат трудно и се чупят лесно.

FAILURE означава: количествената таблица в `.doc` пак ще излиза с нула реда, а
приложението ще казва „няма количества" при документ, който ги съдържа.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.doc_reader import (  # noqa: E402
    DocError,
    _без_полета,
    _области_с_таблици,
    _разбор,
    _таблица_от_област,
    read_doc,
)

#: ТОЧНО потокът от истинската спецификация на Харманли, знак по знак.
#: „Диаметър⏎Ф /mm/⏎" е ЕДНА клетка на два реда; редът се затваря от ПРАЗНА
#: клетка (\x07\x07).
_ХАРМАНЛИ = (
    "О НА ВОДОПРОВОДНА МРЕЖА И СЪОРЪЖЕНИЯ:  \r"
    "Водопроводна мрежа\x07Ед. мярка\x07\rДиаметър\rФ /mm/\r\x07"
    "Дължина\rL /m/\x07\x07"
    "Главни водопроводни клонове\x07m\x07300\x07673,09\x07\x07"
    "Общо дължина на водопроводна мрежа: \r673,09 m (без СВО)\r\x07\x07"
    "\r\r2.3 МЕСТОПОЛОЖЕНИЕ\rДейностите ще се извършват на територията.\r"
)


# ---------------------------------------------------------------------------
# 1. Таблицата от истинската спецификация
# ---------------------------------------------------------------------------

def test_the_quantity_table_comes_out_whole():
    _, таблици = _разбор(_ХАРМАНЛИ)

    assert len(таблици) == 1
    assert таблици[0]["headers"] == [
        "Водопроводна мрежа", "Ед. мярка", "Диаметър Ф /mm/", "Дължина L /m/"]


def test_the_quantity_row_is_read():
    _, таблици = _разбор(_ХАРМАНЛИ)
    ред = таблици[0]["rows"][0]

    assert ред["Водопроводна мрежа"] == "Главни водопроводни клонове"
    assert ред["Ед. мярка"] == "m"
    assert ред["Диаметър Ф /mm/"] == "300"
    assert ред["Дължина L /m/"] == "673,09"


def test_a_multiline_cell_stays_one_cell():
    """„Диаметър⏎Ф /mm/" е едно заглавие, не два реда от таблицата.

    Абзацният знак ВЪТРЕ в клетка беше причината таблицата да се разпадне:
    първият разбор я връщаше с нула реда.
    """
    _, таблици = _разбор(_ХАРМАНЛИ)

    assert "Диаметър Ф /mm/" in таблици[0]["headers"]
    assert len(таблици[0]["headers"]) == 4


def test_body_text_around_the_table_stays_paragraphs():
    абзаци, _ = _разбор(_ХАРМАНЛИ)

    assert "2.3 МЕСТОПОЛОЖЕНИЕ" in абзаци
    assert any("ВОДОПРОВОДНА МРЕЖА И СЪОРЪЖЕНИЯ" in а for а in абзаци)
    assert not any("Главни водопроводни клонове" in а for а in абзаци), \
        "клетка от таблица не бива да минава за абзац"


# ---------------------------------------------------------------------------
# 2. Къде свършва една таблица и започва следващата
# ---------------------------------------------------------------------------

def test_two_tables_separated_by_body_text_are_two():
    """Между таблици стои проза с МНОГО абзаца — това ги дели."""
    проза = "\r".join(f"Абзац номер {i} с достатъчно текст." for i in range(20))
    текст = f"А\x07Б\x07\x07{проза}\rВ\x07Г\x07\x07"

    _, таблици = _разбор(текст)

    assert len(таблици) == 2


def test_a_long_single_paragraph_cell_does_not_split_the_table():
    """Дълга клетка без вътрешни абзаци си остава част от таблицата.

    ИЗМЕРЕНО: истинските междини между таблици носят 20 и повече абзаца, а
    дълга клетка — нула или един.  Затова дели БРОЯТ НА АБЗАЦИТЕ, не
    дължината: клетка с дълго изречение стига 924 знака.
    """
    дълга = "Много дълго изречение в една клетка. " * 20
    текст = f"Заглавие\x07{дълга}\x07\x07Ред\x07Стойност\x07\x07"

    _, таблици = _разбор(текст)

    assert len(таблици) == 1
    assert len(таблици[0]["rows"]) == 1


def test_a_document_without_tables_gives_only_paragraphs():
    абзаци, таблици = _разбор("Първи абзац.\rВтори абзац.\r")

    assert абзаци == ["Първи абзац.", "Втори абзац."]
    assert таблици == []
    assert _области_с_таблици("няма нито един знак за клетка") == []


