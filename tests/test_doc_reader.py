def test_an_empty_cell_closes_the_row():
    таблица = _таблица_от_област("А\x07Б\x07\x07В\x07Г\x07\x07")

    assert таблица["headers"] == ["А", "Б"]
    assert таблица["rows"] == [{"А": "В", "Б": "Г"}]


def test_field_codes_are_dropped_but_their_result_is_kept():
    """Между 0x13 и 0x14 стои КОДЪТ, а между 0x14 и 0x15 — видимото."""
    assert _без_полета("Стр. \x13PAGE\x1412\x15 от 20") == "Стр. 12 от 20"


def test_a_file_that_is_not_a_doc_says_so(tmp_path: Path):
    подправен = tmp_path / "не-е.doc"
    подправен.write_bytes(b"PK\x03\x04 this is a zip, not OLE")

    with pytest.raises(DocError):
        read_doc(подправен)


def test_a_missing_file_raises(tmp_path: Path):
    with pytest.raises((DocError, OSError)):
        read_doc(tmp_path / "няма.doc")
