def test_сценариите_спират_на_първия_излишен_екип(tmp_path):
    данни = {"срокове": [{"фаза": "construction", "дни": 500}],
             "метри": {"водопровод": 6500.0}}
    редове = crew_scenarios(данни)
    assert "1 екип →" in редове[1]
    assert редове[-1].endswith("(в повече)")
    assert len(редове) <= 6, "таблица, която не спира, става шум"


def test_без_метри_няма_сценарии():
    assert crew_scenarios({"срокове": [], "метри": {}}) == []
