def test_срок_за_одобряване_не_е_срок_на_фазата(tmp_path):
    текст = ("В срока за изготвяне на технически проект не се включва срокът "
             "за разглеждането и одобряването му от Възложителя до 30 дни.")
    assert read_terms(_проект(tmp_path, текст)) == []


def test_почистването_не_е_срок_на_строителството(tmp_path):
    текст = ("Окончателното почистване на работния район следва да стане в "
             "срок до 5 дни от приключване на строителството.")
    assert read_terms(_проект(tmp_path, текст)) == []


def test_липсата_се_казва(tmp_path):
    """Свиленград: сроковете са в обявлението, не в спецификацията."""
    текст = "Техническа спецификация без обявени срокове за изпълнение."
    данни = brief(_проект(tmp_path, текст))
    редове = describe(данни)
    assert "НЕ извадих срокове" in редове[0]


