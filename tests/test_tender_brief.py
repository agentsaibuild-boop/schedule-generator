"""Каквото пише в търга се ПОКАЗВА, преди човекът да бъде питан.

FAILURE означава: src/tender_brief.py е счупен — или сроковете не се вадят от
документацията (тогава въпросникът пак пита на сляпо и кара човека да отвори
документ, който вече сме прочели), или вади ГРЕШНИ числа, което е по-лошо от
нищо: човек, който вижда потвърждение, спира да проверява.

Мерилото са три реални процедури:

    Карлово      ПИП 30 (мин. 10) · ПУП 30 (мин. 10) · проект 60 (мин. 20) ·
                 СМР 500 (мин. 365) · надзорът е през целия срок на СМР ·
                 излизане извън границите ДИСКВАЛИФИЦИРА
    Илиянци      проектиране 120 · строителство 660
    Свиленград   в спецификацията НЯМА срокове (19 месеца са в обявлението) —
                 честният отговор е „не извадих", не измислено число
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

from src.tender_brief import (  # noqa: E402
    brief, crew_scenarios, describe, read_terms)


def _проект(tmp_path: Path, текст: str) -> Path:
    (tmp_path / "converted").mkdir(exist_ok=True)
    (tmp_path / "converted" / "Документация.json").write_text(
        json.dumps({"source_file": "Документация.docx", "type": "docx",
                    "full_text": текст}, ensure_ascii=False), encoding="utf-8")
    return tmp_path


КАРЛОВО = (
    "Срокът за извършване на ПИП е до 30 (тридесет) календарни дни, но не "
    "по-малко от 10 (десет) календарни дни, от датата на получаване на "
    "Възлагателно писмо. "
    "Срокът за изготвяне на технически проект е до 60 (шестдесет) календарни "
    "дни, но не по-малко от 20 (двадесет) календарни дни. "
    "Срок за изпълнение на строително-монтажните работи е до 500 (петстотин) "
    "календарни дни, но не по-малко от 365 (триста шестдесет и пет) "
    "календарни дни. "
    "Срокът за осъществяване на авторски надзор е през целия срок за "
    "изпълнение на строително-монтажните работи. "
    "ВАЖНО! В случай че участник предложи срок по-дълъг от посочения, "
    "участникът ще бъде отстранен от участие."
)


# ---------------------------------------------------------------------------
# Числата се вадят вярно
# ---------------------------------------------------------------------------

def test_таванът_и_подът_се_вадят(tmp_path):
    срокове = {с["фаза"]: с for с in read_terms(_проект(tmp_path, КАРЛОВО))}
    assert срокове["construction"]["дни"] == 500
    assert срокове["construction"]["минимум"] == 365
    assert срокове["design"]["дни"] == 60
    assert срокове["design"]["минимум"] == 20
    assert срокове["pip"]["дни"] == 30


def test_дисквалификацията_се_обявява(tmp_path):
    срокове = read_terms(_проект(tmp_path, КАРЛОВО))
    assert all(с["дисквалификация"] for с in срокове if с.get("дни"))
    текст = " ".join(describe({"срокове": срокове}))
    assert "ДИСКВАЛИФИЦИРА" in текст


def test_надзорът_следва_строителството_а_не_свой_брой(tmp_path):
    срокове = {с["фаза"]: с for с in read_terms(_проект(tmp_path, КАРЛОВО))}
    надзор = срокове["supervision"]
    assert надзор["дни"] is None
    assert "целия срок" in надзор["следва"]


def test_продължителност_след_името_на_фазата(tmp_path):
    """Илиянци пише „ЕТАП ПРОЕКТИРАНЕ Продължителност – 120 календарни дни"."""
    текст = ('1. ЕТАП „ПРОЕКТИРАНЕ" Продължителност 120 календарни дни. '
             '6. СТРОИТЕЛСТВО Продължителност 660 календарни дни.')
    срокове = {с["фаза"]: с["дни"] for с in read_terms(_проект(tmp_path, текст))}
    assert срокове["design"] == 120
    assert срокове["construction"] == 660


