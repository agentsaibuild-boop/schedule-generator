# -*- coding: utf-8 -*-
"""Защо тази задача е на ТОЗИ ден — записано на самата задача.

ЗАЩО.  Одиторът, 31.08.2026, за следващия истински въпрос:

    „Може ли за всяка съществена задача да обясни защо е там, защо трае толкова
     и какви ресурси са необходими — преди да я напасне към договорния срок?"

„Защо трае толкова" вече има отговор — `src/duration_evidence.py`.  „Защо е
там" нямаше: графикът казваше в едро „210 задачи отложени до свободен ресурс",
а на въпрос „защо тази дейност е чак на ден 180" се отговаряше на ръка.

КАК СЕ РЕШАВА.  За всяка задача се смята най-ранното начало, което мрежата
допуска, и се сравнява с действителното:

    начало == най-ранното от мрежата   → държи я ЗАВИСИМОСТ (и коя)
    начало >  най-ранното от мрежата   → държи я нещо друго:
                                          екипът ѝ е бил зает, или ресурс е
                                          бил на тавана си
    няма предшественици, начало == 1   → нищо не я държи

Разликата „екип" срещу „ресурс" не е козметична: първото значи, че решението е
организационно (повече бригади), второто — че опира в техника или хора, които
се делят между бригадите.  Двете се поправят различно.

ЧЕСТНОСТТА Е В `UNEXPLAINED`.  Когато нито едно от горните не обяснява дните,
това се казва, вместо да се избере най-правдоподобната причина.  Необяснено
изместване е дефект в конвейера и трябва да се вижда.
"""

from __future__ import annotations

from typing import Any, Iterable

#: Причините, подредени по това колко силно държат задачата.
ПРИЧИНИ: tuple[str, ...] = (
    "CONTRACT_PHASE",      # закована за договорна фаза (надзор, приемане)
    "PHASE_START",         # първа в своята фаза — фазата започва тогава
    "CHAIN_PREDECESSOR",   # технологичната верига
    "CREW_QUEUE",          # екипът ѝ е бил зает
    "RESOURCE_LEVELLED",   # ресурс на тавана си
    "UNEXPLAINED",         # изместена, без да знаем от какво
    "NO_CONSTRAINT",       # нищо не я държи
)

ОБЯСНЕНИЕ = {
    "CONTRACT_PHASE": "закована за договорна фаза",
    "PHASE_START": "първа в своята фаза — фазата започва тогава",
    "CHAIN_PREDECESSOR": "чака предходната стъпка от веригата",
    "CREW_QUEUE": "екипът ѝ е бил зает до този ден",
    "RESOURCE_LEVELLED": "ресурс е бил на тавана си",
    "UNEXPLAINED": "изместена, без обяснение от мрежата — вижте я",
    "NO_CONSTRAINT": "нищо не я държи, започва възможно най-рано",
}


def _цяло(стойност: Any) -> int | None:
    if стойност is None:
        return None
    try:
        return int(стойност)
    except (TypeError, ValueError):
        return None


def _начало(task: dict) -> int | None:
    return _цяло(task.get("start_day"))


def _край(task: dict) -> int | None:
    return _цяло(task.get("end_day"))


def _екип(task: dict) -> str:
    return str(task.get("team") or task.get("crew_id") or "").strip()


def explain(tasks: Iterable[dict]) -> list[str]:
    """Записва `placement_reason` и `placement_detail` на всяка листна задача."""
    tasks = list(tasks or [])
    по_ид = {str(t.get("id")): t for t in tasks}
    листа = [t for t in tasks
             if not t.get("is_summary") and _начало(t) is not None]
    if not листа:
        return []

    начало_на_проекта = min(_начало(t) for t in листа)

    #: Кога започва всяка фаза — първата ѝ задача не чака, тя ОТКРИВА фазата.
    начало_по_фаза: dict[str, int] = {}
    for t in листа:
        ф = str(t.get("wbs_root") or "")
        н = _начало(t)
        if ф and (ф not in начало_по_фаза or н < начало_по_фаза[ф]):
            начало_по_фаза[ф] = н

    #: Кой ден кой екип е зает — за да се различи „чакам своя екип" от
    #: „чакам ресурс, който се дели с други бригади".
    зает: dict[str, set[int]] = {}
    for t in листа:
        е = _екип(t)
        if not е:
            continue
        зает.setdefault(е, set()).update(
            range(_начало(t), (_край(t) or _начало(t)) + 1))

    брой: dict[str, int] = {}
    for task in листа:
        най_рано = начало_на_проекта
        двигател = None
        for dep in (task.get("dependencies") or []):
            ид = str(dep.get("predecessor_id") if isinstance(dep, dict) else dep)
            pred = по_ид.get(ид)
            if pred is None or _начало(pred) is None:
                continue
            лаг = int(dep.get("lag_days", 0)) if isinstance(dep, dict) else 0
            вид = ((dep.get("type") if isinstance(dep, dict) else "FS")
                   or "FS").upper()
            готово = (_начало(pred) + лаг if вид == "SS"
                      else (_край(pred) or _начало(pred)) + лаг + 1)
            if готово > най_рано:
                най_рано, двигател = готово, pred

        действително = _начало(task)
        задържане = действително - най_рано

        #: НАЧАЛОТО НА ФАЗАТА не е закъснение.  Първата задача на всеки екип
        #: („Въвеждане на ВОБД, отлагане на трасето") няма предшественик и
        #: започва на ден 46, защото строителството тръгва след проектирането.
        #: Първата версия ги обяви за 11 необяснени задачи с 495 дни — числото
        #: беше вярно спрямо ден 1, но въпросът беше грешен.
        фаза = str(task.get("wbs_root") or "")
        начало_на_фазата = начало_по_фаза.get(фаза, начало_на_проекта)

        if str(task.get("duration_source") or "") == "construction_span":
            причина = "CONTRACT_PHASE"
            детайл = "разтегната върху договорната фаза"
        elif задържане <= 0 and двигател is not None:
            причина = "CHAIN_PREDECESSOR"
            детайл = (f"след „{str(двигател.get('name'))[:60]}“ "
                      f"(ден {_край(двигател)})")
        elif задържане <= 0:
            причина = "NO_CONSTRAINT"
            детайл = "няма предшественик, започва с обекта"
        elif двигател is None and действително == начало_на_фазата:
            причина = "PHASE_START"
            детайл = (f"фаза „{фаза}“ започва на ден {начало_на_фазата}")
        else:
            е = _екип(task)
            дни_на_екипа = зает.get(е, set())
            # Ако екипът ѝ е бил зает през ЦЕЛИЯ пропуск, той я е държал.
            пропуск = range(най_рано, действително)
            ако_екипът = bool(е) and all(д in дни_на_екипа for д in пропуск)
            if ако_екипът:
                причина = "CREW_QUEUE"
                детайл = f"екип {е} е бил зает {задържане} дни"
            elif task.get("leveled") or task.get("resource_shifted"):
                причина = "RESOURCE_LEVELLED"
                детайл = f"изравняване по ресурс, {задържане} дни"
            else:
                причина = "UNEXPLAINED"
                детайл = (f"{задържане} дни след най-ранното, което мрежата "
                          f"допуска — причината не е записана")
        task["placement_reason"] = причина
        task["placement_detail"] = детайл
        # Началото на фазата НЕ е изчакване — да се брои като такова значеше
        # „495 дни изгубени" за 11 задачи, които просто откриват строителството.
        if задържане > 0 and причина not in ("PHASE_START", "CONTRACT_PHASE"):
            task["placement_delay_days"] = задържане
        брой[причина] = брой.get(причина, 0) + 1

    редове = [f"{ОБЯСНЕНИЕ[п]}: {брой[п]}" for п in ПРИЧИНИ if брой.get(п)]
    бележки = [f"Защо е там — {'; '.join(редове)}."]
    if брой.get("UNEXPLAINED"):
        бележки.append(
            f"ВНИМАНИЕ: {брой['UNEXPLAINED']} задачи са изместени без обяснение "
            f"от мрежата.  Това е дефект в конвейера, не свойство на графика.")
    return бележки


def report(tasks: Iterable[dict]) -> dict:
    """Колко задачи и колко изгубени дни стоят на всяка причина."""
    по_причина: dict[str, dict[str, float]] = {}
    for task in tasks or []:
        if task.get("is_summary"):
            continue
        причина = str(task.get("placement_reason") or "")
        if not причина:
            continue
        клетка = по_причина.setdefault(причина, {"задачи": 0, "дни": 0})
        клетка["задачи"] += 1
        клетка["дни"] += int(task.get("placement_delay_days") or 0)
    return {"по_причина": {п: по_причина[п] for п in ПРИЧИНИ
                           if п in по_причина},
            "задачи": sum(к["задачи"] for к in по_причина.values())}


def describe(отчет: dict) -> list[str]:
    редове = [f"ЗАЩО Е ТАМ ({отчет['задачи']} задачи):"]
    for причина, клетка in отчет["по_причина"].items():
        дни = (f"  {клетка['дни']:.0f} дни изчакване"
               if клетка["дни"] else "")
        редове.append(f"  {причина:<20}{клетка['задачи']:>5} задачи{дни}"
                      f"   {ОБЯСНЕНИЕ[причина]}")
    return редове
