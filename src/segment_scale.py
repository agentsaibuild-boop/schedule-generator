#: Фази, чиято продължителност НЕ се пипа от това правило.  Надзорът се котви
#: за строителството (`enforce_construction_span`) — разтегли ли се и той сам,
#: двете правила се бият.
_БЕЗ_СРОК = frozenset({"supervision"})

#: Кои НАШИ фази покрива един обявен срок.
#:
#: ПРОВЕРЕНО В ДВАТА ЧОВЕШКИ ГРАФИКА (24.08.2026), защото това реши въпроса:
#:
#:   Илиянци   само ДВЕ фази на върха.  „СТРОИТЕЛСТВО" (03.02.2026–24.11.2027)
#:             съдържа откриването на площадката, мобилизацията, участъците,
#:             окончателното приключване на СМР, демобилизацията и
#:             констативния акт.
#:   Русе      „ЕТАП 4 — СТРОИТЕЛСТВО И АВТОРСКИ НАДЗОР" = обявените 180 дни, и
#:             в него са мобилизацията (дни 72–76), участъците, изпитването,
#:             възстановяването, приключването и актът (ден 250).
#:
#: Тоест обявеният срок за СМР тече от подписването на Протокол Образец 2а до
#: приемането — мобилизацията и приемането НЕ са извън него.  Нашият WBS ги
#: държи като отделни редове (така се четат по-лесно), но СРОКЪТ е един.
#:
#: Фаза със СВОЙ обявен срок се измества от групата и се мери сама.
_ПОКРИТИ_ФАЗИ = {"construction": ("mobilization", "construction", "acceptance")}


def _обхват(задачи: list[dict]) -> tuple[int, int]:
    начала = [int(_num(t.get("start_day"))) for t in задачи if t.get("start_day")]
    краища = [int(_num(t.get("end_day"))) for t in задачи if t.get("end_day")]
    if not начала or not краища:
        return (0, -1)
    return (min(начала), max(краища))


def _отбележи(t: dict, цел: int, стана: int) -> None:
    беше = _num(t.get("duration"))
    if стана == беше:
        return
    t.setdefault("computed_duration", беше)
    t["declared_term_days"] = цел
    t["duration"] = стана


#: Под колко дни разлика вече не се мащабира, а се дошива ден по ден.
#: Множител като 70/68 закръгля до „без промяна" при повечето стъпки и фазата
#: увисва две денонощия под тавана — а правилото е срокът да се ИЗПОЛЗВА.
_ДОШИВАНЕ_ПОД = 6


#: През колко от последните действия се разпределя дошиването на края.
_ОПАШКА = 5

#: Под тази разлика фазата се дошива по КРАЯ, а не пропорционално по сбора.
_ТЪНКО = 15


def _доший_края(задачи: list[dict], недостиг: int) -> int:
    """Удължава ПОСЛЕДНИТЕ действия на фазата, докато стигне обявения край.

    ЗАЩО (Илиянци, 25.08.2026).  Пропорционалното разтягане работи по СБОРА
    на продължителностите, а обхватът се държи от критичния път.  Щом
    участъците вървят в редици на екипи, добавен ден на успореден участък не
    мести края с нищо: фазата увисваше на 650 дни при обявени 660 и повече не
    мърдаше, колкото и итерации да се направят.

    Краят го държат последните действия — тях удължаваме, по едно на ред, за
    да не порасне едно действие безобразно.

    Returns:
        Броят пипнати задачи.
    """
    ако = [t for t in задачи
           if not (t.get("milestone") or t.get("is_milestone"))]
    if not ако or недостиг <= 0:
        return 0
    опашка = sorted(ако, key=lambda t: -int(_num(t.get("end_day")) or 0))[:_ОПАШКА]
    пипнати = set()
    for i in range(недостиг):
        t = опашка[i % len(опашка)]
        t.setdefault("computed_duration", int(_num(t.get("duration"))))
        t["duration"] = int(_num(t.get("duration"))) + 1
        t["declared_term_days"] = True
        пипнати.add(id(t))
    return len(пипнати)


def _отрежи_края(задачи: list[dict], излишък: int) -> int:
    """Скъсява ПОСЛЕДНИТЕ действия на фазата — огледалото на `_доший_края`.

    ЗАЩО (Тръстеник, 25.08.2026).  Проектирането оставаше 46 дни при обявени
    45 и не мърдаше: свиването махаше ден от НАЙ-ДЪЛГАТА стъпка, а тя върви
    успоредно с други и не държи края.  Обхватът се държи от последното
    действие, затова денят се маха ОТТАМ.

    Един ден над обявения максимум прави офертата неотговаряща — това не е
    закръгляне, а разлика между отговаряща и неотговаряща оферта.

    Returns:
        Броят пипнати задачи.
    """
    ако = [t for t in задачи
           if not (t.get("milestone") or t.get("is_milestone"))
           and _num(t.get("duration")) > 1]
    if not ако or излишък <= 0:
        return 0
    опашка = sorted(ако, key=lambda t: -int(_num(t.get("end_day")) or 0))[:_ОПАШКА]
    пипнати = set()
    for i in range(излишък):
        подходящи = [t for t in опашка if _num(t.get("duration")) > 1]
        if not подходящи:
            break
        t = подходящи[i % len(подходящи)]
        t.setdefault("computed_duration", int(_num(t.get("duration"))))
        t["duration"] = int(_num(t.get("duration"))) - 1
        t["declared_term_days"] = True
        пипнати.add(id(t))
    return len(пипнати)


def _разтегли(задачи: list[dict], цел: int, сега: int) -> int:
    """Нагоре: пропорционално при голяма разлика, ден по ден при малка."""
    недостиг = цел - сега
    if 0 < недостиг < _ДОШИВАНЕ_ПОД:
        # Ден по ден, върху най-дългите стъпки: те понасят един ден по-леко
        # от кратките и подредбата на фазата не се изкривява.
        по_дължина = sorted(задачи, key=lambda t: -_num(t.get("duration")))
        for i in range(недостиг):
            if not по_дължина:
                break
            t = по_дължина[i % len(по_дължина)]
            _отбележи(t, цел, int(_num(t.get("duration"))) + 1)
        return min(недостиг, len(по_дължина)) if по_дължина else 0

    # ПРОПОРЦИОНАЛНО, ПОСЛЕ ДЕН ПО ДЕН.  Умножението само по себе си не стига:
    # когато всички стъпки са по ЕДИН ден — а след свиване те са точно такива —
    # `1 × 1.16` се закръгля обратно на 1 и фазата не мърда.  Мерено на Русе:
    # строителството оставаше 155 дни при таван 180, тоест двайсет и пет
    # неизползвани дни при правило „срокът се използва максимално".
    множител = цел / сега
    сбор_преди = sum(_num(t.get("duration")) for t in задачи)
    променени = 0
    for t in задачи:
        беше = _num(t.get("duration"))
        if беше <= 0:
            continue
        стана = max(1, int(round(беше * множител)))
        if стана != беше:
            _отбележи(t, цел, стана)
            променени += 1

    недостигащи = int(round(сбор_преди * множител
                            - sum(_num(t.get("duration")) for t in задачи)))
    подредени = sorted(задачи, key=lambda t: -_num(t.get("duration")))
    i = 0
    while недостигащи > 0 and подредени:
        t = подредени[i % len(подредени)]
        _отбележи(t, цел, int(_num(t.get("duration"))) + 1)
        недостигащи -= 1
        променени += 1
        i += 1
    return променени


def _свий_под(задачи: list[dict], цел: int, сега: int) -> int:
    """Пропорционално НАДОЛУ, със закръгляне ВНИМАТЕЛНО и дошиване.

    Закръглянето по правилата на аритметиката връща 71 дни при обявени 70 —
    един ден над тавана, тоест неотговаряща оферта.  Затова тук се закръглява
    НАДОЛУ, а после, ако е останал излишък, той се маха ден по ден от
    най-дългите стъпки: те понасят един ден по-леко от кратките.

    Подът от един ден остава ненарушим — стъпка, която се извършва, не трае
    нула.
    """
    излишък = сега - цел
    if 0 < излишък < _ДОШИВАНЕ_ПОД:
        # Огледалото на дошиването.  Множител като 70/73 закръгля до „без
        # промяна" при повечето стъпки и фазата остава НАД тавана — а точно
        # това прави офертата неотговаряща.  Затова се маха ден по ден.
        #
        # И то от КРАЯ, не от най-дългата стъпка: обхватът се държи от
        # последното действие, а най-дългата стъпка може да върви успоредно с
        # него и махнатият ѝ ден да не мести нищо (Тръстеник: проектирането
        # застояваше на 46 при обявени 45).  Най-дългите остават резервата,
        # когато опашката вече е на своя под от един ден.
        от_края = _отрежи_края(задачи, излишък)
        if от_края:
            return от_края
        свиваеми = sorted((t for t in задачи if _num(t.get("duration")) > 1),
                          key=lambda t: -_num(t.get("duration")))
        if not свиваеми:
            return 0
        for i in range(излишък):
            t = свиваеми[i % len(свиваеми)]
            беше = int(_num(t.get("duration")))
            if беше > 1:
                _отбележи(t, цел, беше - 1)
        return min(излишък, len(свиваеми))

    # ЗАКРЪГЛЯ СЕ ПО ПРАВИЛАТА, НЕ НАДОЛУ.  Закръглянето надолу изглежда
    # безопасно (никога над тавана), но е ТЪПО острие: при множител 0.74
    # задача от 4 дни става 2, тоест свива се наполовина вместо с четвърт.
    # Мерено на Русе: фаза от 243 дни при таван 180 падаше на 155 — 25 дни
    # НЕизползван срок, което е другата половина на същото правило.
    # Едностранният допуск се пази другаде: при излишък под шест дни се маха
    # ден по ден, а най-доброто съвместимо състояние се помни и се връща.
    множител = цел / сега
    сбор_преди = sum(_num(t.get("duration")) for t in задачи)
    цел_за_сбора = сбор_преди * множител
    променени = 0
    for t in задачи:
        беше = _num(t.get("duration"))
        if беше <= 0:
            continue
        стана = max(1, int(round(беше * множител)))
        if стана != беше:
            _отбележи(t, цел, стана)
            променени += 1

    # ЗАКРЪГЛЯНЕТО НЕ БИВА ДА ОСТАВЯ ФАЗАТА НАД ТАВАНА дори при ЕДИН опит:
    # `round` може да добави ден тук-там и 70 да станат 71.  Излишъкът се маха
    # веднага, от най-дългите стъпки — без ново разписване, защото при верига
    # в редица обхватът следва сбора.
    разлика = int(round(sum(_num(t.get("duration")) for t in задачи)
                        - цел_за_сбора))
    while разлика > 0:
        свиваеми = [t for t in задачи if _num(t.get("duration")) > 1]
        if not свиваеми:
            break
        най_дълга = max(свиваеми, key=lambda t: _num(t.get("duration")))
        _отбележи(най_дълга, цел, int(_num(най_дълга.get("duration"))) - 1)
        разлика -= 1
        променени += 1

    # И ОБРАТНОТО.  Закръглянето губи по малко от всяка стъпка: 25 стъпки по 4
    # дни при множител 0.6 дават 2 вместо 2.4, тоест 50 дни вместо 60 — десет
    # дни неизползван срок.  Връщат се, докато сборът стигне целта; подредбата
    # е по най-дългите, за да не се раздува кратка стъпка.
    while разлика < 0 and задачи:
        най_дълга = max(задачи, key=lambda t: _num(t.get("duration")))
        _отбележи(най_дълга, цел, int(_num(най_дълга.get("duration"))) + 1)
        разлика += 1
        променени += 1
    return променени


def enforce_declared_phase_terms(
    tasks: list[dict],
    packages: Iterable[Any],
    chains: dict,
    разпиши: Any = None,
    *,
    опити: int = 5,
) -> tuple[list[dict], list[str]]:
    """Обявеният в документацията срок на фазата НАДДЕЛЯВА над сметнатия.

    ОСНОВНО ПРАВИЛО (изпълнителят, 24.08.2026): „когато има зададени срокове за
    проектиране, строителство и/или други, трябва да се използват МАКСИМАЛНО.
    Ако проектирането е записано 100 дни, ние в графика го записваме 100 дни."

    ЗАЩО.  Срокът в тръжната документация е таван, който възложителят е обявил
    и приема.  График, който обещава по-малко, поема риск, без да получава
    нищо срещу него — а често и се оценява по-ниско.  Мерено на реален търг
    (ВиК Русе, 24.08.2026): нашето проектиране излизаше 124 дни при обявени
    30 + 40, а строителството 58 при обявени 180.  Човешкият график за същата
    поръчка пише точно 30, 40 и 180.

    И В ДВЕТЕ ПОСОКИ.  Фаза над обявеното се СВИВА (иначе офертата е
    неотговаряща), фаза под обявеното се РАЗТЯГА (иначе поемаме риск без
    насрещна полза).  Пропорционално, за да оцелее вътрешната подредба на
    стъпките; подът от един ден остава ненарушим.

    СМЕТНАТОТО ОСТАВА ВИДИМО.  Всяка пипната задача носи `declared_term_days`
    и `computed_duration`, а бележката казва от какво на какво е станало: това
    е решение за пари и за риск, а не поправка на аритметика.

    Args:
        tasks: Вече РАЗПИСАН график (иска `start_day`/`end_day`).
        packages: Пакетите — от тях се разбира коя задача в коя фаза е.
        chains: `tech_chains`, за `wbs_root` на веригата.
        разпиши: `(задачи) -> задачи` — истинско преразписване след промяната.
            Без него се прави ЕДНА итерация и обхватът остава приблизителен.
        опити: Колко пъти да се мери и коригира.

    Returns:
        (задачи, бележки).
    """
    from src.tender_parameters import declared_phase_days

    обявени = {ф: д for ф, д in (declared_phase_days() or {}).items()
               if ф not in _БЕЗ_СРОК and д > 0}
    if not обявени:
        return tasks, []

    # КОЙ ОБЯВЕН СРОК УПРАВЛЯВА КОЯ ФАЗА.  Срокът за СМР покрива и
    # мобилизацията, и приемането — виж `_ПОКРИТИ_ФАЗИ`.  Фаза със свой обявен
    # срок се мери сама и излиза от групата.
    управлява: dict[str, str] = {ф: ф for ф in обявени}
    for водеща, покрити in _ПОКРИТИ_ФАЗИ.items():
        if водеща not in обявени:
            continue
        for фаза in покрити:
            if фаза not in обявени:
                управлява[фаза] = водеща

    chain_defs = (chains or {}).get("chains", chains) or {}
    фаза_на_пакет: dict[str, str] = {}
    for pkg in packages or []:
        pid = _attr(pkg, "id")
        верига = chain_defs.get(str(_attr(pkg, "chain") or ""), {})
        if pid and isinstance(верига, dict):
            фаза_на_пакет[str(pid)] = str(верига.get("wbs_root") or "")

    def _водеща(t: dict) -> str | None:
        return управлява.get(фаза_на_пакет.get(str(t.get("parent_id") or "")))

    def листа_по_фаза(текущи: list[dict]) -> dict[str, list[dict]]:
        """Задачите, чиято ПРОДЪЛЖИТЕЛНОСТ може да се мени."""
        по_фаза: dict[str, list[dict]] = {}
        for t in текущи or []:
            if not t.get("chain_step") or t.get("milestone") or t.get("is_milestone"):
                continue
            водеща = _водеща(t)
            if водеща in обявени:
                по_фаза.setdefault(водеща, []).append(t)
        return по_фаза

    def обхват_по_фаза(текущи: list[dict]) -> dict[str, tuple[int, int]]:
        """Обхватът, КАКТО ГО ВИЖДА ЧОВЕКЪТ — с milestone-ите вътре.

        Мереше се само по работните задачи, а съгласувателните milestone-и
        стоят СЛЕД тях, всеки на свой ден.  Следствието беше срок над тавана
        при „спазен" срок в бележките: проектирането на Илиянци излизаше 124
        дни при обявени 120, а на Русе 74 при 70.  Фазата в графика е това,
        което се брои, а не работната ѝ част.
        """
        обхвати: dict[str, tuple[int, int]] = {}
        for t in текущи or []:
            if t.get("is_summary") or not t.get("start_day"):
                continue
            водеща = _водеща(t)
            if водеща not in обявени:
                continue
            a, b = int(_num(t.get("start_day"))), int(_num(t.get("end_day")))
            ако = обхвати.get(водеща)
            обхвати[водеща] = ((min(ако[0], a), max(ако[1], b)) if ако else (a, b))
        return обхвати

    бележки: list[str] = []
    първи_обхват: dict[str, int] = {}
    #: Най-доброто СЪВМЕСТИМО състояние на фазата — обхват под тавана, но
    #: възможно най-близо до него.  Без него правилото зависи от късмета на
    #: последната итерация: мерено на контролния прогон, строителството се
    #: разтягаше 591 → 782 при обявени 780 и спираше ДВА ДНИ НАД тавана.
    най_добро: dict[str, tuple[int, dict[str, int]]] = {}

    def запомни(фаза: str, обхват: int, задачи: list[dict]) -> None:
        цел = обявени[фаза]
        ако = най_добро.get(фаза)
        if обхват <= цел and (ако is None or обхват > ако[0]):
            най_добро[фаза] = (обхват,
                               {str(t.get("id")): int(_num(t.get("duration")))
                                for t in задачи})

    предишен: dict[str, int] = {}
    for опит in range(max(опити, 1)):
        по_фаза = листа_по_фаза(tasks)
        обхвати = обхват_по_фаза(tasks)
        ощe_има_работа = False

        for фаза, задачи in по_фаза.items():
            цел = обявени[фаза]
            начало, край = обхвати.get(фаза, _обхват(задачи))
            сега = край - начало + 1
            if сега <= 0:
                continue
            първи_обхват.setdefault(фаза, сега)
            запомни(фаза, сега, задачи)

            # СРОКЪТ Е ТАВАН, НЕ ЦЕЛ ПО СРЕДАТА.  Един ден ПОД обявеното е
            # приемливо — губим ден.  Един ден НАД него прави офертата
            # неотговаряща, затова горе допуск няма.
            if цел - 1 <= сега <= цел:
                continue

            if сега > цел:
                променени = _свий_под(задачи, цел, сега)
            elif цел - сега <= _ТЪНКО:
                # ТЪНКАТА НАСТРОЙКА Е ПО КРАЯ, не по сбора.  Пропорционалното
                # разтягане работи върху сбора от продължителности, а обхватът
                # се държи от критичния път: добавен ден на успореден участък
                # не мърда края с нищо.  Мерено на Илиянци — фазата се люлееше
                # 650 → 663 → 662 при обявени 660 и никога не влизаше в целта.
                # Последните действия местят края един към един.
                променени = _доший_края(задачи, цел - сега)
            else:
                променени = _разтегли(задачи, цел, сега)
                # СБОРЪТ РАСТЕ, КРАЯТ НЕ СЕ МЕСТИ.  Пропорционалното разтягане
                # работи по сбора от продължителности, а обхватът се държи от
                # критичния път: щом участъците вървят в редици на екипи,
                # добавен ден на успореден участък не мърда края с нищо.
                # Мерено на Илиянци — фазата увисваше на 650 при обявени 660.
                # Тогава се дошива по ОПАШКАТА: последните действия местят
                # края един към един.
                застояло = (not променени
                            or предишен.get(фаза) == сега
                            or опит == max(опити, 1) - 1)
                if застояло:
                    променени = _доший_края(задачи, цел - сега) or променени
            предишен[фаза] = сега
            if променени:
                ощe_има_работа = True

        if not ощe_има_работа or разпиши is None:
            break
        tasks = разпиши(tasks) or tasks

    # ВРЪЩАНЕ КЪМ НАЙ-ДОБРОТО СЪВМЕСТИМО.  Итерациите свършват там, където
    # свършват — а фаза, останала НАД тавана, прави офертата неотговаряща.
    # Затова, ако някоя итерация е постигнала обхват под тавана, се връщаме
    # към нея; иначе казваме честно, че не се е събрала.
    върнати = False
    обхвати = обхват_по_фаза(tasks)
    for фаза, задачи in листа_по_фаза(tasks).items():
        начало, край = обхвати.get(фаза, _обхват(задачи))
        if край - начало + 1 <= обявени[фаза]:
            continue
        запомнено = най_добро.get(фаза)
        if not запомнено:
            continue
        _, продължителности = запомнено
        for t in задачи:
            дни = продължителности.get(str(t.get("id")))
            if дни and дни != int(_num(t.get("duration"))):
                t["duration"] = дни
                върнати = True
    if върнати and разпиши is not None:
        tasks = разпиши(tasks) or tasks

    крайни = листа_по_фаза(tasks)
    обхвати = обхват_по_фаза(tasks)
    for фаза, цел in sorted(обявени.items()):
        задачи = крайни.get(фаза) or []
        if not задачи:
            continue
        начало, край = обхвати.get(фаза, _обхват(задачи))
        стана = край - начало + 1
        беше = първи_обхват.get(фаза, стана)
        if abs(беше - цел) <= 1:
            бележки.append(f"{фаза}: обявеният срок {цел} дни вече се спазва.")
            continue
        посока = "разтеглена" if цел > беше else "свита"
        бележка = (f"{фаза}: обявен срок {цел} дни — фазата е {посока} от "
                   f"{беше} на {стана} дни.")
        if abs(стана - цел) > 1:
            бележка += ("  Не се събра точно: стъпки от по един ден не могат да "
                        "се делят, а зависимостите държат останалото.")
        бележки.append(бележка)

    for бележка in бележки:
        logger.info("%s", бележка)
    return tasks, бележки


def verify_declared_terms(
    tasks: list[dict],
    packages: Iterable[Any],
    chains: dict,
) -> list[str]:
    """Проверява НАКРАЯ, че нито един обявен срок не е надхвърлен.

    НЕОТМЕНИМО ПРАВИЛО (изпълнителят, 24.08.2026): максималният срок в тръжната
    документация е максимумът и на нашия график.  Не приблизително, не „почти".

    `enforce_declared_phase_terms` налага срока, но след него по графика
    минават още стъпки — сливане на непрекъснатите дейности, критичен път,
    разтягане на обобщаващите — и всяка от тях може да измести с ден.  Мерено:
    налагането връщаше 654 дни при обявени 660, а изнесеният файл показваше
    661.  Затова тук се мери ПОСЛЕДНОТО състояние, същото, което човекът вижда.

    Проверява се и СБОРЪТ: щом всяка обявена фаза има таван, графикът не бива
    да ги надхвърля и заедно.

    Returns:
        Списък с нарушения — празен, когато всичко се събира.  Извикващият ги
        слага при блокерите: график над обявения срок е неотговаряща оферта и
        не бива да излиза мълчаливо.
    """
    from src.tender_parameters import declared_phase_days

    обявени = {ф: д for ф, д in (declared_phase_days() or {}).items()
               if ф not in _БЕЗ_СРОК and д > 0}
    if not обявени:
        return []

    управлява: dict[str, str] = {ф: ф for ф in обявени}
    for водеща, покрити in _ПОКРИТИ_ФАЗИ.items():
        if водеща in обявени:
            for фаза in покрити:
                if фаза not in обявени:
                    управлява[фаза] = водеща

    chain_defs = (chains or {}).get("chains", chains) or {}
    фаза_на_пакет: dict[str, str] = {}
    for pkg in packages or []:
        pid = _attr(pkg, "id")
        верига = chain_defs.get(str(_attr(pkg, "chain") or ""), {})
        if pid and isinstance(верига, dict):
            фаза_на_пакет[str(pid)] = str(верига.get("wbs_root") or "")

    обхвати: dict[str, tuple[int, int]] = {}
    for t in tasks or []:
        if t.get("is_summary") or not t.get("start_day"):
            continue
        водеща = управлява.get(фаза_на_пакет.get(str(t.get("parent_id") or "")))
        if водеща not in обявени:
            continue
        a, b = int(_num(t.get("start_day"))), int(_num(t.get("end_day")))
        ако = обхвати.get(водеща)
        обхвати[водеща] = ((min(ако[0], a), max(ако[1], b)) if ако else (a, b))

    нарушения: list[str] = []
    for фаза, цел in sorted(обявени.items()):
        ако = обхвати.get(фаза)
        if not ако:
            continue
        стана = ако[1] - ако[0] + 1
        if стана > цел:
            нарушения.append(
                f"Фаза {фаза}: {стана} дни при ОБЯВЕН МАКСИМУМ {цел} — "
                f"{стана - цел} дни над тавана.  Срокът в тръжната документация "
                "е максимумът и на графика.")

    таван = sum(обявени.values())
    краища = [int(_num(t.get("end_day"))) for t in tasks or []
              if t.get("end_day") and not t.get("is_summary")]
    начала = [int(_num(t.get("start_day"))) for t in tasks or []
              if t.get("start_day") and not t.get("is_summary")]
    if краища and начала and len(обявени) > 1:
        общо = max(краища) - min(начала) + 1
        if общо > таван:
            нарушения.append(
                f"Целият график е {общо} дни при сбор на обявените срокове "
                f"{таван} — {общо - таван} дни над тавана.")

    for нарушение in нарушения:
        logger.error("%s", нарушение)
    return нарушения
