from __future__ import annotations

import logging
import math
from typing import Any, Iterable

logger = logging.getLogger(__name__)

#: Само тук участък има размер, който значи нещо за срока.
_SCALED_ROOT = "construction"

#: Произходът остава `chain_template`: числото пак НЕ идва от нормите.
_TEMPLATE = "chain_template"

#: Вериги, чийто екземпляр е ОТДЕЛЕН ОБЕКТ, а не част от мрежа — не се
#: анкерират.  Виж защо в тялото на `scale_segment_overhead`.
_САМОСТОЯТЕЛНИ = frozenset({"structure"})


def _num(value: Any) -> float:
    try:
        f = float(value)
    except (TypeError, ValueError):
        return 0.0
    return f if math.isfinite(f) else 0.0


def _attr(obj: Any, name: str) -> Any:
    if isinstance(obj, dict):
        return obj.get(name)
    return getattr(obj, name, None)


#: Мерките, в които тръбата се мери на дължина.  „m3/m'" НЕ е сред тях: то е
#: обем на метър (бетонов кожух) и сборването му би раздуло дължината.
_ДЪЛЖИННИ_МЕРКИ = frozenset({"м", "m", "мл", "ml", "m'", "м'", "лм", "lm"})


def _линейни_метри(pkg: Any) -> float:
    """Метрите ТРЪБА в пакета — по които се мери размерът на обекта.

    Само редовете за ПОЛАГАНЕ: изкопът и настилката също се мерят на метър или
    на квадрат, а те са различна работа върху същото трасе — събрани заедно, те
    биха умножили дължината по броя дейности върху нея.
    """
    метри = 0.0
    for item in (_attr(pkg, "items") or ()):
        клас = str(_attr(item, "activity_class") or "").strip().lower()
        if клас != "laying":
            continue
        мярка = str(_attr(item, "unit") or "").strip().lower().rstrip(".")
        if мярка and мярка not in _ДЪЛЖИННИ_МЕРКИ:
            continue
        метри += abs(_num(_attr(item, "quantity")))
    return метри


def _apportion(общо: int, тегла: list[float]) -> list[int]:
    """Цели дни по НАЙ-ГОЛЯМ ОСТАТЪК: сборът е точно `общо`, всеки поне 1.

    Закръглянето нагоре на всеки пакет поотделно връща същия дефект, който
    поправяме: при 46 дни еталон 8 пакета дават 48, а 14 дават 56 — тоест
    разделянето пак ражда работа.  Тук остатъците се събират и допълват
    сбора, вместо всеки да плаща цял ден нагоре.

    Подът от един ден е по-силен от сбора: стъпка, която се извършва, не може
    да трае нула.  Когато пакетите са повече от дните, сборът излиза равен на
    броя им — и това се вижда, вместо да се крие.
    """
    n = len(тегла)
    if n == 0:
        return []
    сума = sum(тегла)
    ако = [(общо * w / сума) if сума > 0 else (общо / n) for w in тегла]
    цели = [max(1, int(math.floor(x))) for x in ако]
    остава = общо - sum(цели)
    if остава > 0:
        ред = sorted(range(n), key=lambda i: ако[i] - math.floor(ако[i]),
                     reverse=True)
        for i in range(остава):
            цели[ред[i % n]] += 1
    return цели


#: Произходът на стъпка, сметната от ОБЯВЕНО темпо в м/ден.  Различава се от
#: `calculated` (норма по диаметър за собствения ред) и от `chain_template`
#: (дял от анкера): числото идва от норма, но за СТЪПКАТА, не за реда.
_STEP_RATE = "step_rate"

#: Кои произходи броят за „доказана работа" при разпределянето на анкера.
_ДОКАЗАНИ = frozenset({"calculated", _STEP_RATE})


def _темпа_на_стъпки() -> dict:
    """Обявените темпа `<верига>.<стъпка>` → м/ден, от productivities.json."""
    try:
        from src.duration_calculator import load_productivities
        cfg = load_productivities()
    except Exception as exc:      # noqa: BLE001 — конфигът не бива да спира прогона
        logger.warning("Темпата на стъпките не се прочетоха: %s", exc)
        return {}
    раздел = cfg.get("step_productivities") if isinstance(cfg, dict) else None
    return раздел if isinstance(раздел, dict) else {}


def _по_темпо(
    chain_of: dict[str, str],
    дължина_на: dict[str, float],
    листа_на: dict[str, list[dict]],
) -> tuple[int, list[str]]:
    """Стъпките с ОБЯВЕНО темпо се смятат от метрите на своя участък.

    ЗАЩО (24.08.2026).  Изкопът, разкъртването и извозването нямат свой ред в
    количествата — те са вътре в тръбния ред на търга — затова вземаха време от
    анкера на еталона.  Числото беше вярно по големина, но НЕВИДИМО: темпото
    излизаше наум, от `median_days × observed_count` върху метрите, и нямаше
    какво да поправи човекът, който знае колко се копае на ден.

    Стъпка с темпо НАПУСКА анкера (произходът ѝ вече не е `chain_template`),
    затова работата ѝ не се брои два пъти.  Пипа се само шаблонна стъпка:
    когато стъпката си има собствен ред с количество, нормата по диаметър вече
    е казала думата си и не бива да бъде надписвана.

    Returns:
        (брой пипнати задачи, бележки).
    """
    темпа = _темпа_на_стъпки()
    if not темпа:
        return 0, []

    пипнати = 0
    по_ключ: dict[str, list[float]] = {}
    for pkg_id, листа in листа_на.items():
        верига = chain_of.get(pkg_id, "")
        метри = дължина_на.get(pkg_id, 0.0)
        if not верига or метри <= 0:
            continue
        for t in листа:
            if str(t.get("duration_source") or "") != _TEMPLATE:
                continue
            ключ = f"{верига}.{str(t.get('chain_step') or '')}"
            запис = темпа.get(ключ)
            темпо = _num(запис.get("effective_rate")) if isinstance(запис, dict) else 0.0
            if темпо <= 0:
                continue
            дни = max(1, math.ceil(метри / темпо))
            t["duration"] = дни
            t["duration_source"] = _STEP_RATE
            t["step_rate"] = темпо
            t["step_rate_key"] = ключ
            по_ключ.setdefault(ключ, []).append(float(дни))
            пипнати += 1

    бележки = []
    for ключ, дни in sorted(по_ключ.items()):
        темпо = _num((темпа.get(ключ) or {}).get("effective_rate"))
        бележки.append(
            f"Стъпка по обявено темпо: {ключ} — {темпо:g} м/ден, "
            f"{len(дни)} участъка, Σ {sum(дни):.0f} дни (извън анкера).")
    for бележка in бележки:
        logger.info("%s", бележка)
    return пипнати, бележки


def scale_segment_overhead(
    tasks: list[dict],
    packages: Iterable[Any],
    chains: dict,
) -> tuple[list[dict], list[str]]:
    """Разпределя овърхеда на веригата между пакетите ѝ.

    Връща (задачи, бележки).  Всяка пипната задача носи `segment_share` и
    `template_days`, за да е четимо откъде идва числото и обратимо, ако се
    окаже грешно.
    """
    chain_defs = (chains or {}).get("chains", chains) or {}

    chain_of: dict[str, str] = {}
    дължина_на: dict[str, float] = {}
    for pkg in packages or []:
        pid = _attr(pkg, "id")
        if pid:
            chain_of[str(pid)] = str(_attr(pkg, "chain") or "")
            дължина_на[str(pid)] = _линейни_метри(pkg)

    # Листата по пакет; пакетите по верига.
    листа_на: dict[str, list[dict]] = {}
    for task in tasks or []:
        if task.get("chain_step"):
            листа_на.setdefault(str(task.get("parent_id") or ""), []).append(task)

    пакети_на_верига: dict[str, list[str]] = {}
    for pkg_id in листа_на:
        верига = chain_of.get(pkg_id, "")
        if верига:
            пакети_на_верига.setdefault(верига, []).append(pkg_id)

    пипнати = 0
    без_анкер: set[str] = set()
    бележки: list[str] = []
    #: Колко „еталонни участъка" се равнява всяка верига — казва се, защото
    #: това е числото, което мени срока.
    мащаби: list[str] = []

    # ТЕМПОТО НА СТЪПКАТА, КОГАТО Е ОБЯВЕНО, ИДВА ПРЕДИ АНКЕРА (24.08.2026).
    # Стъпка с норма в м/ден се смята от метрите на СВОЯ участък и напуска
    # анкера — виж `_по_темпо`.
    темпови, темпо_бележки = _по_темпо(chain_of, дължина_на, листа_на)
    пипнати += темпови
    бележки.extend(темпо_бележки)

    for верига, pkg_ids in пакети_на_верига.items():
        chain = chain_defs.get(верига)
        if not isinstance(chain, dict):
            continue
        if str(chain.get("wbs_root") or "") != _SCALED_ROOT:
            continue
        if верига in _САМОСТОЯТЕЛНИ:
            # ВЕРИГА, ЧИЙТО ЕКЗЕМПЛЯР Е ОТДЕЛЕН ОБЕКТ, не част от мрежа.
            #
            # Анкерът стъпва на допускането, че `observed_count` брои
            # участъците НА ОБЕКТА: 46 канализационни отсечки са цялата
            # канализация, затова общата работа по стъпка е фиксирана и се
            # дели между нашите пакети.  За `structure` числото е 1, но то
            # значи „видяхме ЕДНА шахта", а не „обектът има една".
            #
            # Резултатът беше обратен на смисъла (измерено 19.08.2026):
            # деветнайсетте дни на еталонната преливна шахта се разделяха
            # между дванайсет наши съоръжения и всяко излизаше с по 8 дни,
            # докато водомерната — която ИМА норма и затова получаваше по-
            # голям дял — стигна 33.  Всяко съоръжение е цяла работа за себе
            # си и пази пълните продължителности на шаблона.
            continue

        наблюдавани = int(_num(chain.get("observed_count")))
        steps = {str(s.get("key")): s for s in (chain.get("steps") or [])}
        if наблюдавани <= 0:
            if any(str(t.get("duration_source") or "") == _TEMPLATE
                   for pid in pkg_ids for t in листа_на[pid]):
                без_анкер.add(верига)
            continue

        # АНКЕРЪТ Е ЕТАЛОНЪТ НА МЕТЪР, НЕ ЦЕЛИЯТ ЕТАЛОН (24.08.2026).
        #
        # Дотук общата работа по стъпка беше `медиана × observed_count` —
        # абсолютният сбор на ЕДИН обект.  Свойството, което пазеше (разделяне
        # на повече пакети да не ражда овърхед), е вярно; цената беше, че
        # размерът на НАШИЯ търг не значеше нищо: обект с 4000 м и обект с
        # 20 000 м канал получаваха едни и същи 161 бригадо-дни изкоп, само
        # нарязани на повече парчета.  Тоест еталонът беше зашит в срока на
        # всеки график.
        #
        # Сега еталонът дава ДЪЛЖИНАТА НА ЕДИН СВОЙ УЧАСТЪК, а нашите метри
        # казват на колко такива участъка се равнява този обект:
        #
        #     еталонен участък = observed_length_m / observed_count
        #     еквивалентни     = нашите метри / еталонен участък
        #     анкер(стъпка)    = median_days × еквивалентни
        #
        # Разделянето пак не ражда работа — метрите не се менят от това на
        # колко пакета сме ги нарязали.
        еталонна_дължина = _num(chain.get("observed_length_m"))
        наши_метри = sum(дължина_на.get(pid, 0.0) for pid in pkg_ids)
        еквивалентни = float(наблюдавани)
        if еталонна_дължина > 0 and наши_метри > 0:
            еталонен_участък = еталонна_дължина / наблюдавани
            еквивалентни = наши_метри / еталонен_участък
            мащаби.append(
                f"{верига}: {наши_метри:.0f} м ÷ {еталонен_участък:.0f} м "
                f"(еталонен участък) = {еквивалентни:.1f} еталонни участъка "
                f"срещу {наблюдавани} в еталона")
        elif еталонна_дължина <= 0:
            бележки.append(
                f"Верига {верига}: еталонът няма записана дължина — овърхедът "
                "остава на абсолютния му обем и НЕ следва размера на този търг.")

        # Делът на пакета от ДОКАЗАНАТА работа.  Стъпката е една, дори когато
        # носи няколко КСС реда: паралелните задачи в нея минават заедно,
        # затова се брои най-дългата, не сборът им.
        доказани: dict[str, float] = {}
        for pid in pkg_ids:
            по_стъпка: dict[str, float] = {}
            for t in листа_на[pid]:
                if str(t.get("duration_source") or "") in _ДОКАЗАНИ:
                    k = str(t.get("chain_step") or "")
                    по_стъпка[k] = max(по_стъпка.get(k, 0.0),
                                       _num(t.get("duration")))
            доказани[pid] = sum(по_стъпка.values())

        общо = sum(доказани.values())
        дял = {pid: (доказани[pid] / общо if общо > 0 else 1.0 / len(pkg_ids))
               for pid in pkg_ids}

        # Стъпката се разпределя ЦЯЛА, между пакетите, които я носят като
        # шаблон.  Пакет, за който същата стъпка е сметната от нормите, вече
        # носи своя дял — неговата част от еталона не се раздава втори път.
        по_стъпка_шаблонни: dict[str, list[str]] = {}
        задачи_на: dict[tuple[str, str], list[dict]] = {}
        for pid in pkg_ids:
            for t in листа_на[pid]:
                if str(t.get("duration_source") or "") != _TEMPLATE:
                    continue
                k = str(t.get("chain_step") or "")
                if k not in steps:
                    continue
                if pid not in по_стъпка_шаблонни.setdefault(k, []):
                    по_стъпка_шаблонни[k].append(pid)
                задачи_на.setdefault((k, pid), []).append(t)

        for k, носители in по_стъпка_шаблонни.items():
            медиана = _num(steps[k].get("median_days"))
            if медиана <= 0:
                continue
            # СВИТАТА СТЪПКА НОСИ ЦЯЛОТО ТРАСЕ, не дела на своя участък
            # (25.08.2026).  При обявено единично трасе изпитването,
            # дезинфекцията и присъединяването стават ЕДНА задача под последния
            # участък (`single_route`).  Тя обаче не е работа за този участък, а
            # за целия водопровод — по дела му тя би получила една осма от
            # анкера и седем осми от работата просто щяха да изчезнат при
            # свиването.  Мерено на тласкателя (ВиК Русе): дезинфекцията падаше
            # от 36 на 4 дни, изпитването — от 9 на 1.
            за_цялото_трасе = any(t.get("route_wide")
                                  for pid in носители
                                  for t in задачи_на[(k, pid)])
            дял_на_носителите = (1.0 if за_цялото_трасе
                                 else sum(дял[pid] for pid in носители))
            цел = int(round(медиана * еквивалентни * дял_на_носителите))
            цел = max(цел, len(носители))
            раздадени = _apportion(цел, [дял[pid] for pid in носители])
            for pid, дни in zip(носители, раздадени):
                for t in задачи_на[(k, pid)]:
                    t["segment_share"] = round(дял[pid], 4)
                    t["template_days"] = медиана
                    if дни != _num(t.get("duration")):
                        t["duration"] = дни
                        пипнати += 1

    if пипнати:
        бележки.append(
            f"Овърхед на участък: {пипнати} задължителни стъпки без количество "
            "получиха дела си от еталона НА МЕТЪР, а не медианата за един "
            "еталонен участък." + (" " + "; ".join(мащаби) if мащаби else ""))
    if без_анкер:
        бележки.append(
            "Без анкер от еталона остават вериги " + ", ".join(sorted(без_анкер))
            + " — техните задължителни стъпки пазят медианата на шаблона.")
    for бележка in бележки:
        logger.info("%s", бележка)
    return tasks, бележки


def calibrate_to_declared_pace(
    tasks: list[dict],
    packages: Iterable[Any],
    boq_index: Iterable[Any],
    overrides: dict[str, float] | None = None,
) -> tuple[list[dict], list[str]]:
    """Свива верига до ОБЯВЕНОТО ѝ темпо, м/ден на екип.

    Изпълнителят казва: „приеми, че всеки екип полага по 8.6 м тръби В на
    ден".  Това е темпо за ЦЕЛИЯ цикъл по участък — трасиране, разкъртване,
    изкоп, заваряване, изтегляне, фасонни части, изпитване, дезинфекция,
    арматури, връзки — не за една стъпка.  Затова се прилага върху сбора, а
    отделните стъпки запазват пропорцията си.

    Числото е по-силно от нормите по стъпки: то идва от изпълнителя за ТОЗИ
    обект, а нормите са средни.  За сравнение еталонът дава 417 екипо-дни за
    3247 м = 7.8 м/ден.

    Мащабът се ОБЯВЯВА, за да не изглежда, че продължителностите са изчислени
    от нормите, когато всъщност са свити до обявено темпо.
    """
    from src.tender_parameters import declared_pace

    верига_на = {}
    for pkg in packages or []:
        pid = _attr(pkg, "id")
        if pid:
            верига_на[str(pid)] = str(_attr(pkg, "chain") or "")

    метри: dict[str, float] = {}
    работа: dict[str, float] = {}
    листа: dict[str, list[dict]] = {}
    количество = {str(_attr(r, "ref")): (float(_attr(r, "quantity") or 0),
                                         str(_attr(r, "unit") or "").strip())
                  for r in (boq_index or [])
                  if isinstance(_attr(r, "quantity"), (int, float))}

    for task in tasks or []:
        верига = верига_на.get(str(task.get("parent_id") or ""))
        if not верига or not task.get("chain_step"):
            continue
        листа.setdefault(верига, []).append(task)
        работа[верига] = работа.get(верига, 0.0) + _num(task.get("duration"))

    for pkg in packages or []:
        верига = str(_attr(pkg, "chain") or "")
        for item in (_attr(pkg, "items") or ()):
            реф = str(_attr(item, "source_ref") or "")
            кол, мярка = количество.get(реф, (0.0, ""))
            if мярка in ("m", "м") and кол:
                метри[верига] = метри.get(верига, 0.0) + _num(
                    _attr(item, "quantity"))

    бележки: list[str] = []
    for верига, задачи in листа.items():
        темпо = (overrides or {}).get(верига) or declared_pace(верига)
        дължина = метри.get(верига, 0.0)
        сега = работа.get(верига, 0.0)
        if not темпо or дължина <= 0 or сега <= 0:
            continue
        цел = дължина / темпо
        if abs(цел / сега - 1.0) < 0.02:
            continue

        # НАГОРЕ СЪЩО (24.08.2026).  Функцията беше писана само за свиване:
        # изпълнителят обявяваше темпо ПО-БЪРЗО от нормите.  Откакто темпото се
        # ИЗВЕЖДА ОТ СРОКА, то често иска ПОВЕЧЕ работа, отколкото нормите
        # дават — мерено на Русе: 1268 м при 3.52 м/ден искат 360 екипо-дни, а
        # веригата беше 108 и оставаше 108.  Тогава темпото не решаваше нищо и
        # срокът се пълнеше от друго правило.
        if цел > сега:
            множител = цел / сега
            for задача in задачи:
                беше = _num(задача.get("duration"))
                if беше <= 0:
                    continue
                стана = max(1, int(round(беше * множител)))
                if стана != беше:
                    задача.setdefault("computed_duration", беше)
                    задача["duration"] = стана
                    задача["declared_pace"] = темпо
            станало = sum(_num(t.get("duration")) for t in задачи)
            бележки.append(
                f"{верига}: темпо {темпо:g} м/ден на екип → {дължина:.0f} м "
                f"искат {цел:.0f} екипо-дни; веригата беше {сега:.0f} и стана "
                f"{станало:.0f}.")
            continue

        # НАМАЛЕНИЕТО СЕ ПРЕНАСОЧВА ТАМ, КЪДЕТО ИМА МЯСТО.
        #
        # Пропорционалното свиване не стига до целта: задача от един ден,
        # умножена по 0.71, пак е един ден, а 270 от 300-те водни задачи са
        # точно такива.  Мереното следствие: сборът оставаше 450 вместо 378 и
        # два екипа изкарваха водопровода за 256 дни вместо за 190.
        #
        # Затова се маха от задачите, които МОГАТ да се съкратят (над един
        # ден), пропорционално на техния излишък, и се повтаря, докато целта се
        # достигне или вече няма откъде.  Подът от един ден остава ненарушим:
        # операция, която се извършва, не трае нула.
        остава = сега - цел
        for _ in range(8):
            свиваеми = [t for t in задачи if _num(t.get("duration")) > 1]
            излишък = sum(_num(t.get("duration")) - 1 for t in свиваеми)
            if остава <= 0.5 or излишък <= 0:
                break
            дял = min(остава / излишък, 1.0)
            махнато = 0.0
            for задача in свиваеми:
                беше = _num(задача.get("duration"))
                стана = max(1, int(round(беше - (беше - 1) * дял)))
                if стана != беше:
                    задача["duration"] = стана
                    задача["declared_pace"] = темпо
                    махнато += беше - стана
            if махнато <= 0:
                break
            остава -= махнато

        станало = sum(_num(t.get("duration")) for t in задачи)
        бележки.append(
            f"{верига}: обявено темпо {темпо:g} м/ден на екип → {дължина:.0f} м "
            f"искат {цел:.0f} екипо-дни; веригата беше {сега:.0f} и стана "
            f"{станало:.0f}."
            + ("" if станало <= цел * 1.05 else
               "  Повече не може: остатъкът е в задачи от по един ден, а "
               "операция, която се извършва, не трае нула."))
    for бележка in бележки:
        logger.info("%s", бележка)
    return tasks, бележки


