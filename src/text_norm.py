# -*- coding: utf-8 -*-
"""Латински букви, вмъкнати в кирилски думи — и как да не губим данни от тях.

ЗАЩО.  Тръжните чертежи и документи се набират на машини с две подредби и в
текста остават букви, които ИЗГЛЕЖДАТ кирилски, а не са.  Измерено 31.08.2026
върху пакета на Илиянци:

    Ситуация Вод.pdf   „Кл.“ с кирилско К — 20 етикета
                       „Kл“  с ЛАТИНСКО K — 10 етикета

Тоест една трета от водопроводните клонове бяха невидими за четеца, който ги
търси с `^Кл\\.`, и изчезваха мълчаливо: без метри, без участък, без
предупреждение.  В целия пакет 68 думи от 177 598 са смесени и падат точно
върху означенията, по които се хващаме — `Kл`, `OТ`, `РP`, `TП`, `Бaлчо`.

Намерено случайно: бенчмаркът на моделите ги обвини, че измислят
„ул. Балчо Нейков“, а в документа пише „ул. Бaлчо Нейков“ с латинско `a`.
Моделите бяха прави; проверката ни грешеше.

ЗАЩО НЕ ВСИЧКО НАРЕД.  Пряка замяна на всяко латинско `P` с кирилско `Р` би
счупила `PEHD`, `DN`, `HDPE`, `L=`, `CCTV` — половината технически означения в
същите чертежи.  Затова замяната става САМО вътре в дума, която вече съдържа
кирилица.  `Kл` се поправя; `PEHD` не се пипа.
"""

from __future__ import annotations

import re

#: Латинска буква → кирилската, която изглежда като нея.  Само двойките, които
#: се различават единствено по кодова точка; `l`/`I`/`1` нарочно ги няма —
#: там приликата е с ЦИФРА и замяната би била догадка.
ОМОГЛИФИ = {
    "A": "А", "B": "В", "C": "С", "E": "Е", "H": "Н", "K": "К", "M": "М",
    "O": "О", "P": "Р", "T": "Т", "X": "Х", "Y": "У",
    "a": "а", "c": "с", "e": "е", "o": "о", "p": "р", "x": "х", "y": "у",
}

_ДУМА = re.compile(r"[A-Za-zА-Яа-яЁёЙйЪъЬьЮюЯя]+")
_КИРИЛИЦА = re.compile(r"[А-Яа-яЁё]")


def cyrillize(текст: str, *, whole_line: bool = False) -> str:
    """Смесените думи стават изцяло кирилски; чисто латинските не се пипат.

    >>> cyrillize("Kл.48 PEHD DN160")
    'Кл.48 PEHD DN160'

    `whole_line=True` добавя ЕДНО правило: САМОСТОЯТЕЛНА единична буква на ред,
    който вече съдържа кирилица, също се кирилизира.  Нужно е заради наставките
    на клоновете — чертежът пише `Кл.8 a` с латинско `a`, а на друго място
    `Кл.8а` с кирилско, и без това правило един клон става два:

    >>> cyrillize("Kл.8 a 160 ПЕВП", whole_line=True)
    'Кл.8 а 160 ПЕВП'
    >>> cyrillize("Q=10.36 l/s L=225м PEHD", whole_line=True)
    'Q=10.36 l/s L=225м PEHD'

    Правилото е тясно нарочно: важи само за ЕДНА буква (мерни единици като
    `l/s`, `m`, `mm` не са в `ОМОГЛИФИ`) и само когато редът е български.
    """
    if not текст:
        return текст

    редът_е_кирилски = whole_line and bool(_КИРИЛИЦА.search(текст))

    def поправи(m: re.Match) -> str:
        дума = m.group(0)
        if _КИРИЛИЦА.search(дума):
            return "".join(ОМОГЛИФИ.get(з, з) for з in дума)
        if редът_е_кирилски and len(дума) == 1:
            return ОМОГЛИФИ.get(дума, дума)
        return дума                           # PEHD, DN, CCTV — чужди си

    return _ДУМА.sub(поправи, текст)


def has_mixed_script(текст: str) -> bool:
    """Има ли поне една дума с двете азбуки — за предупреждение към човека."""
    return any(_КИРИЛИЦА.search(д) and any(з in ОМОГЛИФИ for з in д)
               for д in _ДУМА.findall(текст or ""))


def mixed_words(текст: str) -> list[str]:
    """Кои са смесените думи — за да се каже КОЕ е поправено, а не само че е."""
    return [д for д in _ДУМА.findall(текст or "")
            if _КИРИЛИЦА.search(д) and any(з in ОМОГЛИФИ for з in д)]
