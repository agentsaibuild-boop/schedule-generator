# -*- coding: utf-8 -*-
"""Договорните интервали по FIDIC — прочетени, после показани, после ползвани.

ЗАЩО.  Изпълнителят, 01.09.2026:

    „За FIDIC четеш внимателно процедурата и изкарваш на човека събраната
     информация; ако има корекции, той ще ти каже, иначе приемаш указанията от
     тръжната документация и/или общите условия на FIDIC (в съответния цвят)
     за основни за тази поръчка."

Тоест редът е точно три стъпки и нито една не бива да се прескача:

    1. ПРОЧЕТИ приложението с договорни данни на процедурата — там стойностите
       са нейни и надделяват над всичко.
    2. Където мълчи, вземи общите условия на СЪОТВЕТНАТА КНИГА (цвят).
    3. ПОКАЖИ и двете на човека, преди да влязат в графика, като се вижда кое
       откъде идва.

ЗАЩО ЦВЕТЪТ ИМА ЗНАЧЕНИЕ.  Жълтата книга е за инженеринг — изпълнителят
проектира и строи; червената е за строителство по готов чужд проект.  Сроковете
за преглед на документите на Изпълнителя (5.2) съществуват в жълтата и нямат
смисъл в червената.  Затова книгата се РАЗПОЗНАВА, а не се приема.

ЧЕСТНОСТ ЗА ЧИСЛАТА.  Стойностите от общите условия стоят в `config/fidic.json`
с флаг `потвърдено_срещу_документ`.  Докато е `false`, те се показват с изрична
бележка, че НЕ са прочетени от документ на тази процедура.  Никое от тях не
влиза в график, преди човек да го е видял.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

_КОНФИГ = Path(__file__).resolve().parent.parent / "config" / "fidic.json"

#: По това се познава, че процедурата изобщо е по FIDIC.
_ПРИЗНАК = re.compile(
    r"\bFIDIC\b|под\s*-?\s*клауза|особени\s+условия\s+по\s+договора", re.I)


def _конфиг() -> dict:
    try:
        return json.loads(_КОНФИГ.read_text(encoding="utf-8"))
    except Exception as exc:                         # noqa: BLE001
        logger.warning("config/fidic.json не се прочете: %s", exc)
        return {"книги": {}, "интервали": []}


def detect_book(текст: str) -> tuple[str, str]:
    """(ключ на книгата, как е разпознат).  („", „") ако не е FIDIC."""
    ниско = (текст or "").lower()
    if not _ПРИЗНАК.search(ниско):
        return "", ""
    книги = _конфиг().get("книги") or {}
    for ключ, книга in книги.items():
        for дума in книга.get("разпознава_се_по") or []:
            if дума.lower() in ниско:
                return ключ, f"по думите „{дума}“ в документацията"
    # Няма изричен цвят.  Инженеринг → жълта; иначе не гадаем.
    if any(д in ниско for д in ("инженеринг", "проектиране и строителство",
                                "проектиране, авторски надзор и строителство")):
        return "жълта", ("по предмета на поръчката (инженеринг) — цветът НЕ е "
                         "изписан в документите")
    return "", "FIDIC е споменат, но книгата не се разпознава"


def intervals(base_path: str | Path) -> dict:
    """Договорните интервали за тази процедура, с произход на всяка стойност.

    Returns:
        {книга, етикет, как_е_разпознат, интервали: [...], бележки: [...]}
        Всеки интервал носи `източник`: „процедурата" или „общи условия".
    """
    from src.contract_data import _текст_на_docx, read_contract

    корен = Path(base_path)
    цял = ""
    if корен.exists():
        for път in sorted(корен.rglob("*.docx")):
            if not път.name.startswith("~$"):
                цял += "\n" + _текст_на_docx(път)[0]
        # Конвертираните PDF-и също носят текста на общите условия.
        конв = корен / "converted"
        if конв.exists():
            for f in sorted(конв.glob("*.json")):
                if f.name == "_manifest.json":
                    continue
                try:
                    d = json.loads(f.read_text(encoding="utf-8"))
                except Exception:                    # noqa: BLE001
                    continue
                цял += "\n" + (d.get("full_text") or "")

    книга, как = detect_book(цял)
    if not книга:
        return {"книга": "", "етикет": "", "как_е_разпознат": как,
                "интервали": [],
                "бележки": ["Процедурата не е разпозната като FIDIC — "
                            "договорните интервали не се прилагат."]}

    cfg = _конфиг()
    етикет = (cfg.get("книги") or {}).get(книга, {}).get("етикет", книга)

    # Каквото процедурата казва САМА за себе си — то надделява.
    от_процедурата: dict[str, dict] = {}
    договор = read_contract(корен) if корен.exists() else {}
    for ред in договор.get("приложение") or []:
        клауза = str(ред.get("клауза") or "").strip().rstrip(".")
        if клауза and ред.get("дни"):
            от_процедурата[клауза] = ред

    редове: list[dict] = []
    for основа in cfg.get("интервали") or []:
        клауза = str(основа.get("клауза"))
        # Същото условие носи различен номер в общите условия и в
        # приложението (ССД: 11.1 срещу 1.1.27) — търси се по всички.
        свое = None
        for номер in (основа.get("в_приложението") or [клауза]):
            свое = от_процедурата.get(str(номер))
            if свое:
                break
        if свое:
            редове.append({**основа, "дни": свое["дни"],
                           "източник": "процедурата",
                           "цитат": свое.get("описание", "")[:90],
                           "потвърдено_срещу_документ": True})
        else:
            редове.append({**основа, "източник": "общи условия"})

    непотвърдени = [р for р in редове if not р["потвърдено_срещу_документ"]]
    бележки = [f"Договорни условия: {етикет} — {как}."]
    свои = len([р for р in редове if р["източник"] == "процедурата"])
    if свои:
        бележки.append(f"{свои} стойности идват от приложението на процедурата "
                       f"и надделяват над общите условия.")
    if непотвърдени:
        бележки.append(
            f"{len(непотвърдени)} стойности идват от ОБЩИТЕ УСЛОВИЯ и НЕ са "
            f"сверени с документ на тази процедура — потвърди ги или ги "
            f"поправи, преди да влязат в графика.")
    return {"книга": книга, "етикет": етикет, "как_е_разпознат": как,
            "интервали": редове, "бележки": бележки}


def describe(данни: dict) -> list[str]:
    """Таблицата, която се показва на човека."""
    редове = list(данни.get("бележки") or [])
    интервали = данни.get("интервали") or []
    if not интервали:
        return редове
    редове.append("")
    редове.append("**Договорни интервали, които влизат в графика:**")
    for и in интервали:
        знак = "✔" if и["източник"] == "процедурата" else "○"
        редове.append(
            f"  {знак} Под-Клауза {и['клауза']}: **{и['дни']} дни** — "
            f"{и['какво']}, спрямо {и['спрямо']}"
            + ("" if и["източник"] == "процедурата" else "  [общи условия]"))
    редове.append("")
    редове.append("  ✔ = от документите на процедурата · ○ = от общите условия "
                  "на FIDIC, непроверено срещу твоите документи")
    return редове
