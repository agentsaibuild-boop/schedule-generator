"""Колко екипа трябват, за да се събере обектът в ЗАДАДЕНИЯ срок.

ОБРЪЩАНЕТО (изпълнителят, 19.08.2026): „имаш 780 дни за всичко: 120
проектиране и останалите за строителство… изчисляваш, в зависимост от
параметрите на тръбите, с колко екипа трябва да се работи В и с колко К, и ще
стане много лесно".

Прав е, и това мени задачата из основи.  Дотук питахме „с толкова екипа колко
ще трае обектът" и после се чудехме защо не съвпада с еталона.  Въпросът е
обратният: срокът е ДАДЕН от процедурата, неизвестното е броят екипи.

    екипи за веригата = ceil(нейната работа в екипо-дни / наличните дни)

Работата идва от нормите (`productivities.json`), тоест от диаметрите,
дължините и метода — точно „параметрите на тръбите".

Проверката, че сметката е вярна: за Илиянци излизат 2 канализационни, 1
водопроводен (при сондаж), 2 за настилки, 1 за съоръжения и 1 за кабели —
общо шест.  Човешкият график кара със ШЕСТ поименни екипа: ЕК1, ЕК2, ЕВ1,
ЕВ2, ЕВН и ЕС.

МИНИМУМЪТ НЕ СТИГА, и това е измерено: при 738 екипо-дни канализация и два
екипа теоретичният срок е 369 дни, а разписаният излезе 773 — използваемост
48%.  Зависимостите вътре в участъка (изкоп → полагане → изпитване) държат
екипа в чакане, колкото и работа да има на обекта.

Затова броят се ДОЗИРА С ПРОБА: разписва се, мери се, и веригата, която не се
събира, получава още един екип.  Точно това прави и планировчикът — не смята
наум колко екипа трябват, а гледа къде графикът излиза от срока.
"""

from __future__ import annotations

import logging
import math
from typing import Any, Iterable

logger = logging.getLogger(__name__)

#: Вериги, които НЕ са бригадна работа — не им се смятат екипи.
_БЕЗ_ЕКИП = frozenset({"design", "supervision", "mobilization", "acceptance"})


def work_by_chain(tasks: Iterable[dict],
                  packages: Iterable[Any]) -> dict[str, float]:
    """Екипо-дни по верига — сборът на продължителностите на листата ѝ."""
    верига_на = {}
    for pkg in packages or []:
        pid = getattr(pkg, "id", None) or (
            pkg.get("id") if isinstance(pkg, dict) else None)
        chain = getattr(pkg, "chain", None) or (
            pkg.get("chain") if isinstance(pkg, dict) else None)
        if pid:
            верига_на[str(pid)] = str(chain or "")

    работа: dict[str, float] = {}
    for task in tasks or []:
        if not task.get("chain_step"):
            continue
        верига = верига_на.get(str(task.get("parent_id") or ""))
        if not верига or верига in _БЕЗ_ЕКИП:
            continue
        try:
            дни = float(task.get("duration") or 0)
        except (TypeError, ValueError):
            дни = 0.0
        работа[верига] = работа.get(верига, 0.0) + max(дни, 0.0)
    return работа


#: Ключът, под който пробата връща обхвата на ЦЯЛОТО строителство, а не на
#: отделна верига.  Договорът ограничава точно него.
ОБЩ_ОБХВАТ = "__construction__"


def fit_crews_to_deadline(
    начални: dict[str, int],
    разпиши: Any,
    available_days: int,
    *,
    max_crews: int = 12,
    опити: int = 6,
) -> tuple[dict[str, int], list[str]]:
    """Дозира екипите, докато всяка верига се събере в срока.

    Args:
        начални: теоретичният минимум от `crews_for_deadline`.
        разпиши: `(екипи) -> {верига: обхват в дни}` — истинско разписване.
        available_days: колкото дава процедурата.

    Всяка верига, чийто ОБХВАТ надхвърля срока, получава още един екип и се
    пробва пак.  Спира, щом всичко се събере, щом нищо не се е подобрило, или
    на тавана — за да няма безкраен цикъл при верига, която не може да се
    ускори с повече хора (тя е ограничена от зависимости, не от ресурс).

    ОБЩИЯТ ОБХВАТ Е ОТДЕЛЕН ВЪПРОС (19.08.2026).  Веригите не тръгват заедно:
    с правилото „първо В, после К" каналът стартира 20 дни след водата.  Затова
    всяка верига може да се събира в 660 дни, а строителството да излиза 663 —
    и дозирането да обяви, че срокът е спазен, при график, който го къса.  Ако
    пробата върне `ОБЩ_ОБХВАТ`, той се проверява и той: щом само той е извън
    срока, екип получава НАЙ-ДЪЛГАТА верига, защото тя го държи.
    """
    екипи = dict(начални)
    бележки: list[str] = []
    предишен: dict[str, int] = {}

    for опит in range(1, max(опити, 1) + 1):
        обхвати = dict(разпиши(екипи) or {})
        общ = обхвати.pop(ОБЩ_ОБХВАТ, None)
        късни = {в: д for в, д in обхвати.items()
                 if д > available_days and екипи.get(в, 0) < max_crews}
        if not късни and общ is not None and общ > available_days:
            подходящи = {в: д for в, д in обхвати.items()
                         if екипи.get(в, 0) < max_crews}
            if подходящи:
                държи = max(подходящи, key=lambda в: подходящи[в])
                бележки.append(
                    f"опит {опит}: всяка верига се събира, но строителството "
                    f"излиза {общ:.0f} дни при {available_days} — вдигам "
                    f"най-дългата ({държи}, {подходящи[държи]:.0f} дни)")
                късни = {държи: подходящи[държи]}
        if not късни:
            бележки.append(
                f"Екипите се събират в срока от опит {опит}: "
                + ", ".join(f"{в}×{n}" for в, n in sorted(екипи.items())))
            return екипи, бележки
        # Нищо не помръдна спрямо предишния опит → повече екипи не помагат.
        ако_същото = all(обхвати.get(в) == предишен.get(в) for в in късни)
        if опит > 1 and ако_същото:
            бележки.append(
                "Повече екипи не съкращават " + ", ".join(sorted(късни))
                + " — те са ограничени от зависимости, не от ресурс.")
            return екипи, бележки
        предишен = dict(обхвати)
        for в, д in sorted(късни.items(), key=lambda kv: -kv[1]):
            # ВДИГА СЕ ПРОПОРЦИОНАЛНО, НЕ С ЕДИН (26.08.2026).  Верига, която
            # излиза 1263 дни при 660, не се оправя с още един екип — иска
            # двойно.  С +1 на опит броят опити свършваше преди числото да
            # стигне: Илиянци спираше на 3 канализационни екипа при нужни 6 и
            # излизаше 1125 дни вместо 780.
            сега = max(int(екипи.get(в, 1)), 1)
            нужни = max(сега + 1, int(-(-сега * д // available_days)))
            екипи[в] = min(нужни, max_crews)
            бележки.append(
                f"опит {опит}: {в} излиза {д:.0f} дни при {available_days} — "
                f"вдигам от {сега} на {екипи[в]} екипа")

    бележки.append("Достигнат таван на опитите — виж кои вериги остават извън срока.")
    return екипи, бележки


def add_crews_while_they_pay(
    екипи: dict[str, int],
    разпиши: Any,
    *,
    печалба: float = 0.20,
    max_crews: int = 12,
    опити: int = 4,
) -> tuple[dict[str, int], list[str]]:
    """Добавя екип, докато той СКЪСЯВА веригата съществено.

    Събирането в срока не е единственият въпрос.  Измерено на Илиянци:
    водопроводът има 472 екипо-дни, което при ЕДИН екип е 536 дни — и се
    „събира" в 660-те, затова дозирането спираше.  Но никой не кара един воден
    екип година и половина, когато с два свършва за 339 дни, а човешкият
    еталон го прави за 190 с ДВА.

    Затова: докато още един екип скъсява веригата с поне `печалба` (20% по
    подразбиране), той се добавя.  Спира, щом печалбата стане малка — тогава
    веригата е ограничена от зависимости, не от хора, и още екипи само биха
    стояли.

    Това е решение за ПАРИ, не само за срок, затова всяка стъпка се обявява:
    човекът трябва да види, че вторият екип съкращава с 37%, и да реши.
    """
    текущи = dict(екипи)
    обхвати = разпиши(текущи) or {}
    бележки: list[str] = []

    for _ in range(max(опити, 1)):
        промяна = False
        for верига in sorted(текущи, key=lambda в: -обхвати.get(в, 0)):
            ако = текущи[верига]
            if ако >= max_crews:
                continue
            проба = dict(текущи)
            проба[верига] = ако + 1
            нови = разпиши(проба) or {}
            беше = обхвати.get(верига, 0)
            стана = нови.get(верига, беше)
            if беше > 0 and (беше - стана) / беше >= печалба:
                бележки.append(
                    f"{верига}: {ако} → {ако + 1} екипа скъсява от {беше:.0f} "
                    f"на {стана:.0f} дни ({100 * (беше - стана) / беше:.0f}%) "
                    "— добавям")
                текущи, обхвати, промяна = проба, нови, True
                break
        if not промяна:
            break

    if not бележки:
        бележки.append("Още екипи не биха скъсили нищо съществено.")
    return текущи, бележки


def crews_for_deadline(
    tasks: Iterable[dict],
    packages: Iterable[Any],
    available_days: int,
    *,
    max_crews: int = 12,
) -> tuple[dict[str, int], list[str]]:
    """Колко екипа на верига, за да се събере работата в `available_days`.

    Returns:
        ({верига: екипи}, бележки) — бележките казват сметката, за да е
        проверима отвън, а не да излезе число без произход.
    """
    дни = max(int(available_days), 1)
    работа = work_by_chain(tasks, packages)
    екипи: dict[str, int] = {}
    бележки: list[str] = []

    for верига, дела in sorted(работа.items(), key=lambda kv: -kv[1]):
        нужни = max(1, math.ceil(дела / дни))
        ограничени = min(нужни, max_crews)
        екипи[верига] = ограничени
        бележки.append(
            f"{верига}: {дела:.0f} екипо-дни ÷ {дни} налични = "
            f"{ограничени} екипа" + ("" if ограничени == нужни
                                     else f" (таван {max_crews}, искаха се {нужни})"))

    if екипи:
        бележки.insert(0, f"Срокът е ЗАДАДЕН ({дни} дни) — броят екипи се "
                          f"изчислява от него: общо {sum(екипи.values())}.")
    for бележка in бележки:
        logger.info("%s", бележка)
    return екипи, бележки


def declared_crews_for(изчислени: dict[str, int] | int) -> dict[str, int] | None:
    """Обявените от изпълнителя екипи, ако е обявил — иначе None.

    ВЪПРОСЪТ Е „КОЛКО ЕКИПА СЕ ПРЕДВИЖДАТ" (изпълнителят, 19.08.2026), а
    отговорът е едно число: толкова екипа на верига.  Точно това значи и
    `assign_fronts` — фронтовете са по верига, не общо за обекта.

    Обявеното НАДДЕЛЯВА: срокът е ограничение от процедурата, но с колко
    бригади ще се излезе в него е решение на изпълнителя.  Сметката остава
    видима, за да се вижда разликата.

    Args:
        изчислени: каквото дозирането е решило — за да се знаят кои вериги има.
    """
    from src.tender_parameters import declared, declared_crews

    параметри = declared()
    поименно = параметри.get("crews")
    if isinstance(поименно, dict) and поименно:
        return {str(к): int(n) for к, n in поименно.items()
                if str(n).isdigit() and int(n) > 0} or None

    # И ОТ СРЕДАТА (25.08.2026).  `CREWS=water_section:2,sewer_section:2` се
    # четеше от `tender_parameters.declared_crews`, но НИКОЙ не го питаше —
    # тук се гледаха само отговорите от въпросника.  Мерено на реален търг
    # (Тръстеник): човекът обяви 2+2 екипа, а сметката сложи 6 и 3 и темпото
    # излезе три пъти по-бавно от обявеното.
    от_средата = declared_crews()
    if от_средата:
        return от_средата

    брой = параметри.get("declared_teams")
    try:
        брой = int(брой)
    except (TypeError, ValueError):
        return None
    if брой <= 0:
        return None
    # Без срок дозирането връща едно число, а не речник по вериги — тогава
    # обявеното се прилага там, където числото и без това отива.
    if not isinstance(изчислени, dict) or not изчислени:
        return None
    return {в: брой for в in изчислени}
