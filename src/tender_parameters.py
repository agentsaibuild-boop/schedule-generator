"""Какво ТРЯБВА да се пита за всяка процедура, вместо да се гадае.

Изпълнителят, 19.08.2026: „ти за всяка процедура трябва да питаш няколко неща:
кое е първо В или К, В как се полага — на изкоп или безизкопно, колко екипа се
предвиждат за изпълнението".

Всяко от тях е решение на изпълнителя за КОНКРЕТНИЯ обект, не находка в
документите.  Опитите да се извадят от текста се провалят по един и същи
начин: КСС мълчи („Реконструкция на разпределителната мрежа"), а еталонът е
друг обект.  Затова тук се ЧЕТАТ, а приложението трябва да ги пита.

Стойностите по подразбиране идват от еталона за Илиянци и всяка носи защо:

  РЕД — водата е първа.  Проверено в човешкия график: от 34 участъка с двете
  мрежи, в 15 водата тръгва първа, в 15 заедно и само в 4 каналът пръв.

  МЕТОД — сондаж.  23 безизкопни задачи, точно колкото са водопроводните
  участъци.

  ТЕМПО — 8.6 м/ден на екип за целия цикъл по водопровода (изпълнителят).
  За сравнение еталонът дава 417 екипо-дни за 3247 м = 7.8 м/ден.

  ЕКИПИ — не се задават: изчисляват се от срока (`crew_sizing`).  Ако
  изпълнителят каже колко има, числото му е по-силно от сметката.
"""

from __future__ import annotations

import contextlib
import os
from typing import Any

#: Кое се строи първо в един участък.
ПЪРВО_ВОДА = "В"
ПЪРВО_КАНАЛ = "К"

#: Отговорите на въпросника за ТЕКУЩИЯ прогон.  Празно значи „никой не е питан"
#: и важи `.env`.  Държи се тук, а не се преплита през двайсет подписа, защото
#: същите функции вече се четат отвсякъде — виж `for_this_run`.
_ТЕКУЩИ: dict[str, Any] = {}


@contextlib.contextmanager
def for_this_run(параметри: dict[str, Any] | None):
    """Отговорите на изпълнителя важат за този прогон и само за него.

    ЗАЩО СЪЩЕСТВУВА (19.08.2026).  Въпросникът питаше кое е първо В или К и
    колко екипа, но отговорът стигаше само до промпта на модела.  На
    детерминистичния път — който е по подразбиране — той нямаше НИКАКЪВ ефект,
    а методът на полагане изобщо не се питаше: четеше се от `.env`.  Тоест
    графикът, който мерим, работникът не можеше да получи от приложението.

    Контекстът се затваря след прогона, за да не изтече в следващия: два
    проекта в една сесия не бива да делят отговори.
    """
    global _ТЕКУЩИ
    предишни = _ТЕКУЩИ
    _ТЕКУЩИ = dict(параметри or {})
    try:
        yield _ТЕКУЩИ
    finally:
        _ТЕКУЩИ = предишни


def declared() -> dict[str, Any]:
    """Какво е обявено за този прогон (празно, ако не е питано)."""
    return dict(_ТЕКУЩИ)


def order_of_networks() -> str:
    """„В" или „К" — коя мрежа тръгва първа в участъка."""
    обявен = str(_ТЕКУЩИ.get("network_order") or "").strip().upper()
    ред = обявен or str(os.getenv("NETWORK_ORDER", ПЪРВО_ВОДА) or "").strip().upper()
    return ПЪРВО_КАНАЛ if ред.startswith(("К", "K")) else ПЪРВО_ВОДА


def laying_method() -> str:
    """Как се полага водопроводът: „hdd" (безизкопно) или „" (открит изкоп).

    Питаният отговор НАДДЕЛЯВА над `.env`; липсата на отговор пада към него.
    """
    обявен = str(_ТЕКУЩИ.get("laying_method") or "").strip().lower()
    return обявен or str(os.getenv("LAYING_METHOD", "") or "").strip().lower()


def declared_pace(chain: str) -> float | None:
    """Обявено темпо за верига, м/ден на екип за ЦЕЛИЯ ѝ цикъл.

    Чете се от `PACE_<ВЕРИГА>` (напр. `PACE_WATER=8.6`).  Нула или липса значи
    „не е обявено" — тогава важат нормите по стъпки.
    """
    обявени = _ТЕКУЩИ.get("pace")
    if isinstance(обявени, dict) and chain in обявени:
        try:
            темпо = float(обявени[chain])
        except (TypeError, ValueError):
            темпо = 0.0
        return темпо if темпо > 0 else None

    ключ = {"water_section": "PACE_WATER", "water_section_hdd": "PACE_WATER",
            "sewer_section": "PACE_SEWER"}.get(chain)
    if not ключ:
        return None
    try:
        темпо = float(os.getenv(ключ, "") or 0)
    except ValueError:
        return None
    return темпо if темпо > 0 else None


def sub_project() -> str:
    """Кой подобект е предмет на процедурата, ако чертежът покрива няколко.

    Проектите често са по-големи от търга и клоновете го казват в името си:
    „КЛ.24а-**И**" е кв. Илиянци, „КЛ.16-**Р**" е бул. Рожен, „**ПЗ**-КЛ.4" е
    промишлената зона.  Измерено 21.08.2026: водопроводният чертеж дава 8431 м
    при 3249 м по спецификация, а тя пише изрично „на кв. Илиянци".

    Кой подобект е нашият пише в спецификацията, не в чертежа — затова се
    ПИТА, а не се гадае.  Празно значи „вземи всичко".

    Returns:
        Наставката („И", „Р") или префиксът („ПЗ"), или празен низ.
    """
    обявен = _ТЕКУЩИ.get("sub_project")
    if обявен in (None, ""):
        обявен = os.getenv("SUB_PROJECT", "")
    return str(обявен or "").strip()


def contract_days() -> int:
    """Договорният срок за СТРОИТЕЛСТВОТО в календарни дни, ако е обявен.

    ЗАЩО ГО ИМА.  Броят екипи не се избира — изчислява се така, че графикът да
    се побере в срока (`crew_sizing.crews_for_deadline`).  Дотук срокът се
    четеше САМО от ред в количествената сметка тип „ПРОЕКТИРАНЕ 120 Календарни
    Дни".  Измерено 21.08.2026 върху реалния търг: такъв ред НЯМА нито в
    техническата спецификация (30 реда), нито в количествената сметка (70
    реда) — и в двата случая срокът излиза 0.

    Тоест машинарията за оразмеряване на екипите не се задействаше никога:
    падаше се на подадения брой (2) и срокът ставаше СЛЕДСТВИЕ вместо ЦЕЛ —
    1034 дни при 780 по договор.

    Срокът стои в обявлението и в проекта на договор, не в сметката.  Затова е
    четвъртият въпрос към изпълнителя, наред с реда на мрежите, метода и
    екипите.

    Returns:
        Дни, или 0 когато не е обявен.
    """
    обявен = _ТЕКУЩИ.get("contract_days")
    if обявен in (None, ""):
        обявен = os.getenv("CONTRACT_DAYS", "")
    try:
        дни = int(float(str(обявен).strip() or 0))
    except (TypeError, ValueError):
        return 0
    return дни if дни > 0 else 0


def declared_crews() -> dict[str, int]:
    """Колко екипа е обявил изпълнителят, ако е обявил.

    Формат: `CREWS=water_section_hdd:2,sewer_section:3`.  Каквото е казано,
    е по-силно от изчисленото — човекът знае с какво разполага.
    """
    обявени = _ТЕКУЩИ.get("crews")
    if isinstance(обявени, dict) and обявени:
        return {str(к): int(n) for к, n in обявени.items()
                if str(n).isdigit() and int(n) > 0}

    сурово = str(os.getenv("CREWS", "") or "").strip()
    ако: dict[str, int] = {}
    for част in сурово.split(","):
        ако_части = част.split(":")
        if len(ако_части) != 2:
            continue
        име, брой = ако_части[0].strip(), ако_части[1].strip()
        if име and брой.isdigit() and int(брой) > 0:
            ако[име] = int(брой)
    return ако


def describe() -> list[str]:
    """Какво е прието за този прогон — за да се вижда, не да се подразбира."""
    ред = order_of_networks()
    метод = laying_method() or "не е обявен (важи откритият изкоп)"
    редове = [
        f"Ред на мрежите: първо {'водопровод' if ред == ПЪРВО_ВОДА else 'канализация'}.",
        f"Метод на полагане на водопровода: {метод}.",
    ]
    дни = contract_days()
    редове.append(f"Договорен срок за строителството: {дни} дни." if дни
                  else "Договорен срок: НЕ Е ОБЯВЕН — екипите не се "
                       "оразмеряват по него и срокът излиза какъвто се получи.")
    подобект = sub_project()
    if подобект:
        редове.append(f"Подобект на процедурата: „{подобект}\" — клоновете на "
                      "другите подобекти не влизат.")
    екипи = declared_crews()
    редове.append(
        "Екипи: " + (", ".join(f"{к}×{n}" for к, n in sorted(екипи.items()))
                     if екипи else "изчисляват се от срока."))
    for верига in ("water_section", "sewer_section"):
        темпо = declared_pace(верига)
        if темпо:
            редове.append(f"Обявено темпо за {верига}: {темпо:g} м/ден на екип.")
    return редове
