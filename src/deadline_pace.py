"""Производителността идва от СРОКА и ЕКИПИТЕ, а не от норми.

НОВО ОСНОВНО ПРАВИЛО (изпълнителят, 24.08.2026), дословно:

    „От сега напред приемаш, че НЯМА НОРМИ за полагане на тръби.  Запознаваш се
     с документацията на тръжната процедура и ако в методите на оценяване е
     заложена оценка за оценяване на графика, питаш човека какви норми да
     сложиш.  Ако няма оценка на графика — приемаш крайния срок за изпълнение
     на обекта за даденост и задаваш въпрос към човека: с колко екипа ще се
     работи, и след това: паралелно ли ще работят екипите.  След като имаш тази
     информация, изчисляваш на база срока за изпълнение и броя на екипите каква
     е производителността и разпределяш по дните."

ЗАЩО ТОВА Е ПО-ЧЕСТНО ОТ НОРМИ.  Нормите ни са от ЕДИН обект и никой не ги е
потвърдил: 119 от 189 стойности идват от Илиянци, а за 29% от диаметрите в
реален търг норма изобщо няма — там продължителността пада на медиана и срокът
става недоказуем.  Срокът в процедурата, обратно, е ОБЯВЕН и обвързващ, а броят
екипи го знае изпълнителят.  От тези две числа темпото се ИЗЧИСЛЯВА, вместо да
се твърди.

    паралелно (поточна линия):   темпо = метри ÷ (дни × екипи)
    последователно:              темпо = метри ÷ дни

Разликата е в това дали вторият екип добавя фронт, или чака първия.  „Паралелно
= да" значи, че всички операции текат едновременно — изкопът на един участък
върви, докато на друг се полага.

ЧИСЛОТО СЕ ОБЯВЯВА.  То е следствие от срока, не измерена производителност, и
графикът трябва да го казва — иначе изглежда като норма, каквато не е.
"""

from __future__ import annotations

import logging
import os
from typing import Any, Iterable

logger = logging.getLogger(__name__)

#: Изключване на правилото — тогава важат нормите от productivities.json.
#: Съществува, за да може разликата да се МЕРИ, а не за да се ползва наум.
ФЛАГ = "PACE_FROM_DEADLINE"

#: Вериги, за които темпото има смисъл: линейна работа по трасе.
_ЛИНЕЙНИ_ВЕРИГИ = ("sewer_section", "water_section", "water_section_hdd")


def включено() -> bool:
    """Дали производителността се извежда от срока.  По подразбиране ДА."""
    return str(os.getenv(ФЛАГ, "1") or "1").strip() not in ("0", "false", "no")


def _метри_по_верига(packages: Iterable[Any]) -> dict[str, float]:
    from src.segment_scale import _линейни_метри

    метри: dict[str, float] = {}
    for pkg in packages or []:
        верига = str(getattr(pkg, "chain", None)
                     or (pkg.get("chain") if isinstance(pkg, dict) else "") or "")
        if верига:
            метри[верига] = метри.get(верига, 0.0) + _линейни_метри(pkg)
    return метри


#: ПОД НА ТЕМПОТО, м/ден на екип (изпълнителят, 26.08.2026).
#:
#: ЗАЩО ГО ИМА.  Темпото се извежда от срока и екипите: `метри ÷ дни ÷ екипи`.
#: Правилото е вярно, докато екипите отговарят на обекта.  Дадат ли се повече
#: екипи, отколкото метрите изискват, същото деление връща нереално бавно
#: темпо — Илиянци: 3247 м ÷ 660 дни ÷ 4 екипа = 1.2 м/ден — и оттам всеки
#: участък получава стотици дни.  Бригада не кара по метър на ден.
#:
#: Числата са на изпълнителя.  За сверка: корпусът от 24 негови изпълнени
#: графика дава 5.8 до 13.5 м/ден за целия цикъл на участък, медиана 9.4.
#:
#: Когато подът се задейства, това ЗНАЧИ, че екипите са повече, отколкото
#: обектът изисква — и се казва, а не се крие.
_ПОД_НА_ТЕМПОТО = {
    "water_section": 6.0,
    "water_section_hdd": 6.0,
    "sewer_section": 4.0,
}

#: ДОКАЗАНОТО ТЕМПО — не за да свива графика, а за да каже ИЗПЪЛНИМ ли е.
#:
#: Одиторът, 31.08.2026: „договорният срок е hard constraint; нормите и
#: историческите данни са feasibility check.  Ако bottom-up estimate е 245 дни,
#: системата не трябва тихо да произведе 210."
#:
#: Числата са ИЗМЕРЕНИ от корпуса на изпълнителя — 22 изпълнени графика, 77
#: участъка със записана дължина, темпо за ЦЕЛИЯ цикъл на участък:
#:
#:     25-и персентил  5.8 м/ден
#:     медиана         8.4 м/ден
#:     75-и персентил  9.8 м/ден
#:     максимум       14.4 м/ден
#:
#: Максимумът е ГРАНИЦАТА на наблюдаваното.  Темпо над него не е доказуемо от
#: нищо, с което разполагаме — не значи невъзможно, значи недоказано, и трябва
#: да се каже на човека, а не да се произведе мълчаливо.
ДОКАЗАНО_ТЕМПО = {
    "p25": 5.8,
    "median": 8.4,
    "p75": 9.8,
    "max": 14.4,
    "_източник": "22 изпълнени графика на изпълнителя, 77 участъка (26.08.2026)",
}


def feasibility(верига: str, темпо: float) -> tuple[str, str]:
    """(присъда, обяснение) за исканото темпо спрямо доказаното.

    Присъдите са три и са машинно проверими:

        FEASIBLE                 темпото е в наблюдавания диапазон
        REQUIRES_UPLIFT          над 75-и персентил, но под наблюдавания връх
        NOT_SUPPORTED_BY_DATA    над всичко, което сме виждали
    """
    връх = ДОКАЗАНО_ТЕМПО["max"]
    p75 = ДОКАЗАНО_ТЕМПО["p75"]
    медиана = ДОКАЗАНО_ТЕМПО["median"]

    if темпо <= p75:
        return ("FEASIBLE",
                f"{темпо:.2f} м/ден е в доказания диапазон "
                f"(медиана {медиана:g}, 75-и персентил {p75:g}).")
    надбавка = темпо / медиана - 1.0
    if темпо <= връх:
        return ("REQUIRES_UPLIFT",
                f"{темпо:.2f} м/ден иска {надбавка:.0%} над медианата от "
                f"корпуса ({медиана:g} м/ден).  Наблюдавано е до {връх:g}, "
                f"тоест постижимо, но не типично.")
    return ("NOT_SUPPORTED_BY_DATA",
            f"{темпо:.2f} м/ден е НАД всичко наблюдавано ({връх:g} м/ден) и "
            f"иска {надбавка:.0%} над медианата.  Нищо в 22-та изпълнени "
            f"графика не подкрепя такова темпо.")


def _какво_да_се_смени(дължина: float, days: int, екипи: int) -> str:
    """Какво трябва да се промени, за да стане искането изпълнимо."""
    p75 = ДОКАЗАНО_ТЕМПО["p75"]
    нужни = max(1, int(дължина / (p75 * days) + 0.999))
    добавка = нужни - екипи
    ако_дни = int(дължина / (p75 * max(екипи, 1)) + 0.999)
    части = []
    if добавка > 0:
        части.append(f"{добавка} екипа повече (общо {нужни})")
    части.append(f"или {ако_дни} дни вместо {days}")
    части.append("или друг метод/по-голямо застъпване")
    return "За да влезе в доказания диапазон трябва " + ", ".join(части) + "."


def derive(
    packages: Iterable[Any],
    *,
    days: int,
    crews: dict[str, int] | int,
    parallel: bool = True,
) -> tuple[dict[str, float], list[str]]:
    """Темпо на екип за всяка линейна верига, изведено от срока.

    Args:
        packages: Пакетите — от тях идват метрите по верига.
        days: Обявеният срок за строителството, календарни дни.
        crews: Екипи — общо число или по верига.
        parallel: Дали екипите работят едновременно.

    Returns:
        ({верига: м/ден на екип}, бележки).  Празно, когато срок няма, метри
        няма или правилото е изключено — тогава важат нормите.
    """
    if not включено() or days <= 0:
        return {}, []

    метри = _метри_по_верига(packages)
    темпа: dict[str, float] = {}
    бележки: list[str] = []

    for верига in _ЛИНЕЙНИ_ВЕРИГИ:
        дължина = метри.get(верига, 0.0)
        if дължина <= 0:
            continue
        екипи = (crews.get(верига, 1) if isinstance(crews, dict)
                 else max(int(crews or 1), 1))
        екипи = max(int(екипи or 1), 1)
        работни_дни = days * екипи if parallel else days
        темпо = дължина / работни_дни
        if темпо <= 0:
            continue
        под = _ПОД_НА_ТЕМПОТО.get(верига, 0.0)
        под_задейства = под > 0 and темпо < под
        ако_беше = темпо
        if под_задейства:
            темпо = под
        темпа[верига] = темпо
        бележки.append(
            f"{верига}: {дължина:.0f} м ÷ {days} дни"
            + (f" ÷ {екипи} екипа" if parallel and екипи > 1 else "")
            + f" = {ако_беше:.2f} м/ден на екип — ИЗВЕДЕНО ОТ СРОКА, не норма."
            + ("" if parallel else "  Екипите работят последователно, затова "
                                   "броят им не скъсява срока."))
        if под_задейства:
            стигат = max(1, int(дължина / (под * days) + 0.999))
            бележки.append(
                f"{верига}: темпото {ако_беше:.2f} м/ден е под реалното — "
                f"вдигнато до пода от {под:g} м/ден.  Това значи, че {екипи} "
                f"екипа са ПОВЕЧЕ, отколкото обектът изисква: за {дължина:.0f} м "
                f"в {days} дни стигат {стигат}.")

        # ПРОВЕРКА ЗА ИЗПЪЛНИМОСТ — отделна от сметката, нарочно.  Сметката
        # казва КАКВО темпо иска срокът; тази проверка казва ПОДКРЕПЯТ ЛИ ГО
        # данните.  Мълчаливо произведен график с недоказуемо темпо е точно
        # това, срещу което одиторът предупреди.
        присъда, обяснение = feasibility(верига, темпо)
        if присъда != "FEASIBLE":
            бележки.append(f"{верига}: {присъда} — {обяснение}  "
                           + _какво_да_се_смени(дължина, days, екипи))

    if темпа:
        бележки.append(
            "Нормите за полагане НЕ участват: производителността е следствие "
            "от обявения срок и заявените екипи (правило от 24.08.2026).")
    for бележка in бележки:
        logger.info("%s", бележка)
    return темпа, бележки
