"""Непрекъснатите дейности: работа, която върви ПОКРАЙ строежа, не в него.

ЗАЩО СЪЩЕСТВУВА ТОЗИ МОДУЛ (19.08.2026).  Сравнението с еталонния човешки
график ги показа едно до едно.  Настилките:

    човекът        основен пласт 46 задачи / 131 дни, тротоар 69 / 250,
                   бордюри — ЕДНА задача от 595 дни
    ние            kerbs 95 / 439, sidewalk 95 / 278, asphalt 95 / 124,
                   base_course 95 / 95

Сборът и едновременността съвпадат (936 срещу 976 екипо-дни, 1.6 срещу 1.5).
Разликата е СТРУКТУРНА: човекът НЕ разделя работата по лист „4. Пътна" на
участъци.  Задача UID 5653 се казва буквално „Възстановяване на пътна настилка
извън траншеен изкоп … (асфалтова/паважна настилка), вкл.полагане на средни
бет.бордюри и бет.плочи" — тоест изброява и трите реда от този лист поименно —
и трае 595 дни с ЕДИН предшественик.

Тя не е сама: в еталона има шест такива непрекъснати задачи (авторски надзор
660 дни, опазване на околната среда 658, лабораторни изпитвания 658, актове по
Наредба №3 653, доставка на материали 646, настилката 595).  Всичките описват
присъствие на обекта, а не производствен такт.  Затова тук се нарича level of
effort и се държи като надзора: НЕ влиза в твърдото ресурсно изравняване.

Какво НЕ прави: не пипа `base_course`.  В еталона основният пласт си остава 46
отделни задачи — това е възстановяването В траншеята, участък по участък.
Обединява се само работата ИЗВЪН нея.

Обединената задача носи `source_refs` — няколко цитата, не един.  Иначе описът
щеше да види едно от трите количества и КСС щеше да излезе непокрит.  Виж
`provenance.citation_units`.
"""

from __future__ import annotations

import logging
import os
from typing import Any

logger = logging.getLogger(__name__)

#: Изключва обединяването и връща поведението „задача на участък".
_ФЛАГ = "ROAD_WORKS_LOE"


def merged_into_level_of_effort(task: dict) -> bool:
    """Дали задачата е непрекъсната дейност (level of effort).

    Едно правило за трите места, които го питат: ресурсното изравняване,
    проверката за претоварване и мереното.
    """
    return bool(isinstance(task, dict) and task.get("level_of_effort"))


def _цяло(стойност: Any, по_подразбиране: int = 0) -> int:
    try:
        return int(float(стойност))
    except (TypeError, ValueError):
        return по_подразбиране


def _число(стойност: Any) -> float | None:
    try:
        return float(стойност)
    except (TypeError, ValueError):
        return None


def _описание_на_реда(задача: dict) -> str:
    """Името на задачата, изчистено от стъпката и от етапа.

    Задачата се казва „<стъпка> — <ред от КСС> — <етап N от M>".  В описа обаче
    цитатът трябва да чете като реда, който цитира: обединената дейност покрива
    ЦЕЛИЯ ред, а „Етап 1 от 32" е остатък от първия ѝ член и заблуждава.
    Махат се само двете известни части — каквото не се разпознае, остава.
    """
    име = str(задача.get("name") or "").strip()
    стъпка = str(задача.get("chain_step_name") or "").strip()
    if стъпка and име.startswith(стъпка + " — "):
        име = име[len(стъпка) + 3:]
    етап = str(задача.get("alignment_id") or "").split(" [")[0].strip()
    if етап and име.endswith(" — " + етап):
        име = име[: -(len(етап) + 3)]
    return име.strip()


def _цитати(задача: dict) -> list[dict]:
    """Цитатите, които една задача внася в обединената."""
    налични = задача.get("source_refs")
    if isinstance(налични, list) and налични:
        return [c for c in налични if isinstance(c, dict) and c.get("ref")]
    ref = str(задача.get("source_ref") or "").strip()
    if not ref:
        return []
    return [{
        "ref": ref,
        "quantity": _число(задача.get("quantity")),
        "unit": задача.get("unit"),
        "name": _описание_на_реда(задача) or задача.get("name"),
        "activity_class_hint": задача.get("activity_class_hint"),
        "source_record_id": задача.get("source_record_id"),
    }]


def _събери_цитати(членове: list[dict]) -> list[dict]:
    """Сборът по ред: три реда от КСС, а не 285 отделни цитата.

    Количествата се СЪБИРАТ по ред, защото обединената задача покрива точно
    толкова, колкото покриваха частите ѝ.  Ако сборът се загубеше, редът щеше
    да излезе непокрит и Σ=КСС щеше да падне върху напълно вярна работа.
    """
    по_ред: dict[str, dict] = {}
    for задача in членове:
        for цитат in _цитати(задача):
            ref = str(цитат["ref"])
            запис = по_ред.get(ref)
            ново = _число(цитат.get("quantity"))
            if запис is None:
                запис = dict(цитат)
                запис["quantity"] = ново
                по_ред[ref] = запис
            elif ново is not None:
                запис["quantity"] = (_число(запис.get("quantity")) or 0.0) + ново
    return [по_ред[r] for r in sorted(по_ред)]


def merge_level_of_effort(
    tasks: list[dict], chains: dict[str, Any] | None
) -> tuple[list[dict], list[str]]:
    """Обедини стъпките, обявени за непрекъснати, в по една задача на верига.

    Пуска се СЛЕД ресурсното изравняване и СЛЕД налагането на обхвата на
    надзора: обединената задача взима вече изчислените дати на частите си,
    затова нито удължава, нито скъсява срока.  Обхватът ѝ е техният обхват.

    Args:
        tasks: Готовият график (не се мутира).
        chains: Технологичните вериги; всяка може да носи `level_of_effort`.

    Returns:
        (нов график, обяснения за прогреса)
    """
    if os.getenv(_ФЛАГ, "1").strip() == "0":
        return tasks, []
    if not tasks or not isinstance(chains, dict):
        return tasks, []

    # `load_chains` връща ЦЕЛИЯ файл, а тестовете подават само речника с
    # веригите.  Приемат се и двете — иначе мълчаливо не би се обединило нищо.
    вътрешни = chains.get("chains")
    речник = вътрешни if isinstance(вътрешни, dict) else chains

    бележки: list[str] = []
    резултат = list(tasks)

    for верига, описание in sorted(речник.items()):
        if not isinstance(описание, dict):
            continue
        блок = описание.get("level_of_effort")
        if not isinstance(блок, dict):
            continue
        стъпки = {str(s) for s in (блок.get("steps") or []) if s}
        if not стъпки:
            continue
        мрежа = str(описание.get("network") or "").strip()

        членове = [t for t in резултат
                   if isinstance(t, dict)
                   and str(t.get("chain_step") or "") in стъпки
                   and (not мрежа or str(t.get("network") or "") == мрежа)]
        # Една задача вече Е непрекъсната дейност — няма какво да се обединява.
        if len(членове) < 2:
            continue

        обединена, бележка = _обедини(членове, резултат, верига, описание, блок)
        бележки.append(бележка)
        if обединена is None:
            continue

        изчезнали = {str(t.get("id")) for t in членове}
        останали = [t for t in резултат if str(t.get("id")) not in изчезнали]
        _пренасочи(останали, изчезнали, str(обединена["id"]))
        резултат = останали + [обединена]

    return резултат, бележки


def _обедини(
    членове: list[dict],
    всички: list[dict],
    верига: str,
    описание: dict,
    блок: dict,
) -> tuple[dict | None, str]:
    начало = min(_цяло(t.get("start_day"), 1) for t in членове)
    край = max(_цяло(t.get("end_day"), 1) for t in членове)
    if край < начало:
        return None, (f"{верига}: непрекъснатата дейност НЕ е обединена — "
                      f"частите ѝ нямат смислени дати.")

    изчезнали = {str(t.get("id")) for t in членове}
    по_ид = {str(t.get("id")): t for t in всички}

    # ЕДИН предшественик, както в еталона.  Частите имат по един всяка (95
    # основни пласта), но обединената НЕ чака всички — тя тръгва щом първият
    # участък ѝ отвори фронт.  Затова се взима последният предшественик, който
    # свършва ПРЕДИ началото: връзката остава доказуема, а датата — същата.
    кандидати: list[tuple[int, str]] = []
    for задача in членове:
        for връзка in (задача.get("dependencies") or []):
            if not isinstance(връзка, dict):
                continue
            pid = str(връзка.get("predecessor_id") or "")
            if not pid or pid in изчезнали:
                continue
            предшественик = по_ид.get(pid)
            if предшественик is None:
                continue
            край_на_предшественика = _цяло(предшественик.get("end_day"), 0)
            if край_на_предшественика < начало:
                кандидати.append((край_на_предшественика, pid))
    зависимости: list[dict] = []
    if кандидати:
        _, pid = max(кандидати)
        зависимости = [{"predecessor_id": pid, "type": "FS", "lag_days": 0,
                        "reason": "Възстановяването извън траншеята тръгва щом "
                                  "първият участък отвори фронт"}]

    цитати = _събери_цитати(членове)
    бригада = str(блок.get("crew_label") or "Пътна бригада")
    мрежа = str(описание.get("network") or "").strip() or "LOE"
    корен = str(описание.get("wbs_root") or "construction")
    обединена = {
        "id": f"{мрежа}_LOE",
        "name": str(блок.get("name") or описание.get("label") or верига),
        "chain_step": "level_of_effort",
        "chain_step_name": str(блок.get("name") or ""),
        # КОЯ верига и КОИ стъпки са влезли вътре: без това проверката за
        # пълнота на шаблона би търсила стъпките под пакетите, където вече
        # ги няма, и би обявила пълен график за непълен.
        "chain": верига,
        "merged_steps": sorted({str(t.get("chain_step") or "") for t in членове}),
        "type": "task",
        "parent_id": f"WBS_{корен.upper()}",
        "wbs_root": корен,
        "network": описание.get("network") or "",
        "duration": край - начало + 1,
        "start_day": начало,
        "end_day": край,
        "duration_source": "level_of_effort",
        "duration_status": "SPAN",
        "dependencies": зависимости,
        "resources": list(блок.get("crew") or []),
        "team": бригада,
        "crew_id": бригада,
        "level_of_effort": True,
        "source_refs": цитати,
        "merged_task_count": len(членове),
    }
    # РАБОТНОТО СЪДЪРЖАНИЕ не бива да изчезне в обхвата.  Продължителността на
    # обединената задача е СРОК на присъствие, а колко работа стои вътре идва
    # от нормите — това е числото, с което одиторът дели, за да види колко
    # бригади предполага редът.  Без него „553 дни" не значи нищо.
    работа = sum(_число(t.get("duration")) or 0.0 for t in членове)
    бригади = работа / max(обединена["duration"], 1)
    обединена["merged_work_days"] = round(работа, 1)
    обединена["implied_crews"] = round(бригади, 2)
    обединена["note"] = (
        f"Непрекъсната дейност: обединява {len(членове)} задачи по участък в "
        f"един ред, както е в еталонния график.  Работното съдържание по нормите "
        f"е {работа:.0f} екипо-дни в {обединена['duration']} дни присъствие, "
        f"тоест {бригади:.1f} бригади средно.")
    бележка = (f"Непрекъсната дейност: {len(членове)} задачи → 1 ред, "
               f"дни {начало}–{край} ({обединена['duration']}), "
               f"{работа:.0f} екипо-дни работа, {len(цитати)} цитирани реда.")
    return обединена, бележка


def _пренасочи(задачи: list[dict], изчезнали: set[str], към: str) -> None:
    """Който е чакал някоя от частите, вече чака обединената.

    Дублиращите се връзки се свиват до една: 95 връзки към 95 асфалтови задачи
    стават една връзка към непрекъснатата дейност.
    """
    for задача in задачи:
        връзки = задача.get("dependencies")
        if not isinstance(връзки, list) or not връзки:
            continue
        нови: list[dict] = []
        добавена = False
        for връзка in връзки:
            if not isinstance(връзка, dict):
                нови.append(връзка)
                continue
            if str(връзка.get("predecessor_id") or "") not in изчезнали:
                нови.append(връзка)
                continue
            if добавена:
                continue
            заместител = dict(връзка)
            заместител["predecessor_id"] = към
            нови.append(заместител)
            добавена = True
        задача["dependencies"] = нови
