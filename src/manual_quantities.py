"""Количествата, въведени на ръка — когато файл няма или не се чете.

ЗАЩО.  Приложението умее да чете тръжни документи: спецификация, количествена
сметка, ситуационни чертежи, стар двоичен `.doc`.  Но човек, който иска да
пробне срока за обект, който още няма документация — или чиито документи не се
четат — нямаше как да влезе изобщо.  А за линеен график трябват около
четиринайсет числа: дължини по диаметър и материал, бройки на съоръженията и
площи за възстановяване.

КАК.  Въведеното се записва като ТАБЛИЦА в папката на проекта и оттам нататък
минава по СЪЩИЯ път като всеки друг документ — конверсия, индекс, произход.
Никакъв втори вход, никакъв специален случай надолу по веригата: редът, въведен
на ръка, се цитира като „Ръчно въведени количества.csv!количества!7", и това е
вярно.

ОПИСАНИЕТО НЕ Е СВОБОДЕН ТЕКСТ.  Мрежата, диаметърът, материалът и методът се
четат от ОПИСАНИЕТО на реда надолу по веригата (`_network_of_row`,
`detect_dn`, `detect_material`, `detect_method`).  Затова тук то се СГЛОБЯВА от
структурни полета, вместо да се иска от човека — иначе „ф300 пп" минава за ред
без диаметър и без материал, а грешката излиза чак в графика.
"""

from __future__ import annotations

import csv
import io
import logging
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

logger = logging.getLogger(__name__)

#: Името на файла.  Разпознава се като таблица с количества по „количества" в
#: името (`file_manager._REQUIRED_KEYWORDS`), затова не се налага да се
#: преструва на КСС.
ИМЕ_НА_ФАЙЛА = "Ръчно въведени количества.csv"

#: Заглавията на колоните — тези, които индексът разпознава (`provenance`).
_КОЛОНИ = ("Описание", "Количество", "Мярка")

#: Мрежа → думата, по която редът се разпознава като нейн.
_МРЕЖИ = {"К": "канализационни", "В": "водопроводни"}

#: Точкова позиция → как се изписва, за да я хванат класът, нормата И МРЕЖАТА.
#:
#: Мрежата е в текста нарочно (проба 24.08.2026): „Ревизионни шахти (РШ)" сам
#: по себе си не казва на коя мрежа е, а тук няма лист и няма име на файл, от
#: които да се извади — тоест позицията остава без верига и някой по-надолу
#: трябва да я разпределя наслуки.
ТОЧКОВИ = {
    "РШ": "Ревизионни шахти (РШ) по канализационната мрежа",
    "СРС": "Сградни ревизионни шахти (СРС) по канализационната мрежа",
    "СКО": "Сградни канализационни отклонения (СКО)",
    "СВО": "Сградни водопроводни отклонения (СВО)",
    "УО": "Улични оттоци (УО) по канализационната мрежа",
}

#: Площна/линейна работа по възстановяване → изписване и мярка.
ВЪЗСТАНОВЯВАНЕ = {
    "асфалт": ("Възстановяване на асфалтова настилка", "кв.м"),
    "унипаваж": ("Полагане на тротоарни плочи (унипаваж)", "кв.м"),
    "бордюри": ("Доставка и полагане на бетонови бордюри", "м"),
}


@dataclass(frozen=True)
class Тръба:
    """Един ред тръби: мрежа, диаметър, материал, метод, дължина."""

    network: str          #: „В" | „К"
    dn: int
    material: str         #: PE | PP | PVC | CI | GRP
    length_m: float
    method: str = "open"  #: „open" | „HDD"

    def описание(self) -> str:
        """Редът, както ще го прочете конвейерът — и както го чете човек.

        Всяка дума тук работи: „Полагане" дава класа, „канализационни" —
        мрежата, „DN 300" — диаметъра, „PP" — материала, „безизкопно" — метода.
        """
        мрежа = _МРЕЖИ.get(str(self.network).upper().strip(), "")
        части = ["Полагане на"]
        if мрежа:
            части.append(мрежа)
        части.append("тръби")
        if self.material:
            части.append(str(self.material).upper())
        части.append(f"DN {int(self.dn)}")
        if str(self.method).upper() == "HDD":
            части.append("— безизкопно (сондаж)")
        return " ".join(части)


def _редове(тръби: Iterable[Тръба], точкови: dict, възстановяване: dict) -> list[tuple]:
    """Всичко въведено, като редове (описание, количество, мярка).

    Нулите НЕ влизат: нула броя шахти не е количество, а липса на такова, и
    ред с нула би „покрил" работа, която никой няма да свърши.
    """
    редове: list[tuple] = []

    for тръба in тръби or []:
        дължина = float(тръба.length_m or 0)
        if дължина <= 0 or int(тръба.dn or 0) <= 0:
            continue
        редове.append((тръба.описание(), round(дължина, 2), "м"))

    for ключ, брой in (точкови or {}).items():
        позиция = ТОЧКОВИ.get(ключ)
        число = float(брой or 0)
        if not позиция or число <= 0:
            continue
        редове.append((позиция, int(число), "бр"))

    for ключ, количество in (възстановяване or {}).items():
        запис = ВЪЗСТАНОВЯВАНЕ.get(ключ)
        число = float(количество or 0)
        if not запис or число <= 0:
            continue
        описание, мярка = запис
        редове.append((описание, round(число, 2), мярка))

    return редове


def as_csv(тръби: Iterable[Тръба], точкови: dict | None = None,
           възстановяване: dict | None = None) -> str:
    """Въведеното като CSV — същият формат, който конверторът вече чете."""
    буфер = io.StringIO()
    писач = csv.writer(буфер, delimiter=";", lineterminator="\n")
    писач.writerow(_КОЛОНИ)
    for ред in _редове(тръби, точкови or {}, възстановяване or {}):
        писач.writerow(ред)
    return буфер.getvalue()


def save(base_path: str | Path, тръби: Iterable[Тръба],
         точкови: dict | None = None,
         възстановяване: dict | None = None) -> Path:
    """Запиши таблицата в папката на проекта и върни пътя до нея.

    ПРЕЗАПИСВА се нарочно: човекът поправя своя лист, а не трупа версии, за
    които после да гадае коя е валидната.

    Raises:
        ValueError: когато няма нито едно количество — празен файл би минал за
            прочетен вход и генерирането би паднало по-надолу, с по-мъглява
            причина.
    """
    редове = _редове(тръби, точкови or {}, възстановяване or {})
    if not редове:
        raise ValueError("Няма въведено нито едно количество.")

    папка = Path(base_path)
    папка.mkdir(parents=True, exist_ok=True)
    път = папка / ИМЕ_НА_ФАЙЛА
    път.write_text(as_csv(тръби, точкови, възстановяване), encoding="utf-8-sig")
    logger.info("Ръчни количества: %d реда → %s", len(редове), път)
    return път
