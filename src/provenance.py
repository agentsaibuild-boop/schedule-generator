def _looks_like_description(text: str) -> bool:
    """Описанието е ТЕКСТ (≥2 букви), не пореден номер/код/число.

    Реален КСС „4. Пътна" (проба 2026-08-03): колона „Канализационна мрежа"
    пасва на _DESC_KEYS (заради „мрежа"), но държи номера „1", докато реалното
    описание е под разместен хедър „Ед. мярка".  Число за описание → негодно.
    """
    return bool(re.search(r"[^\W\d_].*[^\W\d_]", str(text or ""), re.UNICODE))


def _is_unit_like(value: Any) -> bool:
    """Дали клетката изобщо може да БЪДЕ мярка.

    Одит 07.08.2026: в експортирания XML стояха „Мярка = 100" (УО единичен),
    „Мярка = 1" (Преливна шахта) и цялото описание на дейността при пътните
    редове.  И трите идват от едно място — колоната се избираше по заглавие, а
    в реалния КСС под заглавие „Ед. мярка" стои ту броят, ту описанието
    (разместен хедър, лист „4. Пътна").

    Мярка не е голо число и не е изречение.
    """
    text = str(value or "").strip()
    if not text or not _looks_like_unit(text):
        return False
    # Само ГОЛО число дисквалифицира клетката.  `_number` вади число от текст
    # (за количествата това е нарочно), но тук би отхвърлило „m3/m'" заради
    # тройката — а точно съставната мярка на бетоновия кожух не бива да се губи.
    try:
        float(text.replace(",", "."))
    except ValueError:
        return True
    return False


def _pick_unit(row: dict) -> Any:
    """Мярката от реда, или „" ако нито една колона не носи мярка.

    Празно е честният отговор, когато КСС не казва мярката: `_norm_unit("")`
    не е реална единица, значи не поражда фалшиво разминаване надолу.  Число
    или описание на нейно място обвинява задачата за нещо, което документът
    никога не е твърдял.
    """
    _, value = _pick(row, _UNIT_KEYS, predicate=_is_unit_like)
    return value if _is_unit_like(value) else ""


#: Под тази дължина ключът трябва да съвпадне с ЦЯЛА дума в заглавието.
#:
#: ЗАЩО.  Проба 31.08.2026: добавих „ме" като съкращение за мярка и то съвпадна
#: вътре в „НаиМЕнование" — описанието на реда започна да минава за мярка.
#: Парче от дума е достатъчно за дълъг ключ („количеств" в „Количество"), но за
#: къс е капан, а капанът е тих: няма грешка, просто грешна колона.
_МИН_ДЪЛЖИНА_ЗА_ПАРЧЕ = 4

_РАЗДЕЛИТЕЛ = re.compile(r"[^\wа-яА-Я]+", re.UNICODE)


def _заглавието_пасва(header: str, keys: tuple[str, ...]) -> bool:
    """Дали заглавието на колоната поема някой от ключовете."""
    ниско = str(header or "").strip().lower()
    if not ниско:
        return False
    думи = {д for д in _РАЗДЕЛИТЕЛ.split(ниско) if д}
    for k in keys:
        ключ = k.strip().lower()
        if not ключ:
            continue
        if len(ключ) >= _МИН_ДЪЛЖИНА_ЗА_ПАРЧЕ:
            if ключ in ниско:
                return True
        # Късият ключ: цяло заглавие или цяла дума в него.  Разделителите в
        # самия ключ („м-ка", „м.е.") се махат, за да съвпадне с „м ка".
        elif ниско == ключ or {д for д in _РАЗДЕЛИТЕЛ.split(ключ) if д} <= думи:
            return True
    return False


def _pick(row: dict, keys: tuple[str, ...], prefer_numeric: bool = False,
          predicate: Callable[[Any], bool] | None = None) -> tuple[str, Any]:
    """Върни (име на колона, стойност) за колона, чието заглавие пасва.

    Одит v12 #5: предпочита се първата НЕПРАЗНА стойност (празна „Количество"
    не бива да засенчва попълнена „Дължина /m/").
    Одит v13: за КОЛИЧЕСТВО (`prefer_numeric=True`) се предпочита първата
    ЧИСЛОВА стойност — иначе текст като „вж. проект" в „Количество" засенчваше
    реалните 538 в „Дължина".
    """
    matches = [(str(c), v) for c, v in row.items()
               if _заглавието_пасва(str(c), keys)]
    if prefer_numeric:
        for col, val in matches:
            if _number(val) is not None:
                return col, val
    if predicate is not None:
        for col, val in matches:
            if predicate(val):
                return col, val
    for col, val in matches:
        if val is not None and str(val).strip():
            return col, val
    return matches[0] if matches else ("", None)


def stale_conversions(base_path: str | Path) -> list[str]:
    """Кои конвертирани файлове са по-стари от оригинала си.

    ОДИТ 10.08.2026, P0.1: изнесохме на одитора график, чиито цитати сочеха
    редове с четири назад.  Кодът беше верен — конверторът записва истинския
    Excel ред от одит v11.  Сгрешена беше ПАПКАТА: `converted/` беше останала
    от по-стара версия на конвертора и никой не я преобразува наново.

    Мълчаливо остарял индекс е най-лошият вид дефект тук, защото всичко
    надолу се сверява срещу самия него и излиза съгласувано.
    """
    base = Path(base_path)
    converted = base / "converted"
    if not converted.exists():
        return []

    stale: list[str] = []
    for json_file in converted.glob("*.json"):
        if json_file.name == "_manifest.json":
            continue
        originals = [p for p in base.glob(f"{json_file.stem}.*")
                     if p.suffix.lower() != ".json"]
        for original in originals:
            try:
                if original.stat().st_mtime > json_file.stat().st_mtime:
                    stale.append(original.name)
            except OSError:
                continue
    return sorted(set(stale))


def _warn_if_conversions_are_stale(base: Path, converted: Path) -> None:
    stale = stale_conversions(base)
    if stale:
        logger.warning(
            "Конвертираните данни са по-стари от оригиналите (%s) — цитатите "
            "може да сочат разместени редове.  Преобразувай наново.",
            ", ".join(stale))


#: Римско число, само по себе си в клетка: „I", „IV.", „VII" — номерът на
#: раздел в тръжна таблица.  Позициите вътре в раздела са с арабски.
_РИМСКО = re.compile(r"^(x{0,3})(ix|iv|v?i{0,3})\.?$", re.IGNORECASE)


def _е_римско(row: dict) -> bool:
    """Дали някоя клетка на реда държи само римско число (номер на раздел)."""
    for стойност in row.values():
        текст = str(стойност or "").strip()
        if текст and _РИМСКО.fullmatch(текст):
            return True
    return False


def _index_row(row: dict, document: str, sheet: str, row_no: int) -> QuantityRow | None:
    """Един ред от таблица → индексиран количествен ред, или None ако е празен.

    Общо за Excel листовете и за таблиците в DOCX: и двете стигат дотук като
    речник „заглавие на колона → клетка", затова правилото за разчитане е едно
    и също и се пише на едно място.

    Args:
        row: Редът като речник.
        document: Име на документа-източник.
        sheet: Име на листа или „таблица N".
        row_no: Номер на реда в източника, 1-базиран.

    Returns:
        `QuantityRow`, или None — когато редът няма никакво описание.
    """
    desc_col, description = _pick(row, _DESC_KEYS)
    qty_col, quantity = _pick(row, _QTY_KEYS, prefer_numeric=True)
    unit = _pick_unit(row)

    # Fallback за описанието: ако избраната колона е празна ИЛИ държи
    # само число/код (напр. пореден номер „1" под разместен хедър —
    # реален КСС „4. Пътна", проба 2026-08-03), вземи най-ДЪЛГАТА
    # БУКВЕНА клетка от реда.  Числата са количества/цени, не описания.
    description = str(description or "").strip()
    if not _looks_like_description(description):
        best = description
        for col, val in row.items():
            s = str(val or "").strip()
            if len(s) > len(best) and _looks_like_description(s):
                desc_col, best = str(col), s
        description = best
    if not description:
        return None

    return QuantityRow(
        description=description,
        quantity=_number(quantity),
        unit=str(unit or "").strip(),
        source=SourceRef(document, sheet, row_no, qty_col or desc_col),
        raw=row,
    )


#: Ролите и речниците им — на едно място, за да може да се ОДИТИРАТ.
РОЛИ_НА_КОЛОНИ: dict[str, tuple[str, ...]] = {
    "описание": _DESC_KEYS,
    "количество": _QTY_KEYS,
    "мярка": _UNIT_KEYS,
}


def _роля_на_заглавие(header: str) -> str:
    """Коя роля поема тази колона — или „" ако никоя."""
    ниско = str(header or "").strip().lower()
    if not ниско:
        return ""
    for роля, ключове in РОЛИ_НА_КОЛОНИ.items():
        if _заглавието_пасва(ниско, ключове):
            return роля
    return ""


