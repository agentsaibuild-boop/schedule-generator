class SourceRef(NamedTuple):
    """Точно място в документ."""

    document: str
    sheet: str = ""
    row: int | None = None
    column: str = ""

    def describe(self) -> str:
        parts = [self.document]
        if self.sheet:
            parts.append(f"лист '{self.sheet}'")
        if self.row is not None:
            parts.append(f"ред {self.row}")
        if self.column:
            parts.append(f"колона {self.column}")
        return ", ".join(parts)


class QuantityRow(NamedTuple):
    """Индексиран ред от количествена сметка."""

    description: str
    quantity: float | None
    unit: str
    source: SourceRef
    raw: dict

    @property
    def ref(self) -> str:
        """Устойчив идентификатор за цитиране: `КСС.xlsx!Водопровод!4`.

        Етап 2: вместо да търсим стойността назад по сходство, даваме на
        модела как да СОЧИ реда, от който взима числото.  После кодът
        проверява дали цитатът е верен.  Цитат + проверка е далеч по-силно
        от обратно сравнение по думи.
        """
        return f"{self.source.document}!{self.source.sheet}!{self.source.row}"

    @property
    def record_id(self) -> str:
        """Неизменен ключ на СЪДЪРЖАНИЕТО, независим от номера на реда.

        ОДИТ 10.08.2026, P0.1: цитатът беше само `документ!лист!ред`, а редът е
        най-крехкото нещо в един Excel файл — вмъкнат ред отгоре мести всичко
        отдолу.  По-лошото се случи наистина: изнесохме график, генериран върху
        конвертирани данни от СТАРА версия на конвертора, чиито номера бяха с
        4 реда назад спрямо файла.  Цитатите сочеха несъществуващи места, а
        нищо не изгърмя, защото цитатът се проверява само срещу същия индекс.

        Затова цитирането има две части с различна роля:

            `ref`        КЪДЕ е записано — за човек, който ще отвори файла
            `record_id`  КОЕ е записано — за машина, която сверява

        Хешът е върху документа, листа, описанието, количеството и мярката.
        Разместване на редове не го мени; смяна на количеството — да, и точно
        това трябва да се забележи.
        """
        payload = " | ".join((
            self.source.document,
            self.source.sheet,
            " ".join(str(self.description or "").split()).lower(),
            "" if self.quantity is None else format(float(self.quantity), ".6g"),
            str(self.unit or "").strip().lower(),
        ))
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()[:12]


def _tokens(text: str) -> set[str]:
    """Значещите думи за сравнение — с ОПРАВЕНА азбука.

    Тръжните документи носят латински букви вътре в кирилски думи (измерено
    31.08.2026: 68 думи в пакета на Илиянци, между тях `Kл`, `OТ`, `Бaлчо`).
    Такава дума не съвпада с чистия си двойник и редът от КСС остава без
    връзка — тихо, точно както се губеха клоновете в чертежа.
    """
    text = cyrillize(text or "")
    return {
        w.lower() for w in _WORD_RE.findall(text)
        if len(w) > 2 and w.lower() not in _STOPWORDS
    }


def similarity(a: str, b: str) -> float:
    """Дял на общите значещи думи (Jaccard).  0..1."""
    ta, tb = _tokens(a), _tokens(b)
    if not ta or not tb:
        return 0.0
    return len(ta & tb) / len(ta | tb)


def _number(value: Any) -> float | None:
    """Число от 420, '420', '1 240', '1,240.5'."""
    if isinstance(value, bool) or value is None:
        return None
    if isinstance(value, (int, float)):
        v = float(value)
        return v if math.isfinite(v) else None
    text = str(value).strip().replace(" ", "").replace(" ", "")
    if not text:
        return None
    # Български формат: 1.240,5 → 1240.5 ; английски: 1,240.5 → 1240.5
    if "," in text and "." in text:
        text = text.replace(".", "").replace(",", ".") if text.rfind(",") > text.rfind(".") \
            else text.replace(",", "")
    else:
        text = text.replace(",", ".")
    cleaned = re.sub(r"[^\d.\-]", "", text)
    if not cleaned or cleaned in ("-", ".", "-.", ".-"):
        return None
    try:
        v = float(cleaned)
    except ValueError:
        return None
    return v if math.isfinite(v) else None


