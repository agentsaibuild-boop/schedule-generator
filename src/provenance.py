def audit_columns(base_path: str | Path) -> list[dict]:
    """Кой лист какви колони има и КОЯ роля не е поета — за всеки лист.

    ЗАЩО СЪЩЕСТВУВА.  Дамяново, 31.08.2026: колоната за мярка се казваше
    „М-КА", речникът я нямаше, и 3148 реда се прочетоха с празна мярка — нула
    линейни метра, нула участъци, график, който не може да съществува.  И нито
    едно предупреждение, защото празна мярка е ЗАКОНЕН отговор, когато
    документът наистина мълчи.

    Разликата между „документът мълчи" и „ние не сме го чули" не може да се
    види от стойностите — само от ЗАГЛАВИЯТА.  Затова тук се гледат те:
    колона, която изглежда като данни и не се е вързала за роля, се обявява
    поименно.  Речникът ще остане непълен винаги; мълчанието не бива.

    Returns:
        По един запис на лист: {документ, лист, роли, непоети, редове,
        с_количество, с_мярка, тревога}.
    """
    converted = Path(base_path) / "converted"
    if not converted.exists():
        return []

    доклад: list[dict] = []
