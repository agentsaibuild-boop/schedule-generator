logger = logging.getLogger(__name__)


class Segment(NamedTuple):
    """Една отсечка от мрежата — това, което прави участъка участък."""

    network: str          #: „В" водопровод | „К" канализация
    branch: str           #: „Кл.48" / „ГЛ.КЛ. I"
    start_node: str       #: начален възел, ако документът го дава
    end_node: str
    length_m: float
    dn: int
    street: str
    source: str           #: документът, от който е прочетена
    in_scope: bool        #: влиза ли в ТАЗИ процедура (по легендата)
    scope_reason: str     #: КОЯ легендна позиция го реши


class Node(NamedTuple):
    """Точкова позиция от чертежа — шахта, отток, сградно отклонение.

    ТОЧКОВИТЕ ПОЗИЦИИ НЕ СА В ТРЪБНИЯ РЕД (изпълнителят, 24.08.2026): „трябва
    да си вземеш линейната дължина за В и К, с всички диаметри на тръбите,
    както и СВО, СКО, шахти, УО от техническата спецификация и чертежите".
    Дотук те влизаха САМО ако някоя таблица ги изброи; чертежът ги показваше и
    ги брояхме на нула.
    """

    kind: str             #: „РШ" | „Пр.Ш" | „СРС" | „ОТ" | „СКО" | „СВО"
    label: str            #: „РШ 12" — както пише на чертежа
    street: str
    source: str           #: документът, от който е прочетен
    in_scope: bool        #: влиза ли в ТАЗИ процедура (по легендата)
    scope_reason: str


# ---------------------------------------------------------------------------
# Легендата: цвят на перото → какво значи → влиза ли в процедурата
# ---------------------------------------------------------------------------

#: Ред от легендата се познава по тези думи.  Списъкът е нарочно тесен: всичко
#: друго в чертежа (заглавен блок, бележки) не е легенда.
_LEGEND_MARKERS = (
    "инвестиционна програма", "по друг проект", "съществуваща",
    "дъждовна канализация", "нова дъждовна", "битов канал",
)

#: Подредени правила текст-на-легендата → влиза ли.  ПЪРВОТО съвпадение печели,
#: затова изключващите стоят отпред: „Инвестиционна програма за битов канал —
#: СЛЕДВАЩ ЕТАП" съдържа и „инвестиционна програма", и „следващ етап".
_SCOPE_RULES = (
    (False, ("следващ етап", "друг проект", "съществуващ", "отпада")),
    (True, ("инвестиционна програма", "за инвестиция", "нова ")),
)


def _scope_of(text: str) -> tuple[bool | None, str]:
    """Дали легендна позиция влиза в процедурата.  None = не се разпознава."""
    low = text.lower()
    for влиза, думи in _SCOPE_RULES:
        for дума in думи:
            if дума in low:
                return влиза, text.strip()
    return None, text.strip()


def _lines_with_boxes(page: Any) -> list[tuple[str, tuple[float, ...]]]:
    """Редовете на страницата, с КИРИЛИЗИРАН текст.

    Тук е единствената врата, през която текстът на чертежа влиза в четците —
    затова поправката на омоглифите стои тук, а не в десетина регулярни израза.
    Без нея `Kл` с латинско K не съвпада с `^Кл\\.` и клонът изчезва мълчаливо:
    в `Ситуация Вод.pdf` това са 10 от 30 етикета.  Виж `src/text_norm.py`.
    """
    out: list[tuple[str, tuple[float, ...]]] = []
    смесени: list[str] = []
    for блок in page.get_text("dict")["blocks"]:
        for ред in блок.get("lines", []):
            текст = "".join(с["text"] for с in ред.get("spans", [])).strip()
            if текст:
                смесени.extend(mixed_words(текст))
                out.append((cyrillize(текст, whole_line=True), tuple(ред["bbox"])))
    if смесени:
        # КАЗВА СЕ КОЕ е поправено: тиха поправка на чужд текст е същият клас
        # проблем като тихото изпускане, само от другата страна.
        logger.info("Смесена азбука в чертежа — поправени %d означения: %s",
                    len(смесени), sorted(set(смесени))[:8])
    return out


#: Заглавието на легендния блок.  Когато го има, легендата е ПОД него — това
#: изрязва надписите по самия чертеж, които случайно съдържат същите думи.
_LEGEND_HEADING = re.compile(r"^ЛЕГЕНДА:?$", re.IGNORECASE)

#: Докъде под заглавието се смята, че стигат записите на легендата.
_LEGEND_SPAN = 620.0


def read_legend(page: Any) -> dict[tuple[float, ...], tuple[bool, str]]:
    """Цвят на перото → (влиза ли, текстът на легендата).

    Мострата е късо цветно чертежче ВЛЯВО от текста, на същата височина —
    така се чертаят легендите в AutoCAD и така се четат от човек.

    ЕДИН МОЛИВ С ДВЕ ЗНАЧЕНИЯ НЕ Е ОТГОВОР.  Ако един и същ цвят стои и до
    включващ, и до изключващ запис, той не се вписва изобщо.  Измерено
    21.08.2026 върху водопроводното инвестиционно приложение: там
    (0.6, 0.6, 0.6) — плътна, дебелина 0.51 — покрива едновременно „НОВ
    ВОДОПРОВОД", „СЪЩЕСТВУВАЩ ВОДОПРОВОД - ОТПАДА" и още три записа.  Нито
    шарката, нито дебелината ги делят: PDF експортът е сплескал типовете линии.
    По-добре празна легенда (и нула отсечки), отколкото половината мрежа
    маркирана наслуки.

    Returns:
        Речник цвят → (влиза, обяснение).  Празен, ако легенда няма.
    """
    редове = _lines_with_boxes(page)
    заглавия = [b for т, b in редове if _LEGEND_HEADING.match(т.strip())]
    пътища = [d for d in page.get_drawings() if d.get("color")]

    присъди: dict[tuple[float, ...], set[bool]] = defaultdict(set)
    обяснения: dict[tuple[float, ...], str] = {}

    for текст, (x0, y0, x1, y1) in редове:
        # Когато чертежът обявява „ЛЕГЕНДА", всичко извън блока се пропуска.
        if заглавия and not any(y0 > з[1] and y0 - з[3] < _LEGEND_SPAN
                                for з in заглавия):
            continue
        if not any(m in текст.lower() for m in _LEGEND_MARKERS):
            continue
        влиза, обяснение = _scope_of(текст)
        if влиза is None:
            continue
        най_близка: tuple[float, tuple[float, ...]] | None = None
        for d in пътища:
            bx0, by0, bx1, by1 = d["rect"]
            if by1 < y0 - 4 or by0 > y1 + 4:      # не е на същия ред
                continue
            if bx1 > x0 + 2:                      # мострата е ВЛЯВО от текста
                continue
            разстояние = x0 - bx1
            if най_близка is None or разстояние < най_близка[0]:
                най_близка = (разстояние, _pen(d["color"]))
        if най_близка is not None:
            присъди[най_близка[1]].add(влиза)
            обяснения.setdefault(най_близка[1], обяснение)

    легенда: dict[tuple[float, ...], tuple[bool, str]] = {}
    for цвят, гласове in присъди.items():
        if len(гласове) > 1:
            logger.warning(
                "Легендата дава на цвят %s и включващо, и изключващо значение "
                "— цветът се пренебрегва (напр. „%s\").",
                цвят, обяснения.get(цвят, ""))
            continue
        легенда[цвят] = (next(iter(гласове)), обяснения[цвят])

    logger.info("Легенда: %d цвята с обяснение", len(легенда))
    return легенда


def _pen(color: Any) -> tuple[float, ...]:
    """Цветът като сравним ключ — закръглен, за да не се дели на нюанси."""
    return tuple(round(float(c), 2) for c in color)


#: Под тази разлика между каналите перото е сиво/черно/бяло — мастило, не цвят.
_CHROMA = 0.10


def _is_chromatic(pen: tuple[float, ...]) -> bool:
    """Дали перото носи ЦВЯТ, а не е черно/сиво/бяло.

    Мрежите на ситуационния чертеж се различават по цвят; каквото е оставено
    в сивата гама, е основата — кадастър, сгради, изнасящи чертички.  Виж
    обосновката при ползването му в `read_sewer_situation`.
    """
    if not pen:
        return False
    return (max(pen) - min(pen)) >= _CHROMA


# ---------------------------------------------------------------------------
# Канализация: етикети до линията, обхват по цвета на линията
# ---------------------------------------------------------------------------

#: „Кл.48", „Кл.30а", „Кл.3-1" — името на клона стои само на своя ред.
#: Съставният номер („3-1", „3-2") е чест: един клон, разбит на подучастъци.
_BRANCH = re.compile(r"^Кл\.\s*([\dа-яa-z][\dа-яa-z\-]*)$", re.IGNORECASE)
_DN = re.compile(r"^DN\s*(\d+)", re.IGNORECASE)
_LENGTH = re.compile(r"^L\s*=\s*([\d.,]+)\s*м$", re.IGNORECASE)

#: Докъде се търси съседен етикет.  Тройката се чертае една под друга с ~8 pt
#: междуредие; 30 pt хваща и разредените групи, без да прескача на съседна.
_LABEL_RADIUS = 30.0
#: Възел: „РШ N12", „Пр.Ш 1", „ОТ 43".
_NODE = re.compile(r"^(РШ|Пр\.?\s*Ш|ОТ|OT)\s*[NН]?\s*[\d]+[а-яa-zA-Z]?$",
                   re.IGNORECASE)
_STREET = re.compile(r"^(ул\.|бул\.|пл\.)\s*(.+)$", re.IGNORECASE)


def _segments_of(drawing: dict) -> list[tuple[float, float, float, float]]:
    """Отсечките на едно чертежче, като четворки координати."""
    out = []
    for оп in drawing["items"]:
        if оп[0] == "l":
            out.append((оп[1].x, оп[1].y, оп[2].x, оп[2].y))
        elif оп[0] == "re":
            r = оп[1]
            out.append((r.x0, r.y0, r.x1, r.y1))
    return out


def _distance(px: float, py: float, s: tuple[float, ...]) -> float:
    ax, ay, bx, by = s
    dx, dy = bx - ax, by - ay
    if dx == 0 and dy == 0:
        return math.hypot(px - ax, py - ay)
    t = ((px - ax) * dx + (py - ay) * dy) / (dx * dx + dy * dy)
    t = max(0.0, min(1.0, t))
    return math.hypot(px - (ax + t * dx), py - (ay + t * dy))


def _center(bbox: tuple[float, ...]) -> tuple[float, float]:
    return (bbox[0] + bbox[2]) / 2, (bbox[1] + bbox[3]) / 2


def _nearest_unused(точка: tuple[float, float],
                    кандидати: list[tuple[Any, tuple[float, float]]],
                    заети: set[int]) -> int | None:
    """Най-близкият още незает етикет в радиуса, или None.

    „Незает" е важното: без него един диаметър би се залепил за две дължини и
    втората отсечка би получила чужд профил.
    """
    най: tuple[float, int | None] = (_LABEL_RADIUS, None)
    for i, (_, център) in enumerate(кандидати):
        if i in заети:
            continue
        d = math.hypot(точка[0] - център[0], точка[1] - център[1])
        if d < най[0]:
            най = (d, i)
    return най[1]


def _nearest_street(cx: float, cy: float,
                    улици: list[tuple[str, float, float]]) -> str:
    if not улици:
        return ""
    име, _, _ = min(улици, key=lambda u: math.hypot(cx - u[1], cy - u[2]))
    return име


def read_sewer_situation(path: str | Path) -> list[Segment]:
    """Отсечките на канализацията от ситуационен чертеж.

    Етикетът е тройка последователни реда — име на клон, диаметър, дължина —
    поставена до самата линия.  Обхватът се решава по цвета на НАЙ-БЛИЗКАТА
    мрежова линия, сверен с легендата на същия чертеж.

    Args:
        path: PDF на ситуацията.

    Returns:
        Списък `Segment`; празен, ако чертежът е нечетим или без легенда.
    """
    try:
        import fitz
    except ImportError:
        logger.warning("PyMuPDF липсва — ситуацията се пропуска.")
        return []

    try:
        doc = fitz.open(str(path))
    except Exception as exc:                       # noqa: BLE001 — чужд формат
        logger.error("Ситуацията %s не се отваря: %s", path, exc)
        return []

    име_на_документа = Path(path).name
    отсечки: list[Segment] = []

    with doc:
        for page in doc:
            легенда = read_legend(page)
            if not легенда:
                continue

            # ЧЕРНОТО НЕ Е МРЕЖА, А МАСТИЛО.
            #
            # Легендата дава на черното значение („Съществуваща смесена
            # канализация"), но със същото перо е начертана и цялата
            # кадастрална подложка: 4365 линии срещу 240 за най-натоварената
            # мрежа, плюс изнасящите чертички под самите етикети.  Затова то
            # печели по близост почти навсякъде — измерено 21.08.2026: с 0.4 до
            # 5 pt пред истинското перо на мрежата.
            #
            # Мрежите СЕ МАРКИРАТ С ЦВЯТ — това е смисълът на цветна легенда.
            # Каквото е оставено сиво или черно, е основата на чертежа, и
            # близостта до него не носи информация.
            #
            # Проверено срещу самия търг, а не по усет: без това правило DN500
            # излиза −14.1 % и DN1000 −47.2 % спрямо техническата спецификация;
            # с него — DN500 точно 0.0 % и DN1000 −1.1 %.
            мрежови: dict[tuple[float, ...], list] = defaultdict(list)
            for d in page.get_drawings():
                цвят = d.get("color")
                if not цвят:
                    continue
                перо = _pen(цвят)
                if перо in легенда and _is_chromatic(перо):
                    мрежови[перо].extend(_segments_of(d))
            if not мрежови:
                continue

            редове = _lines_with_boxes(page)
            улици = [(m.group(0), (b[0] + b[2]) / 2, (b[1] + b[3]) / 2)
                     for т, b in редове if (m := _STREET.match(т))]

            # ДЪЛЖИНАТА Е КОТВАТА, ИМЕТО — НЕ.
            #
            # Досега се тръгваше от реда „Кл.N" и се гледаха следващите два.
            # Това губеше 9 от 77 отсечки (576 м) по три различни начина:
            # клон със съставен номер („Кл.3-1"), ДВЕ тройки в един блок, и
            # етикети БЕЗ име на клон — а те си остават тръба.  Измерено на
            # 21.08.2026: DN500 излизаше −14 % от спецификацията, DN1000 −58 %.
            #
            # Затова се събират трите вида етикет поотделно и се сдвояват по
            # БЛИЗОСТ: на чертежа те стоят един под друг като групичка.  Всеки
            # етикет се ползва веднъж, за да не се залепи един диаметър за две
            # дължини.  Резултат: 77 от 77, DN500 точно, DN1000 −1.1 %.
            имена = [(m.group(1), _center(b)) for т, b in редове
                     if (m := _BRANCH.match(т))]
            диаметри = [(int(m.group(1)), _center(b)) for т, b in редове
                        if (m := _DN.match(т))]
            дължини = [(float(m.group(1).replace(",", ".")), _center(b))
                       for т, b in редове if (m := _LENGTH.match(т))]

            заети_dn: set[int] = set()
            заети_име: set[int] = set()
            for дължина, център in дължини:
                i_dn = _nearest_unused(център, диаметри, заети_dn)
                if i_dn is None:
                    logger.debug("Етикет L=%.2f няма диаметър наблизо", дължина)
                    continue
                заети_dn.add(i_dn)
                i_име = _nearest_unused(център, имена, заети_име)
                if i_име is not None:
                    заети_име.add(i_име)

                cx, cy = център
                най = (float("inf"), None)
                for цвят, сегменти in мрежови.items():
                    for s in сегменти:
                        d = _distance(cx, cy, s)
                        if d < най[0]:
                            най = (d, цвят)
                влиза, причина = легенда.get(най[1], (False, "без легенда"))

                отсечки.append(Segment(
                    network="К",
                    branch=(f"Кл.{имена[i_име][0]}" if i_име is not None
                            else f"участък {len(отсечки) + 1}"),
                    start_node="", end_node="",
                    length_m=дължина,
                    dn=диаметри[i_dn][0],
                    street=_nearest_street(cx, cy, улици),
                    source=име_на_документа,
                    in_scope=влиза,
                    scope_reason=причина,
                ))

    в_обхват = sum(1 for о in отсечки if о.in_scope)
    logger.info("Ситуация %s: %d отсечки, %d в обхвата на процедурата",
                име_на_документа, len(отсечки), в_обхват)
    return отсечки


# ---------------------------------------------------------------------------
# Точкови позиции: шахти, оттоци, сградни отклонения
# ---------------------------------------------------------------------------

#: Вид точкова позиция → как се пише на чертежа.  Редът има значение: „СРШ" и
#: „Пр.Ш" се проверяват ПРЕДИ „РШ", иначе по-общият шаблон ги изяжда.
_NODE_KINDS: tuple[tuple[str, re.Pattern[str]], ...] = (
    ("СРС", re.compile(r"^СРС\s*[NН№]?\s*\d+[а-яa-z]?$", re.IGNORECASE)),
    ("СКО", re.compile(r"^СКО\s*[NН№]?\s*\d+[а-яa-z]?$", re.IGNORECASE)),
    ("СВО", re.compile(r"^СВО\s*[NН№]?\s*\d+[а-яa-z]?$", re.IGNORECASE)),
    ("Пр.Ш", re.compile(r"^Пр\.?\s*Ш\s*[NН№]?\s*\d+[а-яa-z]?$", re.IGNORECASE)),
    ("СРШ", re.compile(r"^СРШ\s*[NН№]?\s*\d+[а-яa-z]?$", re.IGNORECASE)),
    ("РШ", re.compile(r"^РШ\s*[NН№]?\s*\d+[а-яa-z]?$", re.IGNORECASE)),
    ("ОТ", re.compile(r"^(?:ОТ|OT)\s*[NН№]?\s*\d+[а-яa-zA-Z]?$",
                      re.IGNORECASE)),
)

#: Вид → позицията, както се пише в количествата.  Името НЕ е свободно: то
#: минава през същия класификатор и същите норми, както ред от таблица —
#: „Ревизионни шахти" хваща `manhole` + 2 бр./ден, „Улични оттоци (УО)"
#: хваща `manhole` + 4 бр./ден.  Сменѝ думите и количеството остава без норма.
_NODE_POSITIONS: dict[str, str] = {
    "РШ": "Ревизионни шахти (РШ)",
    "СРШ": "Ревизионни шахти (СРШ)",
    "Пр.Ш": "Преливни шахти",
    "СРС": "Сградни ревизионни шахти (СРС)",
    "ОТ": "Улични оттоци (УО)",
    "СКО": "Сградни канализационни отклонения (СКО)",
    "СВО": "Сградни водопроводни отклонения (СВО)",
}


def _kind_of(текст: str) -> str:
    """Кой вид точкова позиция е този етикет, или празно."""
    ред = текст.strip()
    for вид, шаблон in _NODE_KINDS:
        if шаблон.match(ред):
            return вид
    return ""


def read_sewer_nodes(path: str | Path) -> list[Node]:
    """Точковите позиции от ситуационен чертеж — по етикетите им.

    ЗАЩО.  Изпълнителят, 24.08.2026: количествата за график са „линейната
    дължина за В и К, с всички диаметри на тръбите, както и СВО, СКО, шахти,
    УО от техническата спецификация И ЧЕРТЕЖИТЕ".  Дотук чертежът даваше само
    отсечки: шахтите стояха изписани върху него, а `_NODE` — шаблонът, който
    ги познава — беше НАПИСАН И НЕИЗПОЛЗВАН.  Щом спецификацията не изброи
    точковите позиции, те просто липсваха от графика.

    Обхватът се решава като при отсечките: по цвета на най-близката мрежова
    линия, сверен с легендата.  Възел до линия „следващ етап" не е наш.

    ЕДИН ЕТИКЕТ = ЕДНА ПОЗИЦИЯ.  Един и същи чертеж идва по няколко листа и
    „РШ 12" се повтаря; броим РАЗЛИЧНИТЕ етикети, не появите им.

    Returns:
        Списък `Node`; празен, ако чертежът е нечетим или без легенда.
    """
    try:
        import fitz
    except ImportError:
        logger.warning("PyMuPDF липсва — точковите позиции се пропускат.")
        return []

    try:
        doc = fitz.open(str(path))
    except Exception as exc:                       # noqa: BLE001 — чужд формат
        logger.error("Ситуацията %s не се отваря: %s", path, exc)
        return []

    име_на_документа = Path(path).name
    възли: list[Node] = []
    видени: set[tuple[str, str]] = set()

    with doc:
        for page in doc:
            легенда = read_legend(page)
            if not легенда:
                continue

            # Същото правило като при отсечките: черното и сивото са основата
            # на чертежа, не мрежа — виж обосновката в `read_sewer_situation`.
            мрежови: dict[tuple[float, ...], list] = defaultdict(list)
            for d in page.get_drawings():
                цвят = d.get("color")
                if not цвят:
                    continue
                перо = _pen(цвят)
                if перо in легенда and _is_chromatic(перо):
                    мрежови[перо].extend(_segments_of(d))
            if not мрежови:
                continue

            редове = _lines_with_boxes(page)
            улици = [(m.group(0), (b[0] + b[2]) / 2, (b[1] + b[3]) / 2)
                     for т, b in редове if (m := _STREET.match(т))]

            for текст, bbox in редове:
                вид = _kind_of(текст)
                if not вид:
                    continue
                етикет = re.sub(r"\s+", " ", текст.strip())
                ключ = (вид, етикет.lower())
                if ключ in видени:
                    continue
                видени.add(ключ)

                cx, cy = _center(bbox)
                най: tuple[float, Any] = (float("inf"), None)
                for цвят, сегменти in мрежови.items():
                    for s in сегменти:
                        d = _distance(cx, cy, s)
                        if d < най[0]:
                            най = (d, цвят)
                влиза, причина = легенда.get(най[1], (False, "без легенда"))

                възли.append(Node(
                    kind=вид,
                    label=етикет,
                    street=_nearest_street(cx, cy, улици),
                    source=име_на_документа,
                    in_scope=влиза,
                    scope_reason=причина,
                ))

    в_обхват = sum(1 for в in възли if в.in_scope)
    logger.info("Ситуация %s: %d точкови позиции, %d в обхвата",
                име_на_документа, len(възли), в_обхват)
    return възли


def count_nodes(nodes: Iterable[Node], *, only_in_scope: bool = True) -> dict:
    """Брой по вид: {„РШ": 46, „ОТ": 12}."""
    броени: dict[str, int] = {}
    for възел in nodes or []:
        if only_in_scope and not възел.in_scope:
            continue
        броени[възел.kind] = броени.get(възел.kind, 0) + 1
    return броени


def nodes_as_quantity_rows(nodes: Iterable[Node], *,
                           only_in_scope: bool = True) -> list:
    """Преброените позиции като редове с количество — с чертежа за източник.

    ЧЕТЕНЕТО НЕ Е ДОГОВОР.  Редът сочи ЧЕРТЕЖА, не спецификацията, и го казва
    в описанието си: „преброени от чертежа".  Щом таблица даде същата позиция,
    важи ТАБЛИЦАТА — сливането отсява (виж `chat_handler`), защото договорното
    количество е онова, което възложителят е купил, а не онова, което сме
    преброили.

    Returns:
        Списък `QuantityRow` — празен, ако няма нито един възел в обхвата.
    """
    from src.provenance import QuantityRow, SourceRef

    възли = [в for в in (nodes or []) if в.in_scope or not only_in_scope]
    if not възли:
        return []

    по_вид: dict[str, list[Node]] = defaultdict(list)
    for възел in възли:
        по_вид[възел.kind].append(възел)

    документ = възли[0].source
    редове = []
    for ред_номер, вид in enumerate(sorted(по_вид), start=1):
        позиция = _NODE_POSITIONS.get(вид)
        if not позиция:
            continue
        етикети = [в.label for в in по_вид[вид]]
        редове.append(QuantityRow(
            description=f"{позиция} — преброени от чертежа",
            quantity=float(len(етикети)),
            unit="бр",
            source=SourceRef(document=документ, sheet="чертеж", row=ред_номер),
            raw={"вид": вид, "етикети": sorted(етикети),
                 "произход": "преброени от ситуационния чертеж"},
        ))
    return редове


#: Как изглежда СЪЩАТА позиция, когато я има в таблица.  Шаблоните повтарят
#: тези на `duration_calculator` нарочно: там решават коя норма хваща реда, тук
#: — дали чертежът има какво да добави.  Разминат ли се, ще броим два пъти.
_KIND_IN_TABLE: dict[str, re.Pattern[str]] = {
    "РШ": re.compile(r"\bРШ\b|ревизионн\w*\s+шахт", re.IGNORECASE),
    "СРШ": re.compile(r"\bС?РШ\b|ревизионн\w*\s+шахт", re.IGNORECASE),
    "Пр.Ш": re.compile(r"преливн\w*\s+шахт", re.IGNORECASE),
    "СРС": re.compile(r"\bСРС\b|сградн\w*\s+ревизион", re.IGNORECASE),
    "ОТ": re.compile(r"\bУО\b|уличен\s+отток|улични\s+оттоци|дъждоприемн",
                     re.IGNORECASE),
    "СКО": re.compile(r"\bСКО\b|сградн\w*\s+канализационн\w*\s+отклонени",
                      re.IGNORECASE),
    "СВО": re.compile(r"\bСВО\b|сградн\w*\s+водопроводн\w*\s+отклонени",
                      re.IGNORECASE),
}

#: Мерките, в които се брои точкова позиция.
_COUNT_UNITS = frozenset({"бр", "бр.", "брой", "броя", "бройки", "pcs", "pc"})


def merge_node_rows(existing: Iterable, from_drawing: Iterable) -> tuple[list, list[str]]:
    """Долива преброените от чертежа позиции към количествата — без да дублира.

    ТАБЛИЦАТА НАДДЕЛЯВА.  Щом спецификацията или сметката вече дава шахтите,
    важи нейното число: то е ДОГОВОРНО, а нашето е преброено.  Чертежът допълва
    само каквото в таблиците изобщо го няма — точно случаят, заради който
    правилото се появи: техническа спецификация с метри тръба и нито един брой.

    Returns:
        (редове, бележки) — бележките казват какво е добавено и какво е
        премълчано, защото „преброено, но неизползвано" и „непреброено"
        изглеждат еднакво отвън.
    """
    редове = list(existing or [])
    бележки: list[str] = []

    описания = [(str(getattr(р, "description", "") or ""),
                 str(getattr(р, "unit", "") or "").strip().lower())
                for р in редове]

    for ред in from_drawing or []:
        вид = str((getattr(ред, "raw", {}) or {}).get("вид") or "")
        шаблон = _KIND_IN_TABLE.get(вид)
        брой = int(getattr(ред, "quantity", 0) or 0)
        има_я = any(шаблон.search(описание) and мярка in _COUNT_UNITS
                    for описание, мярка in описания) if шаблон else False
        позиция = _NODE_POSITIONS.get(вид, вид)
        if има_я:
            бележки.append(
                f"{позиция}: чертежът брои {брой}, но таблицата вече ги дава — "
                "важи таблицата (договорното количество).")
            continue
        редове.append(ред)
        бележки.append(f"{позиция}: {брой} бр. ПРЕБРОЕНИ ОТ ЧЕРТЕЖА — "
                       "в таблиците ги няма.")

    for бележка in бележки:
        logger.info("%s", бележка)
    return редове, бележки


# ---------------------------------------------------------------------------
# Водопровод: оразмерителната таблица дава отсечките наготово
# ---------------------------------------------------------------------------

#: Заглавие на колона → роля.  Достатъчна е ПЪРВАТА дума: заглавията се пренасят
#: на два реда („Крайна" / „точка") и само първата е сигурна.
_WATER_COLUMNS = (
    ("клон", "branch"),
    ("начална", "start"),
    ("крайна", "end"),
    ("действ", "length"),
    ("d", "dn"),
)

_WATER_ROW = re.compile(r"^(ГЛ\.)?КЛ\.", re.IGNORECASE)


def _header_columns(header_words: list[tuple]) -> list[tuple[float, float, str]]:
    """Колоните на таблицата: (ляв край, десен край, заглавие).

    ВСИЧКИ колони, не само търсените.  Ако се вземат само те, границата преди
    „D [mm]" пада насред четирите колони между тях и в диаметъра влиза числото
    на съседно поле — измерено 21.08.2026: DN излизаше 63, 27, 16 (това са
    оразмерителните дебити).

    Заглавието се пренася на два реда („действ." / „дължина") и се пише с
    интервали („КЛОН №"), затова думите се слепват по две правила: на един ред
    — когато са долепени; между редовете — когато се застъпват по хоризонтала.
    """
    редове: dict[int, list[tuple]] = defaultdict(list)
    for w in header_words:
        редове[round(w[1] / 4)].append(w)

    групи: list[list[float | str]] = []            # [ляв, десен, текст]
    for y in sorted(редове):
        for w in sorted(редове[y], key=lambda w: w[0]):
            if групи and w[0] - групи[-1][1] < 4 and групи[-1][3] == y:
                групи[-1][1] = w[2]
                групи[-1][2] = f"{групи[-1][2]} {w[4]}"
            else:
                групи.append([w[0], w[2], w[4], y])

    слети: list[list[float | str]] = []
    for ляв, десен, текст, _ in sorted(групи, key=lambda g: g[0]):
        застъпена = next((s for s in слети if ляв < s[1] and десен > s[0]), None)
        if застъпена:
            застъпена[0] = min(застъпена[0], ляв)
            застъпена[1] = max(застъпена[1], десен)
            застъпена[2] = f"{застъпена[2]} {текст}"
        else:
            слети.append([ляв, десен, текст])
    return [(g[0], g[1], str(g[2])) for g in sorted(слети, key=lambda g: g[0])]


def _roles_of(колони: list[tuple[float, float, str]]) -> list[tuple[float, str]]:
    """Границите между колоните + ролята на всяка от търсените.

    Границата е по средата между ДЕСНИЯ край на едната и ЛЕВИЯ на следващата —
    не между левите им краища.  „КЛОН №" стига до x≈85, а „Начална точка"
    започва на 96.8; средата между левите краища е 76 и римското „I" от името
    на клона попада в грешната колона.
    """
    граници: list[tuple[float, str]] = []
    for i, (ляв, _десен, текст) in enumerate(колони):
        начало = ((колони[i - 1][1] + ляв) / 2) if i else float("-inf")
        # Сравнява се ВСЯКА дума от заглавието, не началото на слепения надпис:
        # заглавието се пренася на два реда и словоредът му се обръща, когато
        # долният ред започва по-вляво („дължина действ." вместо „действ.
        # дължина").  Освен това се съкращава с точка, затова — по начало.
        думи = текст.lower().strip().split()
        роля = next((r for з, r in _WATER_COLUMNS
                     if any(д.strip("№[]. ").startswith(з) for д in думи)), "")
        граници.append((начало, роля))
    return граници


def _assign(x: float, граници: list[tuple[float, str]]) -> str | None:
    """В коя колона попада дума с център `x`.  Празен низ = колона без роля."""
    роля: str | None = None
    for начало, име in граници:
        if x >= начало:
            роля = име
    return роля or None


def read_water_table(path: str | Path) -> list[Segment]:
    """Отсечките на водопровода от оразмерителната таблица.

    Таблицата дава клон, двата възела, действителната дължина и диаметъра —
    тоест целия участък, без да се мери каквото и да е.

    Args:
        path: PDF на оразмерителната таблица.

    Returns:
        Списък `Segment`.  Всички са `in_scope=True`: таблицата описва само
        проектираната мрежа, за разлика от ситуационния чертеж.
    """
    try:
        import fitz
    except ImportError:
        logger.warning("PyMuPDF липсва — оразмерителната таблица се пропуска.")
        return []

    try:
        doc = fitz.open(str(path))
    except Exception as exc:                       # noqa: BLE001
        logger.error("Таблицата %s не се отваря: %s", path, exc)
        return []

    име_на_документа = Path(path).name
    отсечки: list[Segment] = []

    # ТАБЛИЦАТА ПРОДЪЛЖАВА, ХЕДЪРЪТ — НЕ.  Оразмерителната таблица на реалния
    # проект е 3 страници, а заглавният ред е само на първата.  Докато
    # границите се търсеха на всяка страница поотделно, 50 от 89 отсечки се
    # изхвърляха мълчаливо (измерено 21.08.2026).  Затова колоните веднъж
    # намерени важат и за следващите страници — както ги чете и човек.
    граници: list[tuple[float, str]] = []

    with doc:
        for page in doc:
            думи = page.get_text("words")
            if not думи:
                continue
            # Същата поправка като в `_lines_with_boxes`: таблицата се хваща по
            # думата „клон“, а тя също може да е с латинско K.
            думи = [(*w[:4], cyrillize(w[4]), *w[5:]) for w in думи]

            # Хедърът се пренася на няколко реда, затова се събира по ЛЕНТА
            # височина, а не по един ред: първата дума „клон" дава лентата.
            заглавни = [w for w in думи if w[4].lower().strip("№[]. ") == "клон"]
            if заглавни:
                y_хедър = заглавни[0][1]
                лента = [w for w in думи if abs(w[1] - y_хедър) <= 14]
                кандидат = _roles_of(_header_columns(лента))
                липсва = ({r for _, r in _WATER_COLUMNS}
                          - {р for _, р in кандидат if р})
                if липсва:
                    logger.warning("Таблица %s: не са намерени колони %s",
                                   име_на_документа, sorted(липсва))
                else:
                    граници = кандидат
            elif граници:
                y_хедър = float("-inf")        # продължение: цялата страница е данни
            if not граници:
                continue

            по_ред: dict[int, list] = defaultdict(list)
            for w in думи:
                if w[1] > y_хедър + 14:
                    по_ред[round(w[1] / 4)].append(w)

            for y in sorted(по_ред):
                клетки = sorted(по_ред[y], key=lambda w: w[0])
                if not _WATER_ROW.match(" ".join(w[4] for w in клетки)):
                    continue
                поле: dict[str, list[str]] = defaultdict(list)
                for w in клетки:
                    роля = _assign((w[0] + w[2]) / 2, граници)
                    if роля:
                        поле[роля].append(w[4])
                try:
                    дължина = float(поле["length"][0].replace(",", "."))
                    dn = int(float(поле["dn"][0].replace(",", ".")))
                except (KeyError, IndexError, ValueError):
                    continue
                отсечки.append(Segment(
                    network="В",
                    branch=" ".join(поле.get("branch", [])),
                    start_node=" ".join(поле.get("start", [])),
                    end_node=" ".join(поле.get("end", [])),
                    length_m=дължина,
                    dn=dn,
                    street="",
                    source=име_на_документа,
                    in_scope=True,
                    scope_reason="оразмерителна таблица на проекта",
                ))

    logger.info("Таблица %s: %d отсечки", име_на_документа, len(отсечки))
    return отсечки


def summarize(segments: list[Segment]) -> dict[str, Any]:
    """Сборът по диаметър — за сверка срещу количествата от спецификацията."""
    по_dn: dict[int, list] = defaultdict(lambda: [0, 0.0])
    for о in segments:
        if not о.in_scope:
            continue
        по_dn[о.dn][0] += 1
        по_dn[о.dn][1] += о.length_m
    return {
        "segments": sum(1 for о in segments if о.in_scope),
        "dropped": sum(1 for о in segments if not о.in_scope),
        "by_dn": {dn: {"count": n, "length_m": round(L, 2)}
                  for dn, (n, L) in sorted(по_dn.items())},
        "total_m": round(sum(L for _, L in по_dn.values()), 2),
    }


# ---------------------------------------------------------------------------
# Водопровод: „PEHD DN…" в чертежа значи „тази тръба се подменя"
# ---------------------------------------------------------------------------
#
# ЗАЩО НЕ ПО ЦВЯТ.  За канализацията обхватът се решава по перото, сверено с
# легендата.  За водопровода това е невъзможно и е измерено: в инвестиционното
# приложение перото (0.6, 0.6, 0.6) — плътно, дебелина 0.51 — покрива
# едновременно „НОВ ВОДОПРОВОД", „СЪЩЕСТВУВАЩ ВОДОПРОВОД - ОТПАДА",
# „СЪЩЕСТВУВАЩ, КОЙТО СЕ ЗАПАЗВА" и още два записа.  Нито шарката, нито
# дебелината ги делят — PDF експортът е сплескал типовете линии.
#
# Затова обхватът идва от САМИЯ ЕТИКЕТ.  Водопроводните етикети са пълни
# изречения и казват какво ще СЕ ПОЛОЖИ:
#
#     КЛ.24а-И ¦ L=433.10m ¦ PEHD DN110 ¦ Q=1.63л/с ¦ V=0.2м/с
#
# „PEHD" е новата полиетиленова тръба; съществуващите носят „чугун", „ст." или
# „-същ.".  Тоест етикетът с PEHD Е обявлението за подмяна, и диаметърът до
# него е НОВИЯТ — за разлика от оразмерителната таблица, чиято колона „D" е
# старият диаметър (потвърдено от клиента: „старият е 200, който се заменя с
# 225").
#
# ДЪЛЖИНИТЕ ТУК СА ТЕГЛА, НЕ КОЛИЧЕСТВА.  Договорното количество си остава
# онова от техническата спецификация; прочетените дължини само решават как то
# се разделя между участъците.  Затова несъответствието между сбора на
# чертежа и сбора на търга не прави графика грешен — прави го разчленен.

#: Материалът на НОВАТА тръба.  Само етикет с него обявява подмяна.
_NEW_PIPE = re.compile(r"\bPEHD\b|\bПЕВП\b(?!\s*-\s*същ)", re.IGNORECASE)

#: Съществуващото, изрично маркирано — не влиза, каквото и друго да пише.
_EXISTING = re.compile(r"-\s*същ\.?|\bотпада\b|\bчугун\b|\bст\.\b", re.IGNORECASE)

#: „КЛ.24а-И", „ГЛ.КЛ.II", „ПЗ-КЛ.4" — името на водопроводния клон.
_WATER_BRANCH = re.compile(
    r"((?:ГЛ\.|ПЗ-)?КЛ\.\s*[\dА-Яа-яA-Za-zIΙ]*(?:\s*-\s*[ИРир])?)", re.IGNORECASE)

_WATER_DN = re.compile(r"\bDN\s*(\d+)", re.IGNORECASE)
_WATER_LENGTH = re.compile(r"\bL\s*=\s*([\d.,]+)\s*m", re.IGNORECASE)

#: Етикетът, който носи САМО дължина — котвата, около която се търсят тръбата
#: и името на клона.  Едно съвпадение = една отсечка.
_WATER_LENGTH_ONLY = re.compile(r"^L\s*=\s*([\d.,]+)\s*m$", re.IGNORECASE)


def _water_scope(branch: str, area: str) -> tuple[bool, str]:
    """Дали клонът е от избрания подобект, и защо.

    Магистралните клонове („ГЛ.КЛ.") хранят всичко и не носят наставка —
    те влизат винаги, когато изобщо се филтрира.
    """
    ново = "етикетът обявява нова тръба (PEHD)"
    if not area:
        return True, ново
    име = re.sub(r"\s+", "", branch.upper())
    искан = re.sub(r"\s+", "", area.upper())
    if име.startswith("ГЛ.КЛ."):
        return True, f"{ново}; магистрален клон — влиза при всеки подобект"
    if искан == "ПЗ":
        влиза = име.startswith("ПЗ-")
    else:
        влиза = име.endswith(f"-{искан}")
    if влиза:
        return True, f"{ново}; подобект „{area}\""
    return False, f"клонът е от друг подобект, а процедурата е „{area}\""


def read_water_situation(path: str | Path, area: str = "") -> list[Segment]:
    """Отсечките за подмяна, от водопроводния ситуационен чертеж.

    Всеки етикет е един блок текст.  Взимат се само тези, които обявяват нова
    тръба (`PEHD`/`ПЕВП`) и носят диаметър и дължина.

    ЕДИН ЧЕРТЕЖ, ТРИ ПОДОБЕКТА.  Проектът покрива повече от една процедура и
    клоновете го КАЗВАТ в името си: „КЛ.24а-И" е Илиянци, „КЛ.16-Р" е бул.
    Рожен, „ПЗ-КЛ.4" е промишлената зона.  Измерено 21.08.2026: целият чертеж
    дава 8431 м при 3249 м по техническата спецификация, а тя пише изрично „на
    кв. Илиянци".

    Филтърът е ИЗБОР НА ЧОВЕКА, не догадка на кода: подобектите се четат от
    имената, но кой от тях е предмет на процедурата пише в спецификацията.  По
    подразбиране не се филтрира нищо.  Отсечките извън избрания подобект се
    връщат с `in_scope=False` и казват защо — не изчезват.

    Args:
        path: PDF на водопроводната ситуация или инвестиционното приложение.
        area: Наставка на подобекта („И", „Р") или префикс „ПЗ".  Празно =
            всички.

    Returns:
        Списък `Segment` с мрежа „В".  Празен, ако чертежът е нечетим.
    """
    try:
        import fitz
    except ImportError:
        logger.warning("PyMuPDF липсва — водната ситуация се пропуска.")
        return []

    try:
        doc = fitz.open(str(path))
    except Exception as exc:                       # noqa: BLE001
        logger.error("Ситуацията %s не се отваря: %s", path, exc)
        return []

    име_на_документа = Path(path).name
    отсечки: list[Segment] = []
    без_име = 0

    with doc:
        for page in doc:
            редове = _lines_with_boxes(page)
            улици = [(m.group(0), (b[0] + b[2]) / 2, (b[1] + b[3]) / 2)
                     for т, b in редове if (m := _STREET.match(т))]

            # СЪЩОТО КАТО ПРИ КАНАЛИЗАЦИЯТА: етикетът е РАЗПРЪСНАТ.
            #
            # Дотук се четеше блок по блок и се искаше всичко да е вътре.
            # Измерено 21.08.2026: 120 блока носят „L=", а само 75 се четяха —
            # 45 етикета имат дължина, докато тръбата и диаметърът им стоят в
            # съседен блок.  На ниво РЕД чертежът има 119 дължини, 120
            # диаметъра и 129 имена на клон, тоест отсечките са ~119, не 75.
            имена = [(re.sub(r"\s+", " ", m.group(1)).strip(), _center(b))
                     for т, b in редове if (m := _WATER_BRANCH.match(т))]
            тръби = [(т, _center(b)) for т, b in редове
                     if _WATER_DN.search(т) and (_NEW_PIPE.search(т)
                                                 or _EXISTING.search(т))]
            дължини = [(float(m.group(1).replace(",", ".")), _center(b))
                       for т, b in редове if (m := _WATER_LENGTH_ONLY.match(т))]

            заети_тръба: set[int] = set()
            заети_име: set[int] = set()
            for дължина, център in дължини:
                i_тръба = _nearest_unused(център, тръби, заети_тръба)
                if i_тръба is None:
                    continue
                заети_тръба.add(i_тръба)
                текст_на_тръбата = тръби[i_тръба][0]
                if _EXISTING.search(текст_на_тръбата):
                    continue          # съществуващо — не е работа по договора
                dn = _WATER_DN.search(текст_на_тръбата)
                if not dn:
                    continue

                i_име = _nearest_unused(център, имена, заети_име)
                if i_име is None:
                    без_име += 1
                else:
                    заети_име.add(i_име)
                име = (имена[i_име][0] if i_име is not None
                       else f"водопроводен участък {len(отсечки) + 1}")
                влиза, причина = _water_scope(име, area)
                cx, cy = център
                отсечки.append(Segment(
                    network="В",
                    branch=име,
                    start_node="", end_node="",
                    length_m=дължина,
                    dn=int(dn.group(1)),
                    street=_nearest_street(cx, cy, улици),
                    source=име_на_документа,
                    in_scope=влиза,
                    scope_reason=причина,
                ))

    if без_име:
        logger.info("Водна ситуация %s: %d от %d етикета са продължения без "
                    "име на клон — носят дължина, но не и име.",
                    име_на_документа, без_име, len(отсечки))
    logger.info("Водна ситуация %s: %d отсечки за подмяна",
                име_на_документа, len(отсечки))
    return отсечки
