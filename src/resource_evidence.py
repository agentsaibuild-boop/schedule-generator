logger = logging.getLogger(__name__)

СЪСТОЯНИЯ = ("confirmed", "observed_peak", "assumed")

ОБЯСНЕНИЕ = {
    "confirmed": "потвърдено от изпълнителя",
    "observed_peak": "измерен връх от еталонен график (долна граница)",
    "assumed": "разумно подразбиране — нито измерено, нито потвърдено",
    "unknown": "няма запис откъде идва",
}


def _конфиг() -> dict:
    from src.schedule_builder import _load_resource_capacity

    return _load_resource_capacity() or {}


def _без_наставка(име: str) -> str:
    """„Багер универсален (съоръжения)" → „Багер универсален".

    Ресурсите се именуват с дисциплината в скоби, за да не се делят между
    мрежите.  Произходът обаче е на самата машина, не на дисциплината — без
    това всички те излизаха с „няма запис откъде идва".
    """
    ако = име.find("(")
    return име[:ако].strip() if ако > 0 else име.strip()


def state_of(име: str, конфиг: dict | None = None) -> tuple[str, int | None]:
    """(състояние, бройка) за този ресурс."""
    cfg = конфиг if конфиг is not None else _конфиг()
    по_ресурс = (cfg.get("произход") or {}).get("по_ресурс") or {}
    запис = по_ресурс.get(име) or по_ресурс.get(_без_наставка(име)) or {}
    for състояние in СЪСТОЯНИЯ:
        стойност = запис.get(състояние)
        if isinstance(стойност, int) and стойност > 0:
            return състояние, стойност
    таван = ((cfg.get("capacity") or {}).get(име)
             or (cfg.get("capacity") or {}).get(_без_наставка(име)))
    return "unknown", таван if isinstance(таван, int) else None


def binding(tasks: Iterable[dict]) -> dict:
    """Кои ресурси държат срока и с какво доказателство стоят техните бройки.

    „Държат срока" значи: ползват се ДО тавана си.  Ресурс, който никога не
    опира тавана, не мени нищо, каквото и да е доказателството му.

    СМЕТКАТА Е ТОЧНО ТАЗИ НА ГЕЙТА (`_capacity_overloads`), не приблизителна:
    заетостта се брои по БРИГАДА, надзорните роли и хората на екипа не се
    броят, непрекъснатата дейност не заема ресурс, а където еталонът дава
    състав — мери се в ХОРА срещу наличните, не в слотове срещу `capacity`.

    Първите ми две проби не спазваха това и обявиха „10 заваръчни машини при
    таван 2" — претоварване, което гейтът никога не е допускал.  Число, което
    не се събира с гейта, не бива да излиза пред човек.
    """
    from collections import defaultdict

    from src.road_works import merged_into_level_of_effort
    from src.schedule_builder import (_headcount, _is_leveling_resource,
                                      _load_resource_capacity, _occupancy_key,
                                      _per_crew_roles)

    cfg = _load_resource_capacity() or {}
    capacity = cfg.get("capacity") or {}
    default = int(cfg.get("default", 1))
    състав = _headcount()
    на_екипа = _per_crew_roles()

    товар: dict[tuple[str, int], set] = defaultdict(set)
    for t in tasks or ():
        if not isinstance(t, dict) or t.get("is_summary"):
            continue
        if merged_into_level_of_effort(t):
            continue
        try:
            н, к = int(t.get("start_day")), int(t.get("end_day"))
        except (TypeError, ValueError):
            continue
        заемател = _occupancy_key(t)
        for суров in (t.get("resources") or ()):
            име = str(суров if isinstance(суров, str)
                      else суров.get("name", "")).strip()
            if not име or име in на_екипа or not _is_leveling_resource(име):
                continue
            for ден in range(н, к + 1):
                товар[(име, ден)].add(заемател)

    върхове: dict[str, tuple[int, int]] = {}
    for (име, _ден), заематели in товар.items():
        сведение = състав.get(име)
        if сведение:
            използвани, таван = (len(заематели) * сведение["на_задача"],
                                 int(сведение["налични"]))
        else:
            използвани, таван = len(заематели), int(capacity.get(име, default))
        ако = върхове.get(име)
        if ако is None or използвани > ако[0]:
            върхове[име] = (използвани, таван)

    редове: list[dict] = []
    for име, (пик, таван) in върхове.items():
        състояние, бройка = state_of(име, cfg)
        редове.append({"ресурс": име, "пик": пик, "таван": таван,
                       "състояние": състояние, "бройка": бройка,
                       "държи_срока": таван > 0 and пик >= таван})
    редове.sort(key=lambda р: (-(р["пик"] / (р["таван"] or 1)), -р["пик"]))

    държащи = [р for р in редове if р["държи_срока"]]
    непотвърдени = [р for р in държащи if р["състояние"] != "confirmed"]
    return {
        "ресурси": редове,
        "държат_срока": държащи,
        "непотвърдени_държащи": непотвърдени,
        "срокът_е_обвързващ": bool(държащи) and not непотвърдени,
    }


def describe(отчет: dict) -> list[str]:
    """Изречението, което одиторът поиска — за всеки ресурс, който има значение."""
    държащи = отчет.get("държат_срока") or []
    if not държащи:
        return ["Никой ресурс не опира тавана си — срокът не се държи от "
                "наличности."]

    редове = [f"РЕСУРСИ, КОИТО ДЪРЖАТ СРОКА ({len(държащи)}):"]
    for р in държащи[:12]:
        колко = р["бройка"] if р["бройка"] is not None else "?"
        редове.append(
            f"  {р['ресурс']}: графикът ползва {р['пик']} при таван "
            f"{р['таван']} — {ОБЯСНЕНИЕ.get(р['състояние'], р['състояние'])} "
            f"({колко})."
            + ("" if р["състояние"] == "confirmed"
               else "  Изпълнителят НЕ е потвърдил наличността."))

    непотвърдени = отчет.get("непотвърдени_държащи") or []
    if непотвърдени:
        редове.append(
            f"СРОКЪТ НЕ Е ОБВЪРЗВАЩ: {len(непотвърдени)} от ресурсите, които "
            f"го държат, стоят на бройка, която изпълнителят не е потвърдил.  "
            f"Числата са долна граница от чужд обект, не наличен парк.")
    else:
        редове.append("Всички ресурси, които държат срока, са с потвърдени от "
                      "изпълнителя бройки — срокът е обвързващ по ресурси.")
    return редове
