"""Кой календар важи за графика — и отказ да се изнесе грешният.

ЗАЩО.  Одиторът, 31.08.2026:

    „Системата вече чете, че Свиленград е 5/5 по FIDIC 6.5, но още изнася 7/7.
     Това е P0, защото не е просто визуална разлика — променя реалните
     календарни дати с приблизително 40 %.  Не бих допуснал production export,
     ако contract_calendar_detected != schedule_calendar без изрично човешко
     override."

Проверено в кода: `calendar_type` не се подава от НИТО ЕДНО място в
продукционния път — износът е винаги 7/7 по подразбиране.  Тоест за процедура,
която обявява петдневна работна седмица, всяка дата в подадения `.mpp` е
изместена, и никой не разбира.

ТРИ ИЗТОЧНИКА, в този ред:

    1. изрично от човека        `WORK_WEEK=5` / въпросника — надделява над всичко
    2. от договора              `contract_data.read_contract` → Под-Клауза 6.5
    3. подразбиране             7/7, както досега

РАЗЛИКАТА НЕ Е КОЗМЕТИЧНА.  400 работни дни при 5/5 са 560 календарни; при 7/7
са 400.  Човешкият график на Свиленград го потвърждава: 361 работни дни в 531
календарни.

ГЕЙТЪТ.  Когато договорът казва едно, а изнасяме друго, `check` връща причина
за отказ.  Тя се маха само с изрично човешко решение — не мълчаливо.
"""

from __future__ import annotations

import logging
import os
from pathlib import Path

logger = logging.getLogger(__name__)

#: Как се казват календарите в `export_xml`.
СЕДЕМ = "7-day"
ПЕТ = "5-day"

_ОТ_СЕДМИЦА = {"5/5": ПЕТ, "7/7": СЕДЕМ}


def declared_work_week() -> str:
    """Изрично обявената от човека работна седмица, или „"."""
    сурово = str(os.getenv("WORK_WEEK", "") or "").strip()
    if not сурово:
        return ""
    ниско = сурово.lower().replace(" ", "")
    if ниско in ("5", "5/5", "5x5", "5дни", "петдневна"):
        return "5/5"
    if ниско in ("7", "7/7", "7x7", "7дни", "седемдневна"):
        return "7/7"
    logger.warning("WORK_WEEK=%s не се разбира — пренебрегва се.", сурово)
    return ""


def resolve(base_path: str | Path | None = None) -> dict:
    """Кой календар да се ползва и защо.

    Returns:
        {календар, седмица, източник, от_договора, обяснение}
    """
    от_човека = declared_work_week()
    от_договора = ""
    if base_path:
        try:
            from src.contract_data import read_contract

            от_договора = str(read_contract(base_path).get(
                "работна_седмица") or "")
        except Exception as exc:                     # noqa: BLE001
            logger.warning("Договорният календар не се прочете: %s", exc)

    if от_човека:
        седмица, източник = от_човека, "обявено от човека (WORK_WEEK)"
    elif от_договора:
        седмица, източник = от_договора, "от договора (Под-Клауза 6.5)"
    else:
        седмица, източник = "7/7", "подразбиране"

    календар = _ОТ_СЕДМИЦА.get(седмица, СЕДЕМ)
    обяснение = f"Календар {седмица} — {източник}."
    if от_договора and от_човека and от_договора != от_човека:
        обяснение += (f"  ВНИМАНИЕ: договорът казва {от_договора}, а е обявено "
                      f"{от_човека} — важи обявеното, но разликата е твоя "
                      f"отговорност.")
    return {"календар": календар, "седмица": седмица, "източник": източник,
            "от_договора": от_договора, "обяснение": обяснение}


def check(base_path: str | Path | None, calendar_type: str) -> list[str]:
    """Може ли да се изнесе с ТОЗИ календар.  Празен списък значи да.

    Отказът е нарочно груб: по-добре износът да спре, отколкото да излезе файл,
    в който всяка дата е изместена с 40 %.
    """
    решение = resolve(base_path)
    от_договора = решение["от_договора"]
    if not от_договора:
        return []
    очакван = _ОТ_СЕДМИЦА.get(от_договора, СЕДЕМ)
    if очакван == calendar_type:
        return []
    if declared_work_week():
        # Човекът е решил друго и го знае — минава, но се записва.
        logger.warning("Изнася се с %s, докато договорът казва %s — по изрично "
                       "решение на човека.", calendar_type, от_договора)
        return []
    return [
        f"Договорът обявява работна седмица {от_договора} (Под-Клауза 6.5), а "
        f"графикът се изнася с календар „{calendar_type}“.  Всяка календарна "
        f"дата във файла ще е изместена с около 40 %.  Изнеси с {очакван} или "
        f"потвърди изрично с WORK_WEEK={от_договора.split('/')[0]}."
    ]
