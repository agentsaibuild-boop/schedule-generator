def read_doc(path: str | Path) -> dict[str, Any]:
    """Прочети стар `.doc` — абзаци, таблици и целия текст.

    Резултатът е с формата на `file_manager._convert_docx`, за да влиза на
    същото място надолу по веригата.

    Args:
        path: Пътят до `.doc` файла.

    Returns:
        {"paragraphs", "tables", "full_text"}.

    Raises:
        DocError: Файлът не е четим като стар Word документ.
    """
    сурово = Path(path).read_bytes()
    ole = _Ole(сурово)
    word = ole.stream("WordDocument")
    if not word:
        raise DocError("липсва потокът WordDocument")

    fcClx, lcbClx, втора = _таблица_на_парчетата(word)
    таблица = ole.stream("1Table" if втора else "0Table")
    if not таблица:
        таблица = ole.stream("0Table") or ole.stream("1Table")
    if not таблица:
        raise DocError("липсва потокът с таблицата на парчетата")

    clx = таблица[fcClx:fcClx + lcbClx]
    текст = _без_полета(_текст(word, _парчета(clx)))
    абзаци, таблици = _разбор(текст)

    редове_на_таблиците: list[str] = []
    for т in таблици:
        редове_на_таблиците.append(" | ".join(т["headers"]))
        редове_на_таблиците.extend(
            " | ".join(str(v) for v in ред.values()) for ред in т["rows"])

    logger.info("Прочетен .doc %s: %d абзаца, %d таблици",
                Path(path).name, len(абзаци), len(таблици))
    return {
        "paragraphs": абзаци,
        "tables": таблици,
        "full_text": "\n".join(абзаци + редове_на_таблиците),
    }
