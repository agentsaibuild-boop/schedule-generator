"""Старият двоичен Word (`.doc`) — прочетен без външна зависимост.

ЗАЩО ГО ИМА.  Тръжните документи в България масово са `.doc`.  Проба на
24.08.2026: в „ВиК Хасково — Харманли довеждащ" ЦЯЛАТА техническа
спецификация е един `.doc` от 649 KB, а количеството в нея е единственият
вход за графика.  Приложението не само не можеше да го прочете — `.doc` дори
не беше в списъка на поддържаните разширения, тоест файлът не се и виждаше.
Същото се повтори и в „Община Казанлък", и във „ВиК Русе".

ЗАЩО НЕ С ГОТОВА БИБЛИОТЕКА.  `antiword` го няма под Windows, LibreOffice не
е инсталиран, а автоматизирането на Word през COM е Windows-only и чупливо в
Streamlit.  Форматът обаче е документиран и четенето му е двеста реда.

КАК Е УСТРОЕН.  Един `.doc` е OLE контейнер (Compound File Binary) с няколко
потока.  Текстът НЕ е един непрекъснат низ: той е разкъсан на „парчета"
(pieces), чиято карта стои в отделен поток — таблицата на парчетата.  Всяко
парче казва къде е текстът му и дали е 8-битов (компресиран) или UTF-16.
Затова наивното вадене на низове от файла връща само шум — проверено.

    OLE контейнер
      ├── WordDocument     самият текст, на парчета, плюс заглавния блок (FIB)
      ├── 0Table / 1Table  таблицата на парчетата (кой от двата казва FIB)
      └── …                стилове, картинки — не ни трябват

ТАБЛИЦИТЕ.  В стария Word няма отделна структура за таблица: краят на клетка и
краят на ред са един и същ знак (0x07).  Разликата е в свойствата на абзаца,
не в текста.  Затова тук се ползва правилото, което върши работа на практика:
ПРАЗНА клетка затваря реда.  Проверено срещу истинската спецификация — виж
`tests/test_doc_reader.py`.
"""

from __future__ import annotations

import logging
import struct
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

#: Подписът на OLE контейнер.
_OLE_MAGIC = b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1"

#: Край на верига от сектори, и „свободен сектор".
_END_OF_CHAIN = 0xFFFFFFFE
_FREE_SECTOR = 0xFFFFFFFF

#: Знаци на Word със служебно значение в текстовия поток.
_CELL_OR_ROW_END = "\x07"
_FIELD_BEGIN, _FIELD_SEPARATOR, _FIELD_END = "\x13", "\x14", "\x15"


class DocError(Exception):
    """Файлът не е четим като стар Word документ."""


# ---------------------------------------------------------------------------
# OLE контейнерът
# ---------------------------------------------------------------------------

class _Ole:
    """Минимален четец на Compound File Binary — само каквото ни трябва."""

    def __init__(self, raw: bytes) -> None:
        if not raw.startswith(_OLE_MAGIC):
            raise DocError("файлът не е OLE контейнер")
        self.raw = raw
        self.sector_size = 1 << struct.unpack_from("<H", raw, 0x1E)[0]
        self.mini_sector_size = 1 << struct.unpack_from("<H", raw, 0x20)[0]
        self.mini_cutoff = struct.unpack_from("<I", raw, 0x38)[0]
        първа_директория = struct.unpack_from("<I", raw, 0x30)[0]
        първа_мини_fat = struct.unpack_from("<I", raw, 0x3C)[0]

        self.fat = self._прочети_fat()
        self.mini_fat = self._вериги(self._поток_по_вериги(първа_мини_fat))
        self.entries = self._директория(първа_директория)
        self.mini_stream = self._мини_поток()

    # -- сектори -----------------------------------------------------------

    def _отместване(self, сектор: int) -> int:
        return 512 + сектор * self.sector_size

    def _сектор(self, номер: int) -> bytes:
        нач = self._отместване(номер)
        return self.raw[нач:нач + self.sector_size]

    def _прочети_fat(self) -> list[int]:
        """FAT-ът: за всеки сектор — следващият във веригата."""
        брой = struct.unpack_from("<I", self.raw, 0x2C)[0]
        секторите: list[int] = list(struct.unpack_from("<109I", self.raw, 0x4C))
        # DIFAT продължението — при големи файлове 109 записа не стигат.
        следващ = struct.unpack_from("<I", self.raw, 0x44)[0]
        while следващ not in (_END_OF_CHAIN, _FREE_SECTOR) and len(секторите) < брой + 109:
            блок = self._сектор(следващ)
            на_блок = self.sector_size // 4 - 1
            секторите.extend(struct.unpack_from(f"<{на_блок}I", блок, 0))
            следващ = struct.unpack_from("<I", блок, на_блок * 4)[0]

        fat: list[int] = []
        for с in секторите[:брой]:
            if с in (_END_OF_CHAIN, _FREE_SECTOR):
                continue
            блок = self._сектор(с)
            fat.extend(struct.unpack_from(f"<{len(блок) // 4}I", блок, 0))
        return fat

    def _вериги(self, данни: bytes) -> list[int]:
        return list(struct.unpack_from(f"<{len(данни) // 4}I", данни, 0)) if данни else []

    def _поток_по_вериги(self, начало: int, размер: int | None = None) -> bytes:
        """Съдържанието на поток от обикновени сектори."""
        части: list[bytes] = []
        сектор = начало
        видени: set[int] = set()
        while сектор not in (_END_OF_CHAIN, _FREE_SECTOR) and сектор < len(self.fat):
            if сектор in видени:                # повреден файл — не се въртим
                break
            видени.add(сектор)
            части.append(self._сектор(сектор))
            сектор = self.fat[сектор]
        данни = b"".join(части)
        return данни[:размер] if размер is not None else данни

    # -- директория и потоци ----------------------------------------------

    def _директория(self, начало: int) -> dict[str, tuple[int, int]]:
        """Име на поток → (начален сектор, размер)."""
        данни = self._поток_по_вериги(начало)
        записи: dict[str, tuple[int, int]] = {}
        self._root: tuple[int, int] = (0, 0)
        for отм in range(0, len(данни) - 127, 128):
            дължина = struct.unpack_from("<H", данни, отм + 0x40)[0]
            if not дължина:
                continue
            име = данни[отм:отм + дължина - 2].decode("utf-16-le", "ignore")
            вид = данни[отм + 0x42]
            сектор = struct.unpack_from("<I", данни, отм + 0x74)[0]
            размер = struct.unpack_from("<Q", данни, отм + 0x78)[0]
            if вид == 5:                                    # коренът
                self._root = (сектор, размер)
            elif вид == 2:                                  # поток
                записи[име] = (сектор, размер)
        return записи

    def _мини_поток(self) -> bytes:
        сектор, размер = self._root
        return self._поток_по_вериги(сектор, размер)

    def stream(self, име: str) -> bytes:
        """Съдържанието на поток по име.  Празно, ако го няма."""
        if име not in self.entries:
            return b""
        сектор, размер = self.entries[име]
        if размер < self.mini_cutoff:
            части: list[bytes] = []
            текущ = сектор
            видени: set[int] = set()
            while текущ not in (_END_OF_CHAIN, _FREE_SECTOR) and текущ < len(self.mini_fat):
                if текущ in видени:
                    break
                видени.add(текущ)
                нач = текущ * self.mini_sector_size
                части.append(self.mini_stream[нач:нач + self.mini_sector_size])
                текущ = self.mini_fat[текущ]
            return b"".join(части)[:размер]
        return self._поток_по_вериги(сектор, размер)


# ---------------------------------------------------------------------------
# Word: заглавен блок и таблица на парчетата
# ---------------------------------------------------------------------------

def _таблица_на_парчетата(fib: bytes) -> tuple[int, int, bool]:
    """(отместване на CLX, дължина, дали таблицата е „1Table").

    Дължините на трите блока в заглавието се четат от самия него, а не се
    приемат за фиксирани — така четенето важи и за по-старите му версии.
    """
    if len(fib) < 64 or struct.unpack_from("<H", fib, 0)[0] != 0xA5EC:
        raise DocError("липсва заглавният блок на Word (FIB)")
    флагове = struct.unpack_from("<H", fib, 0x0A)[0]
    втора_таблица = bool(флагове & 0x0200)

    поз = 32
    csw = struct.unpack_from("<H", fib, поз)[0]
    поз += 2 + csw * 2
    cslw = struct.unpack_from("<H", fib, поз)[0]
    поз += 2 + cslw * 4
    поз += 2                                   # cbRgFcLcb
    # fcClx е 34-тата двойка (индекс 33) в FibRgFcLcb97.
    отм = поз + 33 * 8
    if отм + 8 > len(fib):
        raise DocError("заглавният блок е отрязан")
    fcClx, lcbClx = struct.unpack_from("<II", fib, отм)
    return fcClx, lcbClx, втора_таблица


def _парчета(clx: bytes) -> list[tuple[int, int, int, bool]]:
    """Парчетата текст: (начален знак, краен знак, отместване, компресиран).

    CLX е поредица от блокове; интересува ни онзи с етикет 0x02 — самата
    таблица на парчетата.  Преди него може да стои произволен брой блокове
    със стилове (0x01), които се прескачат по обявената си дължина.
    """
    поз = 0
    while поз < len(clx):
        етикет = clx[поз]
        if етикет == 0x01:
            дължина = struct.unpack_from("<H", clx, поз + 1)[0]
            поз += 3 + дължина
            continue
        if етикет != 0x02:
            raise DocError(f"непознат блок в таблицата на парчетата: {етикет}")
        lcb = struct.unpack_from("<I", clx, поз + 1)[0]
        тяло = clx[поз + 5:поз + 5 + lcb]
        break
    else:
        raise DocError("таблицата на парчетата липсва")

    брой = (len(тяло) - 4) // 12
    if брой <= 0:
        return []
    знаци = struct.unpack_from(f"<{брой + 1}I", тяло, 0)
    из: list[tuple[int, int, int, bool]] = []
    основа = (брой + 1) * 4
    for i in range(брой):
        fc = struct.unpack_from("<I", тяло, основа + i * 8 + 2)[0]
        компресиран = bool(fc & 0x40000000)
        отместване = (fc & 0x3FFFFFFF) // 2 if компресиран else (fc & 0x3FFFFFFF)
        из.append((знаци[i], знаци[i + 1], отместване, компресиран))
    return из


#: Кодировките, с които се пробва 8-битов текст.  Български пръв — тръжните
#: документи са на кирилица, а cp1252 би дал безсмислици.
_CODEPAGES = ("cp1251", "cp1252")


def _текст(word: bytes, парчета: list[tuple[int, int, int, bool]]) -> str:
    части: list[str] = []
    for нач_знак, кр_знак, отместване, компресиран in парчета:
        брой = max(0, кр_знак - нач_знак)
        if компресиран:
            сурово = word[отместване:отместване + брой]
            за_декодиране = сурово
            for кодировка in _CODEPAGES:
                try:
                    части.append(за_декодиране.decode(кодировка))
                    break
                except UnicodeDecodeError:
                    continue
            else:
                части.append(за_декодиране.decode("cp1251", "replace"))
        else:
            сурово = word[отместване:отместване + брой * 2]
            части.append(сурово.decode("utf-16-le", "replace"))
    return "".join(части)


# ---------------------------------------------------------------------------
# От текст към абзаци и таблици
# ---------------------------------------------------------------------------

def _без_полета(текст: str) -> str:
    """Изхвърли кодовете на полетата, запази показвания им резултат.

    Между 0x13 и 0x14 стои КОДЪТ („PAGE", „REF _Ref123"), а между 0x14 и 0x15
    — това, което човек вижда.  Без това в текста влизат парчета команди.
    """
    из: list[str] = []
    в_код = False
    for знак in текст:
        if знак == _FIELD_BEGIN:
            в_код = True
        elif знак == _FIELD_SEPARATOR:
            в_код = False
        elif знак == _FIELD_END:
            в_код = False
        elif not в_код:
            из.append(знак)
    return "".join(из)


def _почисти(парче: str) -> str:
    за_махане = "\x00\x01\x02\x05\x08\x0c\x1e\x1f﻿"
    почистено = "".join(" " if з in за_махане else з for з in парче)
    return " ".join(почистено.split())


#: Кога празнината между два знака за край на клетка значи „между ДВЕ таблици".
#:
#: ИЗМЕРЕНО върху истинска спецификация (24.08.2026, 177 знака за край на
#: клетка): 169 от 176 празнини са под 200 знака — това са клетки.  Останалите
#: седем са 271, 499, 924, 1664, 5749, 7737 и 8570 знака.  ДЪЛЖИНАТА не ги
#: дели: клетка с дълго изречение стига 924 знака.  Дели ги броят на АБЗАЦИТЕ
#: вътре — истинските междини носят 20, 28, 65 и 352 абзаца, а дългите клетки
#: нула до три — заглавна клетка на два реда дава три абзацни знака
#: (водещ, между редовете и завършващ).  Затова прагът е 6, с резерв.
_МАКС_АБЗАЦИ_В_КЛЕТКА = 6
#: Втора ограда за всеки случай: толкова знака не е клетка, каквото и да пише.
_МАКС_ПРАЗНИНА = 2000


def _области_с_таблици(текст: str) -> list[tuple[int, int]]:
    """Къде в текста има таблици — по гроздовете знаци за край на клетка.

    Разборът НЕ може да се направи на един проход, защото клетката съдържа
    свои абзаци: заглавието „Диаметър⏎Ф /mm/" е ЕДНА клетка на два реда.  Ако
    абзацният знак затваря парчето, таблицата се разпада на отделни редове —
    точно това стана при спецификацията на Харманли, чиято количествена
    таблица излизаше с нула реда.

    Затова първо се намират ОБЛАСТИТЕ, а вътре в тях абзацният знак е просто
    нов ред в клетката.
    """
    места = [i for i, з in enumerate(текст) if з == _CELL_OR_ROW_END]
    if not места:
        return []
    гроздове: list[list[int]] = [[места[0]]]
    for м in места[1:]:
        предишен = гроздове[-1][-1]
        празнина = текст[предишен + 1:м]
        в_същата = (len(празнина) < _МАКС_ПРАЗНИНА
                    and празнина.count("\r") <= _МАКС_АБЗАЦИ_В_КЛЕТКА)
        if в_същата:
            гроздове[-1].append(м)
        else:
            гроздове.append([м])

    области: list[tuple[int, int]] = []
    for грозд in гроздове:
        начало = текст.rfind("\r", 0, грозд[0])
        области.append((начало + 1 if начало >= 0 else 0, грозд[-1] + 1))
    return области


def _таблица_от_област(парче: str) -> dict | None:
    """Една таблица от областта си: клетките се делят на 0x07.

    ПРАЗНА КЛЕТКА ЗАТВАРЯ РЕДА.  В стария Word краят на клетка и краят на ред
    са един и същ знак; разликата е в свойствата на абзаца, не в текста.  Но
    редовият знак идва без съдържание пред себе си, и това се вижда в потока.
    """
    редове: list[list[str]] = []
    клетки: list[str] = []
    for сурова in парче.split(_CELL_OR_ROW_END):
        стойност = _почисти(сурова.replace("\r", " "))
        if стойност:
            клетки.append(стойност)
        elif клетки:
            редове.append(клетки)
            клетки = []
    if клетки:
        редове.append(клетки)
    if not редове:
        return None
    заглавия = [з or f"кол.{i + 1}" for i, з in enumerate(редове[0])]
    return {"headers": заглавия,
            "rows": [dict(zip(заглавия, ред)) for ред in редове[1:]]}


def _разбор(текст: str) -> tuple[list[str], list[dict]]:
    """Абзаците и таблиците, разделени."""
    области = _области_с_таблици(текст)
    абзаци: list[str] = []
    таблици: list[dict] = []

    предишен_край = 0
    for начало, край in области:
        for ред in текст[предишен_край:начало].split("\r"):
            стойност = _почисти(ред)
            if стойност:
                абзаци.append(стойност)
        таблица = _таблица_от_област(текст[начало:край])
        if таблица:
            таблици.append(таблица)
        предишен_край = край

    for ред in текст[предишен_край:].split("\r"):
        стойност = _почисти(ред)
        if стойност:
            абзаци.append(стойност)
    return абзаци, таблици


