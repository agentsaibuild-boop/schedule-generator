"""Етапите на изпълнение ги прави КОДЪТ, когато геометрия няма.

ЗАЩО.  Измерено на 18.08.2026 върху 30 живи прогона на ЕДИН И СЪЩ търг:

    брой пакети, върнати от модела:
    22, 30, 32, 35, 35, 36, 36, 40, 40, 42, 47, 51, 52, 52, 55, 61, 62, 63,
    66, 70, 73, 74, 100, 132

Шесткратен разброс.  И всичките провали са на едно място:

    прогонът умира изобщо              6 от 30
    счупен JSON                        7 от 24
    Σ ≠ КСС                            8 от 24
    roll-up, надзор, ресурси, цитати   0 от 24

Нито един структурен инвариант надолу по веригата не пада.  Чупи се само
получаването на използваем отговор от модела.

А отговорът, който искахме от него, е невъзможен по информация, не по промпт:

  * КСС НЕ съдържа разчленяване — 0 от 28 реда с количество носят
    идентификатор на участък; всеки ред е насипно количество за целия квартал;
  * класификацията, за която моделът уж трябваше, кодът я прави сам:
    `_coverer_class` рутира 28 от 28 реда — 100%;
  * без DWG/DXF, GIS или таблица с участъци възлите не могат да бъдат
    твърдени (виж `spatial_source`).

Тоест молехме модела да СЪЧИНИ данни, които ги няма във входа, и после
цялата система поправяше последствията.  Тук това спира: без авторитетна
геометрия участъците са ЕТАПИ НА ИЗПЪЛНЕНИЕ — организационно решение, което
кодът има право да вземе и да обяви — а не физически трасета.

Σ = КСС престава да бъде гейт, който се надяваме да мине: количествата се
разделят тук, тоест нарушаването им е невъзможно по конструкция.

КАКВО ТОВА НЕ Е.  Не е заместител на `PhysicalSegment`.  Щом се появи
DWG/DXF, GIS слой или таблица с участъци, участъците идват ОТТАМ и този модул
не се вика.  Дотогава етапите се именуват като етапи и никой не ги показва за
трасета — за това се грижи `number_execution_batches`.
"""

from __future__ import annotations

import logging
import os
from typing import Any, Iterable

logger = logging.getLogger(__name__)

#: Клас на реда → веригата, която ГАРАНТИРАНО го покрива, независимо от листа.
#: Настилките и кабелите живеят в собствени пакети и в еталонния график.
_CLASS_CHAIN = {"pavement": "pavement_section", "cable": "cable_section"}

_NETWORK_CHAIN = {"В": "water_section", "К": "sewer_section",
                  "П": "pavement_section", "ЕЛ": "cable_section"}

_CHAIN_NETWORK = {v: k for k, v in _NETWORK_CHAIN.items()}

#: Кой лист на КСС е коя мрежа.
_SHEET_NETWORK = (
    ("vodoprovod", "В"),
    ("водопровод", "В"),
    ("kanaliz", "К"),
    ("канализац", "К"),
    ("пътни", "П"),
    ("patni", "П"),
    ("пътна", "П"),
    ("ел и тт", "ЕЛ"),
)

#: Колко етапа на верига.  ИЗМЕРЕНО, не избрано: детерминистичният прогон дава
#: 897 дни при 8 етапа и 956 при 14 — по-финото делене влошава срока, защото
#: всеки етап носи наново неделимите стъпки.  Мени се през средата, защото е
#: организационно решение, не природен закон.
DEFAULT_BATCHES = int(os.getenv("EXECUTION_BATCHES", "8") or 8)


def _sheet_of(ref: str) -> str:
    parts = str(ref).split("!")
    return parts[1] if len(parts) >= 3 else ""


def _network_of(ref: str) -> str:
    sheet = _sheet_of(ref).lower()
    for needle, network in _SHEET_NETWORK:
        if needle in sheet:
            return network
    return ""


#: Точкови класове — брой, не метри.
_ТОЧКОВИ = frozenset({"manhole"})

#: Веригата за възстановяване — тя не е самостоятелна работа, а следствие.
_RESTORATION_CHAIN = "pavement_section"

#: Вериги, които са ТРАСЕ: настилката върви след тях, участък по участък.
_ТРАСОВИ = frozenset({"sewer_section", "water_section", "water_section_hdd",
                      "cable_section"})

#: Мерки, при които количеството е БРОЙ и не се дели под единица.
_БРОЙНИ_МЕРКИ = frozenset({"бр", "бр.", "брой", "броя", "бройки", "pcs", "pc"})

#: Таван на отделните съоръжения, за да не се роди график от хиляди задачи при
#: търг с двеста шахти.  Над него се групират и това се вижда в бележките.
_МАКС_СЪОРЪЖЕНИЯ = int(os.getenv("MAX_STANDALONE_STRUCTURES", "40") or 40)


def _клас(row: Any) -> str | None:
    from src.provenance import _coverer_class
    return _coverer_class(row)


def _самостоятелно_съоръжение(row: Any) -> bool:
    """Дали позицията се лее на място от ОТДЕЛЕН екип.

    Разделението идва от еталона, не от догадка: СКО и УО ги няма там като
    отделни задачи (правят се в съставната стъпка на участъка), а „Водомерна
    шахта" стои като своя задача.  Списъкът е в `config/tech_chains.json`,
    ключ `standalone_structures`, с обосновката до него.
    """
    import re

    from src.work_package import load_chains

    шаблони = ((load_chains() or {}).get("standalone_structures") or {}).get(
        "patterns") or []
    описание = str(getattr(row, "description", "") or "")
    return any(re.search(ш, описание, re.IGNORECASE) for ш in шаблони)


def split_exactly(total: float, parts: int) -> list[float]:
    """Раздели на `parts` дяла, чийто сбор е ТОЧНО `total`.

    Последният дял поема остатъка от закръглянето.  Без това самото
    разделяне внася дрейфа, заради който Σ ≠ КСС падаше в 8 от 24 прогона.
    """
    if parts <= 1:
        return [total]
    share = round(total / parts, 6)
    head = [share] * (parts - 1)
    return head + [round(total - share * (parts - 1), 6)]


def allocate_execution_batches(
    boq_index: Iterable[Any],
    batches_per_chain: int = 0,
) -> dict[str, Any]:
    """Разпределя КСС на етапи по вериги — детерминистично и без модел.

    Returns:
        {"packages": [...], "unroutable": [...], "notes": [...]} — `packages`
        е СЪЩИЯТ вид, който `packages_from_ai` очаква, за да мине през
        всичките му проверки (клас от описанието, конфликт на диаметри,
        запазване на количествата).
    """
    брой = int(batches_per_chain or DEFAULT_BATCHES)
    брой = max(1, брой)

    from src.provenance import _coverer_class, is_duration_row

    кофи: dict[str, list[Any]] = {}
    неразпределими: list[str] = []
    продължителности: list[str] = []

    for row in boq_index or []:
        quantity = getattr(row, "quantity", None)
        if not isinstance(quantity, (int, float)) or isinstance(quantity, bool):
            continue                      # заглавия и „ОБЩО" — нямат количество
        if is_duration_row(row):
            # „ПРОЕКТИРАНЕ 120 Календарни Дни" не е работа за разпределяне, а
            # обявен срок на договорна фаза.  Не влиза в участъците.
            продължителности.append(str(row.ref))
            continue
        клас = _coverer_class(row)
        if not клас:
            неразпределими.append(str(row.ref))
            continue
        верига = _CLASS_CHAIN.get(клас) or _NETWORK_CHAIN.get(
            _network_of(row.ref), "")
        if not верига:
            неразпределими.append(str(row.ref))
            continue
        кофи.setdefault(верига, []).append(row)

    # НАСТИЛКИТЕ СЛЕДВАТ ТРАСЕТО, НЕ СТОЯТ НАКРАЯ (19.08.2026).
    #
    # Сравнение с човешкия еталон: той възстановява настилки от ден 131 до
    # 774 — през целия строеж, 70 задачи, вървейки след всеки завършен
    # участък.  Ние ги трупахме накрая (514→712) и точно те определяха края
    # на обекта.
    #
    # Причината е в количествата: „Пътна — възстановяване на настилка"
    # е 10824 кв.м за ЦЕЛИЯ квартал, тоест общообектов ред, който ставаше
    # свой пакет.  Човекът го пише по участъци.
    #
    # Затова тук настилката получава ПО ЕДИН ПАКЕТ НА УЧАСТЪК ОТ ТРАСЕТО, в
    # същия ред: тогава вълните съвпадат едно към едно и кл. N възстановява
    # своята настилка, щом засипе своя изкоп.
    редове_настилка = кофи.pop(_RESTORATION_CHAIN, [])

    packages: list[dict] = []
    for верига, всички in sorted(кофи.items()):
        мрежа = _CHAIN_NETWORK[верига]

        # СЪОРЪЖЕНИЯТА СА ОТДЕЛНА РАБОТА, ОТ ОТДЕЛЕН ЕКИП (19.08.2026).
        #
        # Шахтите — улични оттоци, преливна, монолитни РШ — не ги прави
        # бригадата на тръбите.  Идва отделна група, която върши само това, а
        # работата ѝ ВЪРВИ УСПОРЕДНО с трасето.  Затова я няма и в еталонния
        # график като отделен ред: тя не движи срока.
        #
        # Дотук те попадаха в стъпката за полагане, на фронта на тръбната
        # бригада, и я държаха заета.  Измерено на този търг: ЕДНА преливна
        # шахта, разцепена на осемте етапа, изяждаше 8 × 17 = 136 бригадо-дни
        # от екипа, който полага тръбите — за позиция, която дори няма норма.
        #
        # И не се разцепва: шахтата е БРОЙ, не метри.  Една осма от шахта не е
        # нищо на обекта, а само начин подът от един ден да се плати осем пъти.
        точкови = [r for r in всички
                   if _клас(r) in _ТОЧКОВИ and _самостоятелно_съоръжение(r)]
        линейни = [r for r in всички if r not in точкови]

        # ПО ЕДИН ПАКЕТ НА БРОЙ, не на позиция.
        #
        # Изпълнителят (19.08.2026): „едни правят кофража, други армировката,
        # трети леят бетона.  Когато свършат с кофража на първата, отиват към
        # втората, а на първата започва армировката — има застъпване."
        #
        # Тоест същият конвейер като по трасето, но между СЪОРЪЖЕНИЯ.  За да
        # може кофражната бригада да мине напред, всяка шахта трябва да е свой
        # пакет: заетостта е (мрежа, операция, бригада), затова десет шахти в
        # ЕДИН пакет биха се изпълнявали като една дълга редица.
        for н, row in enumerate(точкови, 1):
            # НЕ се казва `брой` — така се казва броят ЕТАПИ на трасето по-долу
            # и презаписването му остави мрежата с един етап вместо осем.
            екземпляри = max(1, int(round(float(row.quantity))))
            екземпляри = min(екземпляри, _МАКС_СЪОРЪЖЕНИЯ)
            дялове = split_exactly(float(row.quantity), екземпляри)
            описание = str(getattr(row, "description", "") or "").strip()
            for к, дял in enumerate(дялове, 1):
                packages.append({
                    "id": f"С{мрежа}{н}_{к}" if екземпляри > 1 else f"С{мрежа}{н}",
                    "name": (f"{описание} №{к}" if екземпляри > 1
                             else описание or f"Съоръжение {н}"),
                    "network": мрежа,
                    "chain": "structure",
                    "items": [{"source_ref": str(row.ref), "quantity": дял}],
                })

        редове = линейни
        if not редове:
            continue
        етапи: list[dict] = [
            {
                "id": f"{мрежа}{i + 1}",
                # ИМЕТО КАЗВА КАКВО Е.  Никакви „от РШ 1 до РШ 2": това е етап
                # на изпълнение, не трасе, и не бива да изглежда като прочетена
                # геометрия в MS Project.
                "name": f"Етап {i + 1} от {брой}",
                "network": мрежа,
                "chain": верига,
                "items": [],
            }
            for i in range(брой)
        ]
        for отместване, row in enumerate(редове):
            # БРОЯТ НЕ СЕ ДЕЛИ ПОД ЕДИНИЦА.
            #
            # Една водомерна шахта, разцепена на осем етапа, дава осем задачи по
            # един ден вместо една от пет — количеството е вярно, а работата е
            # измислена.  Затова редът се дели най-много на толкова части,
            # колкото брои: една шахта отива в ЕДИН етап.
            #
            # Отместването върти началния етап, за да не се струпат всичките
            # единични позиции в първия.
            части = брой
            ед = str(getattr(row, "unit", "") or "").strip().lower()
            if ед in _БРОЙНИ_МЕРКИ:
                части = max(1, min(брой, int(float(row.quantity))))
            дялове = split_exactly(float(row.quantity), части)
            for н, дял in enumerate(дялове):
                if дял <= 0:
                    continue
                pkg = етапи[(отместване + н) % len(етапи)]
                pkg["items"].append(
                    {"source_ref": str(row.ref), "quantity": дял})
        packages.extend(p for p in етапи if p["items"])

    трасови = [p for p in packages if p["chain"] in _ТРАСОВИ]
    if редове_настилка and трасови:
        тегла = [sum(float(i["quantity"]) for i in p["items"]) or 1.0
                 for p in трасови]
        общо_тегло = sum(тегла)
        настилки: list[dict] = []
        for и, (p, тегло) in enumerate(zip(трасови, тегла), 1):
            настилки.append({
                "id": f"П{и}",
                "name": f"Възстановяване на настилката — {p['name']}",
                "network": "П", "chain": _RESTORATION_CHAIN, "items": [],
            })
        for row in редове_настилка:
            дялове = [float(row.quantity) * т / общо_тегло for т in тегла]
            # Последният поема остатъка от закръглянето — Σ остава точно КСС.
            дялове = [round(д, 6) for д in дялове[:-1]]
            дялове.append(round(float(row.quantity) - sum(дялове), 6))
            for pkg, дял in zip(настилки, дялове):
                if дял > 0:
                    pkg["items"].append(
                        {"source_ref": str(row.ref), "quantity": дял})
        packages.extend(p for p in настилки if p["items"])

    бележки = [
        f"Участъците са направени от кода: {len(packages)} етапа на изпълнение "
        f"по {брой} на верига, количествата разделени точно по КСС."
    ]
    if редове_настилка and трасови:
        бележки.append(
            f"Настилките следват трасето: {len(трасови)} пакета, по един на "
            "участък, вместо отделни етапи накрая.")
    if продължителности:
        бележки.append(
            f"{len(продължителности)} реда обявяват договорна ПРОДЪЛЖИТЕЛНОСТ, "
            "не количество — не се разпределят по участъци.")
    if неразпределими:
        бележки.append(
            f"{len(неразпределими)} реда не попадат в нито една верига по "
            f"описание и лист: {', '.join(неразпределими[:5])}"
            + (" …" if len(неразпределими) > 5 else ""))
    for бележка in бележки:
        logger.info("%s", бележка)

    return {"packages": packages, "unroutable": неразпределими,
            "durations": продължителности, "notes": бележки}
