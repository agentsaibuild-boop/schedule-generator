def _отсечки_по_диаметър(segments: Iterable[Any] | None) -> dict[tuple, list[dict]]:
    """Прочетените от чертежа отсечки, групирани по (мрежа, диаметър).

    В обхвата на процедурата влизат само тези с `in_scope`.  Отсечка без
    дължина не може да носи дял от количество и се пропуска.
    """
    из: dict[tuple, list[dict]] = {}
    for s in segments or []:
        данни = s if isinstance(s, dict) else dict(s._asdict())
        if данни.get("in_scope") is False:
            continue
        мрежа = str(данни.get("network") or "").strip()
        dn = данни.get("dn")
        дължина = float(данни.get("length_m") or 0.0)
        if not мрежа or not dn or дължина <= 0:
            continue
        из.setdefault((мрежа, int(dn)), []).append(данни)
    return из


def _раздели_по_тегло(общо: float, тегла: list[float]) -> list[float]:
    """Дялове, пропорционални на теглата, чийто сбор е ТОЧНО `общо`.

    Последният дял поема остатъка от закръглянето — иначе разпределението
    само внася дрейфа, който гейтът за запазване на количествата после лови.
    """
    сбор = sum(тегла)
    if сбор <= 0:
        return split_exactly(общо, max(1, len(тегла)))
    дялове = [round(общо * т / сбор, 6) for т in тегла[:-1]]
    return дялове + [round(общо - sum(дялове), 6)]


def _добави_отсечки(packages: list[dict], редове: list[Any], верига: str,
                    мрежа: str, отсечки: list[dict]) -> tuple[int, int]:
    """По ЕДИН участък на ПРОЧЕТЕНА отсечка, вместо измислени етапи.

    Количеството на всеки ред се дели между отсечките ПРОПОРЦИОНАЛНО на
    измерените им дължини — по-дългата отсечка носи повече работа, точно както
    е на място.  Бройните позиции не се делят под единица.

    ИМЕТО ТУК Е ЗАКОННО.  По-долу стои предупреждение етапите да не се кръщават
    „от РШ 1 до РШ 2" — то важи за ИЗМИСЛЕНИ имена, които биха изглеждали като
    прочетена геометрия.  Тези имена ГИ ИМА в чертежа: „Кл.48" и улицата са
    прочетени етикети.  Затова тук името казва истината, а не преструвка.
    """
    отсечки = sorted(отсечки, key=lambda о: -float(о.get("length_m") or 0.0))

    # ЧЕРТЕЖЪТ Е ПРОЕКТЪТ, ТЪРГЪТ Е ЕТАП ОТ НЕГО.
    #
    # Измерено 21.08.2026 на реален търг: за водопровода Ф110 чертежът показва
    # 5327 м, оразмерителната таблица потвърждава ~4956 м, а спецификацията
    # купува 1760 м.  Тоест процедурата е ЧАСТ от проектираната мрежа — и никой
    # от наличните документи не казва КОИ клонове са в нея.
    #
    # Ако всичките се вземат за участъци, договорните 1760 м се размазват на 53
    # парчета по 33 м: количеството остава вярно, но работата се раздробява и
    # срокът се раздува с неделимите стъпки на всеки участък.
    #
    # Затова се взимат толкова отсечки, колкото КУПЕНОТО количество носи при
    # РЕАЛНИЯ им размер — от най-дългата надолу, докато се покрие.  Така
    # участъкът остава с истинската си дължина, а броят му следва договора.
    # Изборът кои точно е произволен и това се КАЗВА в бележките; когато
    # проектантът посочи клоновете, тук няма да има какво да се реже.
    купено = sum(float(r.quantity) for r in редове
                 if str(getattr(r, "unit", "") or "").strip().lower()
                 in _ЛИНЕЙНИ_МЕРКИ)
    начертано = sum(float(о.get("length_m") or 0.0) for о in отсечки)
    отрязани = 0
    if купено > 0 and начертано > купено * 1.05:
        покрито, задържани = 0.0, []
        for о in отсечки:
            задържани.append(о)
            покрито += float(о.get("length_m") or 0.0)
            if покрито >= купено:
                break
        отрязани = len(отсечки) - len(задържани)
        отсечки = задържани

    начало = len(packages) + 1

    пакети: list[dict] = []
    for i, о in enumerate(отсечки):
        клон = str(о.get("branch") or "").strip() or f"участък {i + 1}"
        улица = str(о.get("street") or "").strip()
        пакети.append({
            "id": f"{мрежа}{начало + i}",
            "name": f"{клон} по {улица}" if улица else клон,
            "network": мрежа,
            "chain": верига,
            "branch": клон,
            "street": улица,
            "items": [],
        })

    тегла = [float(о.get("length_m") or 0.0) for о in отсечки]
    for row in редове:
        количество = float(row.quantity)
        ед = str(getattr(row, "unit", "") or "").strip().lower()
        if ед in _БРОЙНИ_МЕРКИ:
            части = max(1, min(len(пакети), int(количество)))
            дялове = (split_exactly(количество, части)
                      + [0.0] * (len(пакети) - части))
        else:
            дялове = _раздели_по_тегло(количество, тегла)
        for пакет, дял in zip(пакети, дялове):
            if дял > 0:
                пакет["items"].append(
                    {"source_ref": str(row.ref), "quantity": дял})

    packages.extend(p for p in пакети if p["items"])
    return len(пакети), отрязани


def _добави_етапи(packages: list[dict], редове: list[Any], верига: str,
                  мрежа: str, брой: int, етикет: str = "") -> None:
    """Етапите на ЕДНА група (един диаметър), с точно разделени количества."""
    брой = max(1, int(брой))
    начало = len(packages) + 1
    етапи = [
        {
            "id": f"{мрежа}{начало + i}",
            "name": f"Етап {i + 1} от {брой}{етикет}",
            "network": мрежа,
            "chain": верига,
            "items": [],
        }
        for i in range(брой)
    ]
    for отместване, row in enumerate(редове):
        части = брой
        ед = str(getattr(row, "unit", "") or "").strip().lower()
        if ед in _БРОЙНИ_МЕРКИ:
            части = max(1, min(брой, int(float(row.quantity))))
        for н, дял in enumerate(split_exactly(float(row.quantity), части)):
            if дял <= 0:
                continue
            етапи[(отместване + н) % len(етапи)]["items"].append(
                {"source_ref": str(row.ref), "quantity": дял})
    packages.extend(p for p in етапи if p["items"])


def _самостоятелно_съоръжение(row: Any) -> bool:
    """Дали позицията се лее на място от ОТДЕЛЕН екип.

    Разделението идва от еталона, не от догадка: СКО и УО ги няма там като
    отделни задачи (правят се в съставната стъпка на участъка), а „Водомерна
    шахта" стои като своя задача.  Списъкът е в `config/tech_chains.json`,
    ключ `standalone_structures`, с обосновката до него.
    """
    import re

    from src.work_package import load_chains

    шаблони = ((load_chains() or {}).get("standalone_structures") or {}).get(
        "patterns") or []
    описание = str(getattr(row, "description", "") or "")
    return any(re.search(ш, описание, re.IGNORECASE) for ш in шаблони)


def split_exactly(total: float, parts: int) -> list[float]:
    """Раздели на `parts` дяла, чийто сбор е ТОЧНО `total`.

    Последният дял поема остатъка от закръглянето.  Без това самото
    разделяне внася дрейфа, заради който Σ ≠ КСС падаше в 8 от 24 прогона.
    """
    if parts <= 1:
        return [total]
    share = round(total / parts, 6)
    head = [share] * (parts - 1)
    return head + [round(total - share * (parts - 1), 6)]


def allocate_execution_batches(
    boq_index: Iterable[Any],
    batches_per_chain: int = 0,
    segments: Iterable[Any] | None = None,
) -> dict[str, Any]:
    """Разпределя КСС на етапи по вериги — детерминистично и без модел.

    Args:
        boq_index: Количествените редове.
        batches_per_chain: На колко етапа да се дели верига, когато НЯМА
            прочетени отсечки.
        segments: Отсечките, прочетени от ситуационния чертеж.  Когато за
            даден диаметър ги има, участъците са ТЕ — с истинските си имена и
            с количества, разделени пропорционално на измерените дължини.
            Броят етапи е компромис за случая, в който геометрията липсва.

    Returns:
        {"packages": [...], "unroutable": [...], "notes": [...]} — `packages`
        е СЪЩИЯТ вид, който `packages_from_ai` очаква, за да мине през
        всичките му проверки (клас от описанието, конфликт на диаметри,
        запазване на количествата).
    """
    брой = int(batches_per_chain or DEFAULT_BATCHES)
    брой = max(1, брой)

    from src.provenance import _coverer_class, is_duration_row

    кофи: dict[str, list[Any]] = {}
    неразпределими: list[str] = []
    продължителности: list[str] = []
    прочетени_отсечки = _отсечки_по_диаметър(segments)
    от_чертежа: list[str] = []

    for row in boq_index or []:
        quantity = getattr(row, "quantity", None)
        if not isinstance(quantity, (int, float)) or isinstance(quantity, bool):
            continue                      # заглавия и „ОБЩО" — нямат количество
        if is_duration_row(row):
            # „ПРОЕКТИРАНЕ 120 Календарни Дни" не е работа за разпределяне, а
            # обявен срок на договорна фаза.  Не влиза в участъците.
            продължителности.append(str(row.ref))
            continue
        клас = _coverer_class(row)
        if not клас:
            неразпределими.append(str(row.ref))
            continue
        верига = _CLASS_CHAIN.get(клас) or _NETWORK_CHAIN.get(
            _network_of_row(row), "")
        if not верига:
            неразпределими.append(str(row.ref))
            continue
        кофи.setdefault(верига, []).append(row)

    # НАСТИЛКИТЕ СЛЕДВАТ ТРАСЕТО, НЕ СТОЯТ НАКРАЯ (19.08.2026).
    #
    # Сравнение с човешкия еталон: той възстановява настилки от ден 131 до
    # 774 — през целия строеж, 70 задачи, вървейки след всеки завършен
    # участък.  Ние ги трупахме накрая (514→712) и точно те определяха края
    # на обекта.
    #
    # Причината е в количествата: „Пътна — възстановяване на настилка"
    # е 10824 кв.м за ЦЕЛИЯ квартал, тоест общообектов ред, който ставаше
    # свой пакет.  Човекът го пише по участъци.
    #
    # Затова тук настилката получава ПО ЕДИН ПАКЕТ НА УЧАСТЪК ОТ ТРАСЕТО, в
    # същия ред: тогава вълните съвпадат едно към едно и кл. N възстановява
    # своята настилка, щом засипе своя изкоп.
    редове_настилка = кофи.pop(_RESTORATION_CHAIN, [])

    packages: list[dict] = []
    for верига, всички in sorted(кофи.items()):
        мрежа = _CHAIN_NETWORK[верига]

        # СЪОРЪЖЕНИЯТА СА ОТДЕЛНА РАБОТА, ОТ ОТДЕЛЕН ЕКИП (19.08.2026).
        #
        # Шахтите — улични оттоци, преливна, монолитни РШ — не ги прави
        # бригадата на тръбите.  Идва отделна група, която върши само това, а
        # работата ѝ ВЪРВИ УСПОРЕДНО с трасето.  Затова я няма и в еталонния
        # график като отделен ред: тя не движи срока.
        #
        # Дотук те попадаха в стъпката за полагане, на фронта на тръбната
        # бригада, и я държаха заета.  Измерено на този търг: ЕДНА преливна
        # шахта, разцепена на осемте етапа, изяждаше 8 × 17 = 136 бригадо-дни
        # от екипа, който полага тръбите — за позиция, която дори няма норма.
        #
        # И не се разцепва: шахтата е БРОЙ, не метри.  Една осма от шахта не е
        # нищо на обекта, а само начин подът от един ден да се плати осем пъти.
        точкови = [r for r in всички
                   if _клас(r) in _ТОЧКОВИ and _самостоятелно_съоръжение(r)]
        линейни = [r for r in всички if r not in точкови]

        # ПО ЕДИН ПАКЕТ НА БРОЙ, не на позиция.
        #
        # Изпълнителят (19.08.2026): „едни правят кофража, други армировката,
        # трети леят бетона.  Когато свършат с кофража на първата, отиват към
        # втората, а на първата започва армировката — има застъпване."
        #
        # Тоест същият конвейер като по трасето, но между СЪОРЪЖЕНИЯ.  За да
        # може кофражната бригада да мине напред, всяка шахта трябва да е свой
        # пакет: заетостта е (мрежа, операция, бригада), затова десет шахти в
        # ЕДИН пакет биха се изпълнявали като една дълга редица.
        for н, row in enumerate(точкови, 1):
            # НЕ се казва `брой` — така се казва броят ЕТАПИ на трасето по-долу
            # и презаписването му остави мрежата с един етап вместо осем.
            екземпляри = max(1, int(round(float(row.quantity))))
            екземпляри = min(екземпляри, _МАКС_СЪОРЪЖЕНИЯ)
            дялове = split_exactly(float(row.quantity), екземпляри)
            описание = str(getattr(row, "description", "") or "").strip()
            for к, дял in enumerate(дялове, 1):
                packages.append({
                    "id": f"С{мрежа}{н}_{к}" if екземпляри > 1 else f"С{мрежа}{н}",
                    "name": (f"{описание} №{к}" if екземпляри > 1
                             else описание or f"Съоръжение {н}"),
                    "network": мрежа,
                    "chain": "structure",
                    "items": [{"source_ref": str(row.ref), "quantity": дял}],
                })

        редове = линейни
        if not редове:
            continue

        # ЕТАПЪТ Е ОТСЕЧКА ОТ ЕДНА ТРЪБА, не осмина от цялата мрежа.
        #
        # Дотук всеки етап получаваше по малко от ВСЕКИ ред на КСС, тоест по
        # парче от всеки диаметър.  Следствието се мери: стъпката за полагане
        # на един етап се разбиваше на по една задача за диаметър и всяка
        # книжно заемаше цялата бригада.  Бетоновозът излизаше на 210 задачи
        # при 73 в еталона, строителният работник на 265 при 77 — а той е
        # най-дефицитният ресурс и държеше половината закъснения.
        #
        # Реалният участък има ЕДИН диаметър: кл.32 е 80 м DN300, не троха от
        # седем диаметъра.  Затова етапите се правят ВЪТРЕ в група по диаметър,
        # а броят им се дели между групите по дела им от работата.
        по_диаметър: dict[Any, list[Any]] = {}
        for row in редове:
            dn, _ = _диаметър(row)
            по_диаметър.setdefault(dn, []).append(row)

        тегла = {к: sum(float(r.quantity) for r in гр)
                 for к, гр in по_диаметър.items()}
        общо_тегло = sum(тегла.values()) or 1.0
        дялове = {к: max(1, round(брой * т / общо_тегло))
                  for к, т in тегла.items()}

        for dn, група in sorted(по_диаметър.items(),
                                key=lambda kv: (kv[0] is None, kv[0])):
            прочетени = прочетени_отсечки.get((мрежа, dn)) if dn else None
            if прочетени:
                взети, отрязани = _добави_отсечки(
                    packages, група, верига, мрежа, прочетени)
                бележка = (f"{мрежа} DN{dn}: {взети} участъка от чертежа "
                           f"вместо {дялове[dn]} етапа по подразбиране.")
                if отрязани:
                    бележка += (
                        f"  Чертежът показва още {отрязани} — проектът е по-голям "
                        "от процедурата и документите не казват кои клонове "
                        "са в нея; взети са най-дългите, докато се покрие "
                        "договорното количество.")
                от_чертежа.append(бележка)
            else:
                _добави_етапи(packages, група, верига, мрежа, дялове[dn],
                              етикет=f" DN{dn}" if dn else "")
        continue

        етапи: list[dict] = [
            {
                "id": f"{мрежа}{i + 1}",
                # ИМЕТО КАЗВА КАКВО Е.  Никакви „от РШ 1 до РШ 2": това е етап
                # на изпълнение, не трасе, и не бива да изглежда като прочетена
                # геометрия в MS Project.
                "name": f"Етап {i + 1} от {брой}",
                "network": мрежа,
                "chain": верига,
                "items": [],
            }
            for i in range(брой)
        ]
        for отместване, row in enumerate(редове):
            # БРОЯТ НЕ СЕ ДЕЛИ ПОД ЕДИНИЦА.
            #
            # Една водомерна шахта, разцепена на осем етапа, дава осем задачи по
            # един ден вместо една от пет — количеството е вярно, а работата е
            # измислена.  Затова редът се дели най-много на толкова части,
            # колкото брои: една шахта отива в ЕДИН етап.
            #
            # Отместването върти началния етап, за да не се струпат всичките
            # единични позиции в първия.
            части = брой
            ед = str(getattr(row, "unit", "") or "").strip().lower()
            if ед in _БРОЙНИ_МЕРКИ:
                части = max(1, min(брой, int(float(row.quantity))))
            дялове = split_exactly(float(row.quantity), части)
            for н, дял in enumerate(дялове):
                if дял <= 0:
                    continue
                pkg = етапи[(отместване + н) % len(етапи)]
                pkg["items"].append(
                    {"source_ref": str(row.ref), "quantity": дял})
        packages.extend(p for p in етапи if p["items"])

    трасови = [p for p in packages if p["chain"] in _ТРАСОВИ]
    if редове_настилка and трасови:
        тегла = [sum(float(i["quantity"]) for i in p["items"]) or 1.0
                 for p in трасови]
        общо_тегло = sum(тегла)
        настилки: list[dict] = []
        for и, (p, тегло) in enumerate(zip(трасови, тегла), 1):
            настилки.append({
                "id": f"П{и}",
                "name": f"Възстановяване на настилката — {p['name']}",
                "network": "П", "chain": _RESTORATION_CHAIN, "items": [],
            })
        for row in редове_настилка:
            дялове = [float(row.quantity) * т / общо_тегло for т in тегла]
            # Последният поема остатъка от закръглянето — Σ остава точно КСС.
            дялове = [round(д, 6) for д in дялове[:-1]]
            дялове.append(round(float(row.quantity) - sum(дялове), 6))
            for pkg, дял in zip(настилки, дялове):
                if дял > 0:
                    pkg["items"].append(
                        {"source_ref": str(row.ref), "quantity": дял})
        packages.extend(p for p in настилки if p["items"])

    бележки = [
        f"Участъците са направени от кода: {len(packages)} етапа на изпълнение "
        f"по {брой} на верига, количествата разделени точно по КСС."
    ]
    # Прочетеното от чертежа се КАЗВА: разликата между „Етап 3 от 8" и
    # „Кл.48 по ул.Балчо Нейков" е разликата между догадка и документ, и
    # човекът, който чете графика, трябва да знае кое от двете гледа.
    бележки.extend(от_чертежа)
    if редове_настилка and трасови:
        бележки.append(
            f"Настилките следват трасето: {len(трасови)} пакета, по един на "
            "участък, вместо отделни етапи накрая.")
    if продължителности:
        бележки.append(
            f"{len(продължителности)} реда обявяват договорна ПРОДЪЛЖИТЕЛНОСТ, "
            "не количество — не се разпределят по участъци.")
    if неразпределими:
        бележки.append(
            f"{len(неразпределими)} реда не попадат в нито една верига по "
            f"описание и лист: {', '.join(неразпределими[:5])}"
            + (" …" if len(неразпределими) > 5 else ""))
    for бележка in бележки:
        logger.info("%s", бележка)

    return {"packages": packages, "unroutable": неразпределими,
            "durations": продължителности, "notes": бележки}
