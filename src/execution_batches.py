def _sheet_of(ref: str) -> str:
    parts = str(ref).split("!")
    return parts[1] if len(parts) >= 3 else ""


def _document_of(ref: str) -> str:
    parts = str(ref).split("!")
    return parts[0] if parts else ""


def _network_of(ref: str) -> str:
    """Коя мрежа е редът — по листа, а ако той мълчи, по ИМЕТО НА ФАЙЛА.

    Мрежата не винаги е в името на листа.  Проба 24.08.2026, търг „Община
    Казанлък": файлът се казва „КСС ВОДОПРОВОД Енина - първи етап.xlsx", а
    листът вътре — просто „КСС първи етап".  Без този прочит 1311 от 1647
    реда с количество оставаха без верига и генерацията спираше, преди да
    излезе график.

    Първо листът, защото при КСС на няколко части той е по-точният: един файл
    може да носи и водопровод, и канализация на отделни листове.
    """
    return _network_in(_sheet_of(ref), _document_of(ref))


def _network_of_row(row: Any) -> str:
    """Мрежата на реда — лист, после файл, после САМОТО ОПИСАНИЕ.

    Три проби, три различни търга, един и същ корен: мрежата се търсеше в
    КОНТЕЙНЕРА, а редът сам си я казва.

        Илиянци   спецификация без раздели → лист „таблица 1", мълчи
        Казанлък  лист „КСС първи етап", а файлът казва „ВОДОПРОВОД"
        Харманли  един ред „Главни ВОДОПРОВОДНИ клонове DN300 CI" — нито
                  листът, нито файлът го казват, а той сам го пише

    Описанието е ПОСЛЕДНО, защото е най-шумното: ред „възстановяване на
    настилка над водопровода" е пътна работа, не водопровод.  Но когато
    контейнерът мълчи, то е единственото, което остава — и е по-добро от
    „никаква верига", което спира генерацията изцяло.
    """
    ref = str(getattr(row, "ref", "") or "")
    по_контейнер = _network_of(ref)
    if по_контейнер:
        return по_контейнер
    return _network_in(str(getattr(row, "description", "") or ""))


def _network_in(*текстове: str) -> str:
    """Първата мрежа, спомената в подадените текстове, по реда им."""
    for текст in текстове:
        low = текст.lower()
        for needle, network in _SHEET_NETWORK:
            if needle in low:
                return network
    return ""


