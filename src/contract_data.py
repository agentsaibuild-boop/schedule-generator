"""Договорните срокове се ЧЕТАТ от документите на процедурата, не се приемат.

ЗАЩО.  Изпълнителят, 31.08.2026: „При FIDIC е по-специфично, за всеки е
различно и трябва внимателно да се прочете тръжната документация, предоставена
от инвеститора."

Прав е, и разликата се вижда веднага между две процедури от корпуса:

    Свиленград (ВиК Хасково)   FIDIC — има приложение „Договорни данни" с
                               таблица Под-Клауза → стойност
    Илиянци (Столична община)  национален договор — такава таблица НЯМА

Затова тук няма зашити стойности.  Има четене: каквото документът казва, се
вади; каквото не казва, остава празно и се вижда, че е празно.

КОЕ МЕНИ ГРАФИКА.  От всичко в приложението графикът се влияе пряко от четири
неща, и те се вадят поименно:

    работна седмица   „8-17 понеделник-петък" (Под-Клауза 6.5) значи ПЕТДНЕВЕН
                      календар.  Ние изнасяме 7/7 по подразбиране — при 5/5
                      същата работа заема 1.4 пъти повече календарни дни.  Това
                      е капанът, който веднъж вече ни подведе с числото 558.
    време за завършване   Под-Клауза 1.1.86 — общият договорен срок
    срок за дефекти   Под-Клауза 1.1.27 — не удължава строителството, но е
                      част от договорния хоризонт
    срокове по клаузи  всяко „N дни" със своята под-клауза

Празната стойност е ЧЕСТНИЯТ отговор: в реалното приложение „Време за
завършване" стои като „…. календарни дни", защото се попълва от офертата.
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

#: По това се познава приложението с договорните данни на FIDIC.
_ЗАГЛАВИЕ_НА_ПРИЛОЖЕНИЕТО = re.compile(r"под\s*-?\s*клауза", re.IGNORECASE)

#: „8-17 понеделник-петък", „08:00-17:00 пн-пт", „понеделник до петък"
_ПЕТДНЕВНА = re.compile(
    r"понеделник\s*(?:-|–|до|÷)\s*петък|пн\s*(?:-|–|до)\s*пт", re.IGNORECASE)
_СЕДЕМДНЕВНА = re.compile(
    r"седем\s*дни|7\s*дни\s*в\s*седмицата|понеделник\s*(?:-|–|до)\s*неделя",
    re.IGNORECASE)

#: „365 дни", „56 (петдесет и шест) дни", „30 календарни дни"
_ДНИ = re.compile(
    r"(\d{1,4})\s*(?:\([^)]{0,40}\))?\s*(календарни|работни)?\s*дни",
    re.IGNORECASE)
_МЕСЕЦИ = re.compile(r"(\d{1,3})\s*(?:\([^)]{0,30}\))?\s*месец", re.IGNORECASE)

#: Кои под-клаузи носят кое.  Ключът е НАЧАЛОТО на номера, защото документите
#: пишат ту „1.1.86", ту „1.1.86.".
_РОЛИ = {
    "1.1.27": "срок_за_дефекти",
    "1.1.86": "време_за_завършване",
    "6.5": "работно_време",
    "8.3": "програма",
    "8.8": "неустойка_за_забава",
    "1.9": "срок_за_грешки_в_изискванията",
    "4.7.2": "срок_за_грешки_в_реперите",
}


def _текст_на_docx(път: Path) -> tuple[str, list[list[list[str]]]]:
    """(целият текст, таблиците като списък от редове от клетки)."""
    try:
        import docx
    except ImportError:                              # pragma: no cover
        logger.warning("python-docx липсва — договорните данни се пропускат.")
        return "", []
    try:
        d = docx.Document(str(път))
    except Exception as exc:                         # noqa: BLE001
        logger.warning("Договорният документ %s не се отваря: %s", път, exc)
        return "", []

    текст = "\n".join(p.text for p in d.paragraphs)
    таблици = []
    for tb in d.tables:
        редове = []
        for r in tb.rows:
            клетки = [c.text.strip().replace("\n", " ") for c in r.cells]
            # Слетите клетки се повтарят — съседните еднакви се свиват до една.
            изчистени: list[str] = []
            for к in клетки:
                if not изчистени or к != изчистени[-1]:
                    изчистени.append(к)
            редове.append(изчистени)
            текст += "\n" + " | ".join(изчистени)
        таблици.append(редове)
    return текст, таблици


def _дни_от(стойност: str) -> int | None:
    m = _ДНИ.search(стойност or "")
    if m:
        return int(m.group(1))
    m = _МЕСЕЦИ.search(стойност or "")
    if m:
        # Месец в договорен смисъл е календарен; 30 дни е обичайното
        # приближение и се ОБЯВЯВА като приближение, а не се крие.
        return int(m.group(1)) * 30
    return None


def read_appendix(път: Path) -> list[dict]:
    """Редовете на приложението „Договорни данни", ако документът го носи."""
    _, таблици = _текст_на_docx(път)
    записи: list[dict] = []
    for редове in таблици:
        if not редове:
            continue
        шапка = " ".join(редове[0])
        if not _ЗАГЛАВИЕ_НА_ПРИЛОЖЕНИЕТО.search(шапка):
            continue
        for ред in редове[1:]:
            if len(ред) < 2:
                continue
            клауза = ред[0].strip().rstrip(".")
            описание = ред[1].strip()
            стойност = ред[2].strip() if len(ред) > 2 else ""
            if not клауза and not описание:
                continue
            записи.append({"клауза": клауза, "описание": описание,
                           "стойност": стойност,
                           "дни": _дни_от(стойност),
                           "роля": _РОЛИ.get(клауза, "")})
    return записи


def read_contract(base_path: str | Path) -> dict:
    """Договорните данни на ТАЗИ процедура — от нейните собствени документи.

    Гледа всеки `.docx` в папката (и в подпапките): приложението с договорните
    данни може да е в „Специфични условия", в „Проект на договор" или в
    отделен файл — зависи от възложителя.

    Returns:
        {приложение, работна_седмица, време_за_завършване_дни,
         срок_за_дефекти_дни, срокове, източници, бележки}
    """
    корен = Path(base_path)
    if not корен.exists():
        return {"приложение": [], "бележки": [f"няма такава папка: {корен}"]}

    записи: list[dict] = []
    източници: list[str] = []
    цял_текст = ""
    for път in sorted(корен.rglob("*.docx")):
        if път.name.startswith("~$"):
            continue
        текст, _ = _текст_на_docx(път)
        цял_текст += "\n" + текст
        редове = read_appendix(път)
        if редове:
            записи.extend(редове)
            източници.append(път.name)

    по_роля = {з["роля"]: з for з in записи if з["роля"]}

    # РАБОТНАТА СЕДМИЦА — най-важното, защото мени всички календарни дни.
    работно = (по_роля.get("работно_време") or {}).get("стойност", "")
    седмица = ""
    if _ПЕТДНЕВНА.search(работно) or _ПЕТДНЕВНА.search(цял_текст):
        седмица = "5/5"
    if _СЕДЕМДНЕВНА.search(работно) or _СЕДЕМДНЕВНА.search(цял_текст):
        седмица = "7/7"

    бележки: list[str] = []
    if записи:
        бележки.append(
            f"Договорни данни: {len(записи)} реда от "
            f"{', '.join(източници)} — стойностите са на ТАЗИ процедура.")
    else:
        бележки.append("Приложение с договорни данни не е намерено — "
                       "процедурата не е по FIDIC или документът липсва.")
    if седмица:
        бележки.append(
            f"Работна седмица по договора: {седмица}"
            + (f" („{работно}“, Под-Клауза 6.5)" if работно else "")
            + ".  Изнасяме 7/7 по подразбиране — при 5/5 същата работа заема "
              "около 1.4 пъти повече КАЛЕНДАРНИ дни.")

    завършване = (по_роля.get("време_за_завършване") or {})
    if завършване and завършване.get("дни") is None and завършване.get("стойност"):
        бележки.append(
            f"Време за завършване (Под-Клауза 1.1.86) стои непопълнено в "
            f"приложението: „{завършване['стойност'][:60]}“ — числото идва от "
            f"обявлението или от офертата, не оттук.")

    срокове = [{"клауза": з["клауза"], "описание": з["описание"][:80],
                "дни": з["дни"]} for з in записи if з.get("дни")]
    return {
        "приложение": записи,
        "източници": източници,
        "работна_седмица": седмица,
        "време_за_завършване_дни": завършване.get("дни"),
        "срок_за_дефекти_дни": (по_роля.get("срок_за_дефекти") or {}).get("дни"),
        "срокове": срокове,
        "бележки": бележки,
    }


def describe(данни: dict) -> list[str]:
    редове = list(данни.get("бележки") or [])
    for с in (данни.get("срокове") or [])[:12]:
        редове.append(f"  Под-Клауза {с['клауза']}: {с['дни']} дни — "
                      f"{с['описание']}")
    return редове
