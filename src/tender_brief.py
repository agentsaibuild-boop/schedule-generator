# -*- coding: utf-8 -*-
"""Каквото пише в търга — извадено и ПОКАЗАНО, преди да се пита човекът.

ЗАЩО.  Изпълнителят, 31.08.2026: „След като прочетеш всички документи на търга,
питай човека зададените въпроси — тук предоставяш информацията, която си взел
от документацията: колко дни ще се работи, с колко екипа и другите въпроси."

Дотук въпросникът питаше НА СЛЯПО:

    „Колко календарни дни дава договорът за СТРОИТЕЛСТВОТО?
     Пише го в обявлението, не в количествата."

Тоест караме човека да отвори документ, който ние вече сме прочели.  Той може
да сгреши, може да не го намери, а ние мълчим за онова, което знаем.  По-лошо:
при Карлово документацията казва не само таван (500 дни), но и ПОД (365) и че
излизане извън тях ДИСКВАЛИФИЦИРА — това е информация, която човекът трябва да
види, преди да отговори, а не след като е сгрешил.

Затова тук се събира всичко прочетено и се подава на въпроса.  Отговорът си
остава на човека — ние само спираме да го питаме неща, които вече знаем.

КАКВО СЕ ВАДИ:

    срокове по фази   с таван, под и предупреждение за дисквалификация
    количества        метри по мрежа, от индекса на КСС
    договорни данни   работна седмица, срок за дефекти (`contract_data`)
    сценарии          при колко екипа какво излиза (`deadline_pace`)
"""

from __future__ import annotations

import json
import logging
import re
from pathlib import Path
from typing import Any, Iterable

logger = logging.getLogger(__name__)

#: Фазите, които търсим в текста, и по какви думи се познават.
_ФАЗИ: tuple[tuple[str, str, tuple[str, ...]], ...] = (
    ("pip", "прединвестиционни проучвания (ПИП)",
     ("пип", "прединвестиционни проучвания")),
    ("pup", "ПУП / парцеларен план", ("пуп", "парцеларен план")),
    ("design", "проектиране",
     ("технически проект", "изготвяне на проект", "проектиране",
      "работен проект", "инвестиционен проект")),
    ("construction", "строителство",
     ("строително-монтажни", "строителството", "смр", "строителство")),
    ("supervision", "авторски надзор", ("авторски надзор",)),
)

#: „до 500 (петстотин) календарни дни", „500 календарни дни", „19 месеца"
_ДО = re.compile(
    r"(?:до|не\s+повече\s+от|максимум)\s+(\d{1,4})\s*(?:\([^)]{0,45}\))?\s*"
    r"(календарни|работни)?\s*дни", re.IGNORECASE)
_ПОД = re.compile(
    r"не\s+по-?малко\s+от\s+(\d{1,4})\s*(?:\([^)]{0,45}\))?\s*"
    r"(календарни|работни)?\s*дни", re.IGNORECASE)
_ПРОСТО = re.compile(
    r"(?:продължителност[^\d]{0,20}|срок[^\d]{0,30})(\d{1,4})\s*"
    r"(?:\([^)]{0,45}\))?\s*(календарни|работни)?\s*дни", re.IGNORECASE)
_ДИСКВАЛИФИКАЦИЯ = re.compile(
    r"ще\s+бъде\s+отстранен|отстранява\s+се|не\s+се\s+допуска", re.IGNORECASE)

#: Изречението трябва да Е ЗА СРОКА НА ФАЗАТА, не просто да я споменава.
#: Първата проба вадеше „30 дни" за авторския надзор от съседно изречение и
#: даваше на Свиленград 30/30/30, при положение че истинският срок е 19 месеца
#: в обявлението.  Затова се иска дума за срок ПРЕДИ името на фазата.
_ДУМА_ЗА_СРОК = re.compile(
    r"срок(?:ът|а|овете)?\s+(?:за|на)|продължителност|време\s+за\s+завършване",
    re.IGNORECASE)

#: Изречения, в които число има, но то НЕ е срокът на фазата.
_НЕ_Е_СРОКЪТ = (
    "не се включва", "разглеждане", "одобряване от", "приемането му",
    "почистване", "уведоми", "застраховк", "гаранц", "плащан", "оферт",
    "обжалван", "съобщаване на дефекти", "съгласуване от",
)

#: „през целия срок на строително-монтажните работи" — надзорът няма свой брой
#: дни, а следва друга фаза.  Това е ОТГОВОР, не липса.
#: Колко знака се допускат между думата за срок и името на фазата.  Мерено по
#: реалните изречения: „Срок за изпълнение на строително-монтажните работи" е
#: 22 знака, „ЕТАП „ПРОЕКТИРАНЕ" Продължителност" — 20.
_БЛИЗОСТ = 60

_ПРЕЗ_ЦЕЛИЯ = re.compile(
    r"през\s+целия\s+срок|за\s+целия\s+период|през\s+целия\s+период",
    re.IGNORECASE)


def _текстовете(base_path: str | Path) -> str:
    """Целият конвертиран текст на процедурата, в един низ."""
    converted = Path(base_path) / "converted"
    if not converted.exists():
        return ""
    парчета = []
    for f in sorted(converted.glob("*.json")):
        if f.name == "_manifest.json":
            continue
        try:
            d = json.loads(f.read_text(encoding="utf-8"))
        except Exception:                            # noqa: BLE001
            continue
        парчета.append(d.get("full_text") or json.dumps(d, ensure_ascii=False))
    return " ".join(" ".join(п.split()) for п in парчета)


def read_terms(base_path: str | Path) -> list[dict]:
    """Обявените срокове по фази — таван, под и има ли дисквалификация.

    Търси се в ИЗРЕЧЕНИЕТО: „Срок за изпълнение на строително-монтажните работи
    е до 500 (петстотин) календарни дни, но не по-малко от 365".  Едно
    изречение носи и фазата, и двете граници — затова се реже по точка, а не по
    прозорец от знаци.
    """
    текст = _текстовете(base_path)
    if not текст:
        return []

    намерени: dict[str, dict] = {}
    for изречение in re.split(r"(?<=[.;])\s+", текст):
        ниско = изречение.lower()
        има_число = "дни" in ниско or "месец" in ниско
        if not има_число and not _ПРЕЗ_ЦЕЛИЯ.search(изречение):
            continue
        if any(и in ниско for и in _НЕ_Е_СРОКЪТ):
            continue
        for ключ, етикет, думи in _ФАЗИ:
            позиции = [ниско.find(д) for д in думи if д in ниско]
            if not позиции:
                continue
            # Думата за срок трябва да е БЛИЗО до името на фазата — но може да
            # е и след него: „ЕТАП ПРОЕКТИРАНЕ Продължителност – 120 дни".
            # Първата проба искаше „преди" и изгуби точно този запис на
            # Илиянци; втората не искаше нищо и даде на Свиленград 30/30/30.
            срокова = min(
                (m for m in _ДУМА_ЗА_СРОК.finditer(изречение)),
                key=lambda m: min(abs(m.start() - п) for п in позиции),
                default=None)
            if срокова is None:
                continue
            ако_далеч = min(abs(срокова.start() - п) for п in позиции)
            if ако_далеч > _БЛИЗОСТ:
                continue
            if _ПРЕЗ_ЦЕЛИЯ.search(изречение):
                намерени.setdefault(ключ, {
                    "фаза": ключ, "етикет": етикет, "дни": None,
                    "минимум": None, "дисквалификация": False,
                    "следва": "целия срок на строителството",
                    "цитат": " ".join(изречение.split())[:200]})
                continue
            таван = _ДО.search(изречение)
            под = _ПОД.search(изречение)
            просто = _ПРОСТО.search(изречение)
            дни = (int(таван.group(1)) if таван
                   else int(просто.group(1)) if просто else None)
            if дни is None:
                continue
            запис = намерени.setdefault(ключ, {
                "фаза": ключ, "етикет": етикет, "дни": дни,
                "минимум": None, "дисквалификация": False, "цитат": ""})
            if запис.get("следва"):
                continue                    # фазата следва друга, не свой брой
            # По-голямото число печели: документът повтаря срока на няколко
            # места, а таванът е този, който важи.
            if дни >= (запис["дни"] or 0):
                запис["дни"] = дни
                запис["цитат"] = " ".join(изречение.split())[:200]
            if под:
                запис["минимум"] = int(под.group(1))
            if _ДИСКВАЛИФИКАЦИЯ.search(изречение):
                запис["дисквалификация"] = True

    # Дисквалификацията често е в ОТДЕЛНО изречение („ВАЖНО! В случай че
    # участник предложи срок … ще бъде отстранен") — важи за всички срокове.
    if _ДИСКВАЛИФИКАЦИЯ.search(текст) and "предложи срок" in текст.lower():
        for запис in намерени.values():
            запис["дисквалификация"] = True

    return [намерени[к] for к, *_ in _ФАЗИ if к in намерени]


def _метри_по_мрежа(boq_index: Iterable[Any] | None) -> dict[str, float]:
    метри: dict[str, float] = {}
    for ред in boq_index or ():
        мярка = str(getattr(ред, "unit", "") or "").strip().lower()
        if мярка not in ("m", "м", "м'", "м.", "лм", "л.м"):
            continue
        описание = str(getattr(ред, "description", "") or "").lower()
        мрежа = ("канализация" if "канализ" in описание
                 else "водопровод" if "водопров" in описание else "друго")
        try:
            метри[мрежа] = метри.get(мрежа, 0.0) + float(
                getattr(ред, "quantity", 0) or 0)
        except (TypeError, ValueError):
            continue
    return метри


def brief(base_path: str | Path, boq_index: Iterable[Any] | None = None) -> dict:
    """Всичко прочетено от търга, готово да се покаже преди въпросите."""
    from src.contract_data import read_contract

    срокове = read_terms(base_path)
    договор = read_contract(base_path)
    метри = _метри_по_мрежа(boq_index)
    return {
        "срокове": срокове,
        "метри": метри,
        "работна_седмица": договор.get("работна_седмица", ""),
        "срок_за_дефекти_дни": договор.get("срок_за_дефекти_дни"),
        "договорни_данни": bool(договор.get("приложение")),
    }


def describe(данни: dict, *, за_въпрос: str = "") -> list[str]:
    """Брифингът с думи.  `за_въпрос` подрежда какво е най-важно горе."""
    редове: list[str] = []
    срокове = данни.get("срокове") or []
    if срокове:
        редове.append("**Прочетох от документацията:**")
        for с in срокове:
            if с.get("следва"):
                редове.append(f"  • {с['етикет']}: **{с['следва']}**")
                continue
            ред = f"  • {с['етикет']}: **{с['дни']} дни**"
            if с.get("минимум"):
                ред += f" (не по-малко от {с['минимум']})"
            if с.get("дисквалификация"):
                ред += " — излизане извън тези граници ДИСКВАЛИФИЦИРА"
            редове.append(ред)
    метри = данни.get("метри") or {}
    if метри:
        редове.append("  • количества: " + ", ".join(
            f"{м} {д:,.0f} м".replace(",", " ") for м, д in sorted(метри.items())))
    if данни.get("работна_седмица"):
        редове.append(f"  • работна седмица по договора: "
                      f"**{данни['работна_седмица']}**")
    if данни.get("срок_за_дефекти_дни"):
        редове.append(f"  • срок за съобщаване на дефекти: "
                      f"{данни['срок_за_дефекти_дни']} дни")
    if not срокове:
        редове.insert(0, "**От документацията НЕ извадих срокове** — провери "
                         "ги в обявлението, преди да отговориш.")
    return редове


def crew_scenarios(данни: dict, *, days: int = 0) -> list[str]:
    """При колко екипа какво излиза — числата, с които се избира отговор."""
    from src.deadline_pace import scenarios

    метри = данни.get("метри") or {}
    дължина = float(метри.get("водопровод") or 0) + float(
        метри.get("канализация") or 0) + float(метри.get("друго") or 0)
    if not days:
        срокове = {с["фаза"]: с["дни"] for с in (данни.get("срокове") or [])}
        days = int(срокове.get("construction") or 0)
    if дължина <= 0 or days <= 0:
        return []

    знак = {"FEASIBLE": "да", "REQUIRES_UPLIFT": "на ръба",
            "NOT_SUPPORTED_BY_DATA": "не", "OVERSTAFFED": "в повече"}
    редове = ["**При колко екипа какво излиза** "
              f"({дължина:,.0f} м за {days} дни):".replace(",", " ")]
    # Спира се на ПЪРВИЯ „в повече" — оттам нататък всеки следващ екип само
    # надува работата (мерено 26.08.2026) и редовете стават шум.
    в_повече = 0
    for р in scenarios(дължина, days, до=10):
        дума = "екип" if р["екипи"] == 1 else "екипа"
        редове.append(f"  {р['екипи']} {дума} → {р['темпо']:g} м/ден "
                      f"({знак.get(р['присъда'], '?')})")
        if р["присъда"] == "OVERSTAFFED":
            в_повече += 1
            if в_повече >= 1:
                break
    return редове
