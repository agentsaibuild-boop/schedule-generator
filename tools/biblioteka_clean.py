# -*- coding: utf-8 -*-
"""Изчиства библиотеката от следи на ЧУЖДИ обекти — преди да влезе в оферта.

ЗАЩО.  `biblioteka.py` вади 1491 технологични описания от изпълнените работни
програми на изпълнителя — около 1494 страници собствен текст, който може да се
преизползва.  Но той е писан ЗА КОНКРЕТНИ ОБЕКТИ и ги назовава:

    „…за обществената поръчка с предмет: „Инженеринг (проектиране, авторски
     надзор и строителство) за реконструкция на водопровод Ø100 етернит от
     ПС „Образцов Чифлик" до НКР „Образцов Чифлик""

Подаден така, този абзац казва на комисията, че предложението е за друг обект.
Това е единственият дефект в целия ни списък, който може да провали процедура —
затова тук нищо не се „поправя тихо".

КАК.  Всяка находка се ОБЯВЯВА и се заменя с явно обозначение (`{ОБЕКТ}`,
`{НАСЕЛЕНО_МЯСТО}`, …), което човек вижда и попълва.  Описание със следи НЕ се
маркира като готово: то излиза в отделен файл със статус `за_преглед`.

ЧИСТО НЕ ЗНАЧИ ГОТОВО.  Липсата на находка значи само, че не сме намерили
следа с тези правила.  Затова отчетът дава и КОЛКО е чисто, и по кои правила е
съдено — за да може човек да добави правило, вместо да вярва на числото.

    python tools/biblioteka_clean.py --vhod biblioteka.json --out cisto.json
    python tools/biblioteka_clean.py --vhod biblioteka.json --pokazhi 10
"""

from __future__ import annotations

import argparse
import collections
import json
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

_ГЛАВНА = "А-ЯЁ"
_МАЛКА = "а-яё"
_БУКВА = _ГЛАВНА + _МАЛКА

#: Правилата.  Всяко е (име, регулярен израз, с какво се заменя).
#:
#: Редът има значение: по-конкретните вървят първи, за да не изяде общото
#: правило част от находката на конкретното (`ПС „Образцов Чифлик"` трябва да
#: се хване като съоръжение, а не като кавички).
ПРАВИЛА: tuple[tuple[str, re.Pattern, str], ...] = (
    ("населено място",
     re.compile(rf"\b(?:гр|с|общ|обл)\.\s*[{_ГЛАВНА}][{_БУКВА}]+"),
     "{НАСЕЛЕНО_МЯСТО}"),
    ("община",
     re.compile(rf"\bобщина\s+[{_ГЛАВНА}][{_БУКВА}]+"),
     "{ОБЩИНА}"),
    ("възложител",
     re.compile(rf"\b(?:ВиК|В и К)\s*(?:ООД|ЕООД|АД)?\s*[–—-]?\s*"
                rf"[{_ГЛАВНА}][{_БУКВА}]+"),
     "{ВЪЗЛОЖИТЕЛ}"),
    ("съоръжение",
     re.compile(rf"\b(?:ПСОВ|ПСПВ|ПС|НКР|НР|ВС)\s*[„\"'']?\s*"
                rf"[{_ГЛАВНА}][{_БУКВА}]+(?:\s+[{_ГЛАВНА}][{_БУКВА}]+)?"
                rf"\s*[\"'']?"),
     "{СЪОРЪЖЕНИЕ}"),
    ("улица",
     re.compile(rf"\b(?:ул|бул|кв|ж\.к|м-ст|местност)\.?\s*[„\"'']?\s*"
                rf"[{_ГЛАВНА}][{_БУКВА}]+(?:\s+[{_ГЛАВНА}][{_БУКВА}]+)?"
                rf"\s*[\"'']?"),
     "{УЛИЦА}"),
    ("име в кавички",
     re.compile(rf"„[^“\"]{{0,118}}[{_ГЛАВНА}][^“\"]{{0,118}}“"),
     "{ОБЕКТ}"),
    ("размер",
     re.compile(r"\b(?:Ø|DN|Ф)\s*\d{2,4}\b"),
     "{ДИАМЕТЪР}"),
    ("дължина",
     re.compile(r"\bL\s*=\s*[\d\s.,]+\s*(?:м|m|км|km)\b"),
     "{ДЪЛЖИНА}"),
    ("дата",
     re.compile(r"\b\d{1,2}\.\d{1,2}\.\d{4}\s*(?:г\.?)?"),
     "{ДАТА}"),
    ("номер на процедура",
     re.compile(r"\b\d{5,}\b"),
     "{НОМЕР}"),
)


#: В КАВИЧКИ СТОИ И ОБЩОТО, НЕ САМО ЧУЖДОТО.  Първата проба обяви 1485
#: „имена в кавички"; честотната таблица показа какви са те всъщност:
#:
#:     233× „Водоснабдяване“   107× „Геодезия“   75× „Контрол на качеството“
#:      56× „Конструктивна“     55× „Канализация“   30× „Технически проект“
#:
#: Това са ИМЕНА НА ПРОЕКТНИ ЧАСТИ и на документи — те се пишат в кавички във
#: всяко предложение и не издават нищо за обекта.  Обектните са другите:
#: „Х. Димитър“, „Колхида“, „Ж. Петков“, „Реконструкция и доизграждане на …“.
#:
#: Списъкът на частите не е измислен тук — сверен е с проектантската верига в
#: `config/tech_chains.json` (25 стъпки), за да не се разминат двете места.
ОБЩИ_В_КАВИЧКИ = frozenset(
    т.lower() for т in (
        # проектни части
        "Водоснабдяване", "Канализация", "Геодезия", "Конструктивна",
        "Пътна", "Пътна и ВОБД", "ВОБД и Пътна", "ВОБД", "ВОД", "Електро",
        "Електрическа", "Отводняване", "Технологична", "Архитектурна",
        "ОВК", "Логистика",
        "Хидрология", "Паркоустройство", "Паркоустройство и благоустройство",
        "ПБЗ", "ПБ", "ПУСО", "Сметна документация", "ВиК",
        "Пожарна безопасност", "Временна организация на движението",
        "Инженерно-геоложки и хидрогеоложки проучвания",
        "Инженерно-геоложки и хидрогеоложки доклад",
        "Експертна оценка на съществуваща растителност",
        # документи и роли
        "Технически проект", "Работен проект", "Идеен проект",
        "План за безопасност и здраве", "Технически спецификации",
        "Възложител", "Възложителя", "Изпълнител", "Изпълнителя",
        "Инженер", "Инженера", "Строител", "Строителят", "Консултант",
        # контролни дейности
        "Контрол на качеството", "Контрол по качеството",
    ))
#: НАРОЧНО НЕ Е ТУК: „Водоснабдяване и канализация“.  Изглежда като име на
#: проектна част, но в кавички почти винаги е ИМЕТО НА ВЪЗЛОЖИТЕЛЯ
#: („Водоснабдяване и канализация“ ООД – <град>).  По-добре да мине през
#: преглед, отколкото да остане в подаван текст.


def _обектно_ли_е(в_кавички: str) -> bool:
    """Дали кавичките държат ИМЕ НА ОБЕКТ, а не общо понятие."""
    ядро = в_кавички.strip("„“\"' ").strip()
    if not ядро:
        return False
    if ядро.lower() in ОБЩИ_В_КАВИЧКИ:
        return False
    # Заглавие на процедура — дълго и започва с това, което поръчката прави.
    # То е най-опасното: точно то назовава чуждия обект.
    return True


def почисти(текст: str) -> tuple[str, list[dict]]:
    """(текст с обозначения, находки).  Нищо не се маха мълчаливо."""
    находки: list[dict] = []
    изход = текст
    for име, израз, замяна in ПРАВИЛА:
        def запиши(m: re.Match) -> str:
            намереното = m.group(0).strip()
            if име == "име в кавички" and not _обектно_ли_е(намереното):
                return m.group(0)          # общо понятие — остава както си е
            находки.append({"вид": име, "текст": намереното})
            return замяна
        изход = израз.sub(запиши, изход)
    return изход, находки


def обработи(библиотека: dict) -> dict:
    записи = []
    по_вид: collections.Counter = collections.Counter()
    чисти = знаци_чисти = 0

    for о in библиотека.get("операции", []):
        текст = о.get("текст") or ""
        заглавие = о.get("операция") or ""
        чист_текст, находки_т = почисти(текст)
        чисто_заглавие, находки_з = почисти(заглавие)
        находки = находки_з + находки_т
        for н in находки:
            по_вид[н["вид"]] += 1

        статус = "чисто" if not находки else "за_преглед"
        чисти += статус == "чисто"
        знаци_чисти += len(текст) if статус == "чисто" else 0
        записи.append({
            **{k: v for k, v in о.items() if k != "текст"},
            "статус": статус,
            "операция_обозначена": чисто_заглавие,
            "текст_обозначен": чист_текст,
            "находки": находки[:40],
            "брой_находки": len(находки),
        })

    общо = len(записи)
    return {
        "правила": [име for име, *_ in ПРАВИЛА],
        "обобщение": {
            "операции": общо,
            "чисти": чисти,
            "за_преглед": общо - чисти,
            "дял_чисти": round(чисти / общо, 4) if общо else 0.0,
            "знаци_чисти": знаци_чисти,
            "страници_чисти": знаци_чисти // 1800,
            "находки_по_вид": dict(по_вид.most_common()),
        },
        "операции": записи,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vhod", required=True, help="biblioteka.json")
    parser.add_argument("--out", default="", help="къде да излезе резултатът")
    parser.add_argument("--pokazhi", type=int, default=0,
                        help="покажи N примера с находки")
    args = parser.parse_args()

    библиотека = json.loads(Path(args.vhod).read_text(encoding="utf-8"))
    резултат = обработи(библиотека)
    о = резултат["обобщение"]

    print(f"операции: {о['операции']}")
    print(f"  чисти по тези правила: {о['чисти']} "
          f"({о['дял_чисти']:.0%}, ≈{о['страници_чисти']} стандартни страници)")
    print(f"  за преглед:            {о['за_преглед']}")
    print("\nнаходки по вид:")
    for вид, брой in о["находки_по_вид"].items():
        print(f"  {брой:>6}× {вид}")

    if args.pokazhi:
        print("\nпримери:")
        показани = 0
        for з in резултат["операции"]:
            if з["статус"] == "чисто" or показани >= args.pokazhi:
                continue
            показани += 1
            print(f"\n  ── {з['операция'][:70]}")
            for н in з["находки"][:4]:
                print(f"     {н['вид']:<18} {н['текст'][:60]}")

    if args.out:
        Path(args.out).write_text(
            json.dumps(резултат, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"\n→ {args.out}")

    print("\nЧИСТО НЕ ЗНАЧИ ГОТОВО: липсата на находка значи само, че тези "
          "правила не са намерили следа.  Преди подаване текстът се чете от "
          "човек.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
