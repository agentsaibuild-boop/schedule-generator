"""Кои от изпълнените процедури могат да станат benchmark — опис преди строеж.

ЗАЩО.  Одиторът, 31.08.2026:

    „40 stochastic generations вече не са главният benchmark.  Щом при известни
     segments генерирането е 0 LLM calls / $0 / deterministic, много по-ценно е
     да изградите 22-project deterministic benchmark suite от историческия
     корпус: tender inputs -> нашият engine -> generated schedule ~ real
     submitted/executed schedule."

Съгласни сме.  Но суита не се строи върху предположение колко проекта имат
пълен комплект — затова първо ОПИС, после мерки, после суита.  За benchmark
трябват ДВЕ страни:

    ВХОД    количества (КСС или спецификация) + геометрия (ситуационни чертежи)
    ИЗХОД   изпълненият човешки график (.mpp / .xml)

Проект само с график става за изваждане на норми и топология — не за
сравнение, защото няма от какво да генерираме.  Проект само с вход не става за
нищо тук.  Този инструмент брои кои са кои, поименно.

    python tools/benchmark_inventory.py --koren "<корен на корпуса>"
    python tools/benchmark_inventory.py --grafici <папка с извадени .json>
    python tools/benchmark_inventory.py --koren ... --out opis.json
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

#: Какво търсим и по какво го познаваме.  Само по ИМЕ и разширение — отварянето
#: на всеки файл в корпуса струва часове и не е нужно за опис.
ВИДОВЕ: tuple[tuple[str, tuple[str, ...], tuple[str, ...]], ...] = (
    # (вид, разширения, думи в името; празни думи = всяко име става)
    ("график", (".mpp",), ()),
    ("график_xml", (".xml",), ("график", "graf", "линеен", "времеви")),
    ("ксс", (".xlsx", ".xls"), ("кс", "ксс", "количеств", "boq", "смет")),
    ("чертеж", (".pdf",), ("ситуац", "ситуация", "situation", "план")),
    ("спецификация", (".pdf", ".docx", ".doc"),
     ("спецификац", "техническа специф")),
    ("работна_програма", (".docx", ".doc"),
     ("работна програма", "предложение за изпълнение", "приложение 1",
      "приложение № 1")),
)

_ПРЕСКАЧАЙ = ("~$", ".tmp")

#: ТРИТЕ ПРИЗНАКА, по които човешки график става сравним с наш.  Не всеки от
#: 26-те ги има — точно затова се броят поотделно, вместо да се предполага:
#:
#:   клон    "КЛ. 25 - И от ОТ 27 А до ОТ 25"  -> има ли изобщо участъци
#:   възли   "от ОТ 27 А до ОТ 25"             -> знае ли се докъде стига
#:   метри   "L=588 м"                         -> може ли да се мери темпо
#:
#: Без първия сравнението „възстановени физически участъци" няма смисъл; без
#: третия не може да се сравни темпо.
ПРИЗНАЦИ = {
    "клон": re.compile(r"\bкл\.?\s*\d", re.IGNORECASE),
    "възли": re.compile(r"\bот\s+\S+\s+до\s+\S+", re.IGNORECASE),
    "метри": re.compile(r"L\s*=\s*[\d\s.,]+\s*(?:м|m)", re.IGNORECASE),
}


def _признаци_на(имена: list[str]) -> dict[str, int]:
    """Колко задачи носят всеки признак."""
    return {к: sum(1 for и in имена if изр.search(и))
            for к, изр in ПРИЗНАЦИ.items()}


def _вид_на(път: Path) -> list[str]:
    име = път.name.lower()
    if име.startswith(_ПРЕСКАЧАЙ):
        return []
    разш = път.suffix.lower()
    намерени = []
    for вид, разширения, думи in ВИДОВЕ:
        if разш not in разширения:
            continue
        if думи and not any(д in име for д in думи):
            continue
        намерени.append(вид)
    return намерени


def опиши(корен: Path, дълбочина: int = 3) -> list[dict]:
    """По една папка на обект — първото ниво под корена."""
    обекти: list[dict] = []
    for папка in sorted(p for p in корен.iterdir() if p.is_dir()):
        намерено: dict[str, list[str]] = {}
        for път in папка.rglob("*"):
            if not път.is_file():
                continue
            if len(път.relative_to(папка).parts) > дълбочина:
                continue
            for вид in _вид_на(път):
                намерено.setdefault(вид, []).append(път.name)

        има_изход = bool(намерено.get("график") or намерено.get("график_xml"))
        има_количества = bool(намерено.get("ксс")
                              or намерено.get("спецификация"))
        има_геометрия = bool(намерено.get("чертеж"))

        if има_изход and има_количества and има_геометрия:
            присъда = "готов"
        elif има_изход and има_количества:
            присъда = "без геометрия"
        elif има_изход:
            присъда = "само график"
        elif има_количества:
            присъда = "само вход"
        else:
            присъда = "празен"

        обекти.append({
            "обект": папка.name,
            "присъда": присъда,
            "график": (len(намерено.get("график", []))
                       + len(намерено.get("график_xml", []))),
            "ксс": len(намерено.get("ксс", [])),
            "чертеж": len(намерено.get("чертеж", [])),
            "спецификация": len(намерено.get("спецификация", [])),
            "работна_програма": len(намерено.get("работна_програма", [])),
            "файлове": {к: v[:6] for к, v in намерено.items()},
        })
    return обекти


def опиши_графици(папка: Path) -> list[dict]:
    """Само изходната страна — от вече извадените в JSON графици."""
    редове = []
    for f in sorted(папка.glob("*.json")):
        try:
            данни = json.loads(f.read_text(encoding="utf-8"))
        except Exception as exc:                    # noqa: BLE001
            редове.append({"файл": f.name, "грешка": str(exc)[:60]})
            continue
        # `read_mpp.py` пише {файл, проект, старт, край, брой, ресурси, задачи};
        # приема се и гол списък, за да не зависи описът от една версия.
        задачи = (данни if isinstance(данни, list)
                  else (данни.get("задачи") or данни.get("tasks") or []))
        # Продължителността идва в МИНУТИ (`min`), както я дава MS Project;
        # листата се познават по `sum: false`.
        листа = [t for t in задачи if not t.get("sum")]
        дни = [t for t in листа
               if isinstance(t.get("min") or t.get("duration"), (int, float))
               and (t.get("min") or t.get("duration"))]
        имена = [str(t.get("name") or t.get("име") or "") for t in задачи]
        признаци = _признаци_на(имена)
        име = re.sub(r"^\d+_", "", f.stem)
        редове.append({
            "файл": име[:60], "задачи": len(задачи), "листа": len(листа),
            "с_продължителност": len(дни), **признаци,
            "сравним": ("участък+темпо" if признаци["метри"]
                        else "участък" if признаци["клон"]
                        else "само структура"),
            "проект": (str(данни.get("проект") or "")[:60]
                       if isinstance(данни, dict) else ""),
        })
    return редове


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--koren", default="", help="корен на корпуса")
    parser.add_argument("--grafici", default="",
                        help="папка с извадени графици (.json)")
    parser.add_argument("--out", default="")
    args = parser.parse_args()

    резултат: dict = {}

    if args.grafici:
        редове = опиши_графици(Path(args.grafici))
        резултат["графици"] = редове
        print(f"ИЗХОДНА СТРАНА — {len(редове)} извадени графика\n")
        print(f"{'график':<46}{'задачи':>7}{'листа':>7}{'клон':>6}"
              f"{'възли':>6}{'метри':>6}   сравним")
        for р in редове:
            if "грешка" in р:
                print(f"{р['файл']:<46}  ГРЕШКА {р['грешка']}")
                continue
            print(f"{р['файл'][:45]:<46}{р['задачи']:>7}{р['листа']:>7}"
                  f"{р['клон']:>6}{р['възли']:>6}{р['метри']:>6}   "
                  f"{р['сравним']}")
        по_вид: dict[str, int] = {}
        for р in редове:
            к = р.get("сравним", "?")
            по_вид[к] = по_вид.get(к, 0) + 1
        print("\n" + " · ".join(f"{к}: {v}" for к, v in по_вид.items()))
        print("Само графиците с клонове И метри позволяват сравнение на темпо "
              "участък по участък; с клонове, но без метри — сравнение на "
              "структура и брой участъци.")

    if args.koren:
        корен = Path(args.koren)
        if not корен.exists():
            print(f"\nКОРЕНЪТ НЕ Е ДОСТЪПЕН: {корен}")
            print("Входната страна не може да се опише оттук.  Пусни същата "
                  "команда от машина, която вижда папката.")
            резултат["вход"] = {"достъпен": False, "път": str(корен)}
        else:
            обекти = опиши(корен)
            резултат["вход"] = {"достъпен": True, "обекти": обекти}
            брой: dict[str, int] = {}
            for о in обекти:
                брой[о["присъда"]] = брой.get(о["присъда"], 0) + 1
            print(f"\nВХОДНА СТРАНА — {len(обекти)} обекта\n")
            print(f"{'обект':<46}{'присъда':<16}{'граф':>5}{'КСС':>5}"
                  f"{'черт':>6}{'спец':>6}")
            for о in обекти:
                print(f"{о['обект'][:45]:<46}{о['присъда']:<16}"
                      f"{о['график']:>5}{о['ксс']:>5}"
                      f"{о['чертеж']:>6}{о['спецификация']:>6}")
            print("\nобобщение: " + " · ".join(
                f"{к}: {v}" for к, v in sorted(брой.items(),
                                               key=lambda x: -x[1])))
            print(f"\nЗА BENCHMARK СТАВАТ {брой.get('готов', 0)} обекта "
                  "(имат и вход, и изход).")

    if args.out and резултат:
        Path(args.out).write_text(
            json.dumps(резултат, ensure_ascii=False, indent=1),
            encoding="utf-8")
        print(f"\n→ {args.out}")
    if not резултат:
        parser.error("дай --koren и/или --grafici")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
