#: Опашки с бройка: „– 1 бр.", „(4)", „– 4 лиценза", „(2)".  Бройката не е част
#: от името — тя живее в наличността (MaxUnits), а от 04.09.2026 изобщо не се
#: показва (правило 19).
#: Гола цифра НЕ се маха: „Водопроводен екип 1" и „екип 8" са РАЗЛИЧНИ екипи,
#: не един ресурс с бройка.  Маха се само число, което носи мерна дума
#: („1 бр.", „4 лиценза") или стои в скоби („(2)").
_БРОЙКА = re.compile(
    r"(\s*[–—-]?\s*\d+\s*(бр\.?|лиценз[аи]?|комплект[аи]?)\s*\.?$"
    r"|\s*\(\s*\d+\s*(бр\.?|лиценз[аи]?|комплект[аи]?)?\s*\)\s*\.?$)")

#: Същата опашка, но СРЕД текста: „проектантът … – 1 бр. при необходимост".
_БРОЙКА_ВЪТРЕ = re.compile(r"\s*[–—-]\s*\d+\s*(бр\.|лиценз[аи]?|комплект[аи]?)\s+")

#: Записи, които изобщо НЕ са ресурси — това са бележки, попаднали в колоната.
