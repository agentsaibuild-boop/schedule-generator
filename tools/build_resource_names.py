def _вид(име: str) -> str:
    ниско = име.lower()
    for вид, парчета in _ВИД:
        if any(п in ниско for п in парчета):
            return вид
    return "неопределен"


def _смесена(дума: str) -> bool:
    """Има ли и кирилица, и латиница в една дума."""
    има_кир = any("Ѐ" <= з <= "ӿ" for з in дума)
    има_лат = any(("a" <= з <= "z") or ("A" <= з <= "Z") for з in дума)
    return има_кир and има_лат


def _латиница_в_кирилска_дума(име: str) -> str:
    """Поправя латинска буква ВЪТРЕ в кирилска дума и само там.

    Първата версия транслитерираше всичко и изяде съкращенията: „CAD софтуер"
    ставаше „САD софтуер", „PDF" — „РDF", „CCTV" — „ССТV".  Тоест лекарството
    беше по-лошо от болестта.  Латинска дума, която е ЦЯЛА латинска, е
    съкращение и се оставя на мира.  Реже се на БУКВЕНИ парчета, не по
    интервал: „CAD/специализиран" е една дума за split(" "), но две за смисъла.
    """
    return re.sub(r"[^\W\d_]+",
                  lambda m: (m.group(0).translate(_ЛАТИНСКИ)
                             if _смесена(m.group(0)) else m.group(0)),
                  име)


def _почисти(име: str) -> str:
    ново = _латиница_в_кирилска_дума(име.strip())
    ново = _БРОЙКА_ВЪТРЕ.sub(" ", ново)
    ново = _БРОЙКА.sub("", ново).strip()
    ново = re.sub(r"\s{2,}", " ", ново)
    return ново.rstrip(".").strip() if not ново.endswith("бр.") else ново


def прочети(mpp: Path) -> list[str]:
    """Имената на ресурсите, както са записани в човешкия график."""
    import pywintypes
    import win32com.client as wc

    последна = None
    for _ in range(5):
        try:
            wc.gencache.EnsureDispatch("MSProject.Application")
            app = wc.DispatchEx("MSProject.Application")
            app.Visible = False
            app.DisplayAlerts = False
            app.FileOpen(str(mpp))
            имена = [р.Name for р in app.ActiveProject.Resources if р is not None]
            app.FileCloseAll(0)
            app.Quit()
            return имена
        except (pywintypes.com_error, TypeError) as грешка:
            последна = грешка
            subprocess.run(["taskkill", "/F", "/IM", "WINPROJ.EXE"],
                           capture_output=True)
            time.sleep(8)
    raise SystemExit(f"MS Project не отвори {mpp.name}: {последна}")


def _добавените_отпреди(път: Path) -> list[dict]:
    """Записите, добавени с решение — те НЕ идват от човешкия график.

    Речникът се ПРЕГРАЖДА от .mpp-то при всеки прогон.  Ръчно добавен запис
    („Самосвал", решение на инженера от 04.09.2026) би изчезнал тихо на
    следващото пускане — точно видът провал, който този файл трябва да лови,
    а не да причинява.  Затова всичко с ключ `добавен` се пренася.
    """
    if not път.exists():
        return []
    try:
        стар = json.loads(път.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as грешка:
        print(f"ВНИМАНИЕ: старият речник не се чете ({грешка}) — "
              f"добавените записи ще се загубят")
        return []
    return [р for р in стар.get("ресурси", []) if р.get("добавен")]


def сглоби(сурови: list[str], добавени: list[dict] | None = None) -> dict:
    бележки, работни = [], []
    for име in сурови:
        (бележки if име.strip() in _НЕ_СА_РЕСУРСИ else работни).append(име)

    # Първо: ръчните решения и механичното чистене.
    почистени: dict[str, list[str]] = {}
    for сурово in работни:
        чисто = _почисти(_РЪЧНИ.get(сурово.strip(), сурово))
        if not чисто:
            continue
        почистени.setdefault(чисто, [])
        if сурово.strip() != чисто:
            почистени[чисто].append(сурово.strip())

    # После: отрязаните.  Отрязан е този, който е ПРЕФИКС на по-дълъг и сам не
    # се среща като завършена мисъл — „средство за цифрова фот" срещу
    # „средство за цифрова фотофиксация".
    имена = sorted(почистени, key=len, reverse=True)
    отрязани: dict[str, str] = {}
    for късо in list(почистени):
        по_дълго = next((д for д in имена
                         if д != късо and д.startswith(късо)
                         and len(късо) >= 8
                         and not късо[-1].isspace()
                         and len(д) - len(късо) >= 1
                         # Срязано е ВЪТРЕ в дума: „…фот|офиксация".  Ако
                         # следващият знак е интервал, късото е завършена
                         # мисъл — „Компресор" не е отрязан „Компресор с
                         # къртица".
                         and (д[len(късо)].isalpha() or д[len(късо)] == ".")
                         and not късо.endswith(("софтуер", "станция", "пакет",
                                                "система", "нивелир",
                                                "автомобил", "проект",
                                                "компютър", "камера"))), None)
        if по_дълго:
            отрязани[късо] = по_дълго
    for късо, дълго in отрязани.items():
        почистени[дълго].append(късо)
        почистени[дълго].extend(почистени.pop(късо, []))

    записи = list(добавени or [])
    от_решение = {р["име"] for р in записи}
    for име in sorted(почистени):
        if име in от_решение:      # човешкият график го е догонил — вече е негов
            записи = [р for р in записи if р["име"] != име]
            от_решение.discard(име)
        варианти = sorted(set(почистени[име]))
        запис = {"име": име, "вид": _вид(име)}
        if име in ОПЕРАТОР:
            запис["оператор"] = ОПЕРАТОР[име]
        if варианти:
            запис["варианти"] = варианти
        записи.append(запис)
    записи.sort(key=lambda р: р["име"])
    return {
        "_какво_е": ("Еталонният речник на ресурсите: как изпълнителят ги "
                     "изписва.  Съставен от неговия график и почистен от "
                     "отрязани, полулатински и повторени записи.  Бройката НЕ е "
                     "част от името.  Записите с ключ „добавен“ НЕ идват "
                     "от графика — те са решение и носят причината си."),
        "_източник": "човешки график (MS Project), ръчно попълван",
        "_правила": ["12 — пълни думи, никакви съкращения и кодове",
                     "13 — изписват се както ги изписва човекът",
                     "19 — никакви скоби с проценти"],
        "ресурси": записи,
        "не_са_ресурси": sorted(set(бележки)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mpp")
    parser.add_argument("--out", default=str(ИЗХОД))
    args = parser.parse_args()

    сурови = прочети(Path(args.mpp))
    път = Path(args.out)
    пренесени = _добавените_отпреди(път)
    речник = сглоби(сурови, пренесени)
    път.parent.mkdir(parents=True, exist_ok=True)
    път.write_text(json.dumps(речник, ensure_ascii=False, indent=1),
                   encoding="utf-8")

    поправени = sum(1 for р in речник["ресурси"] if р.get("варианти"))
    print(f"сурови записа: {len(сурови)}")
    print(f"чисти ресурса: {len(речник['ресурси'])} · с поправка: {поправени}")
    print(f"не са ресурси: {len(речник['не_са_ресурси'])}")
    if пренесени:
        print(f"пренесени по решение: {len(пренесени)} — "
              f"{', '.join(р['име'] for р in пренесени)}")
    print(f"речник → {път}")
    for р in речник["ресурси"]:
        if р.get("варианти"):
            print(f"  {р['име']}  ←  {', '.join(repr(в) for в in р['варианти'])}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
