"""Изчиства речника на ресурсите от човешкия график и го записва като еталон.

ЗАЩО.  Имената на ресурсите се взимат от изпълнителя — така ги пише той и така
ги чака да ги види (`engineer-schedule-rules.md`, правила 12 и 13).  Неговият
файл обаче е ръчно попълван и в него има отрязани, полулатински и повторени
записи: „преносим компютъr.", „средство за цифрова фот", „офис пакетиценз",
„Tоварен автомобил" с ЛАТИНСКО T.  Ако всеки прогон ги чете направо оттам,
всеки ще ги повтори по своему.

Тук те се поправят ВЕДНЪЖ и се записват в `config/resource_names.json`, заедно
с вариантите, от които идват.  Поправката е видима: всеки запис казва какво е
било и защо е сменено, така че решението може да се оспори, а не да се приеме
на доверие.

    python tools/build_resource_names.py <човешки график>.mpp
"""

