def _дни(задачи: list[dict], корен: str) -> tuple[int, int]:
    """Първи и последен ден на дадена фаза."""
    свои = [t for t in задачи
            if str(t.get("wbs_root") or "") == корен
            and not t.get("is_summary") and t.get("start_day")]
    if not свои:
        return (0, 0)
    return (min(int(t["start_day"]) for t in свои),
            max(int(t["end_day"]) for t in свои))


def _стъпки(задачи: list[dict], мрежа: str) -> list[tuple[str, str]]:
    """Стъпките на веригата за дадена мрежа, в реда на изпълнение."""
    видени: dict[str, str] = {}
    for t in задачи:
        if t.get("is_summary") or not t.get("chain_step"):
            continue
        if str(t.get("network") or "") != мрежа:
            continue
        ключ = str(t["chain_step"])
        if ключ not in видени:
            видени[ключ] = str(t.get("chain_step_name") or t.get("name") or ключ)
    return list(видени.items())


def _участъци(задачи: list[dict]) -> dict[str, list[str]]:
    """Екип → участъците, които кара."""
    по_екип: dict[str, list[str]] = {}
    for t in задачи:
        име = str(t.get("name") or "")
        if not (t.get("is_summary") or t.get("type") == "summary"):
            continue
        екип = str(t.get("team") or "")
        if екип and име.startswith(("кл.", "Гл.")):
            по_екип.setdefault(екип, []).append(име)
    return по_екип


def _ресурси(задачи: list[dict], колко: int = 20) -> list[tuple[str, int]]:
    брой: collections.Counter = collections.Counter()
    for t in задачи:
        for r in t.get("resources") or []:
            брой[str(r)] += 1
    return брой.most_common(колко)


