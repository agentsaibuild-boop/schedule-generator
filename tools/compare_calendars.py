"""Сравнява срока на два MSPDI графика ПО ТЕХНИТЕ СОБСТВЕНИ календари.

НЕЗАВИСИМ ОДИТ 17.08.2026, P0.1: „650 дни се сравняват с 558 дни от човешкия
график, въпреки че човешкият MSPDI е 7-дневен и има Duration = PT6240H =
780 × 8h дни.  558 е броят понеделник-петък между 06.10.2025 и 24.11.2027, а
не продължителността на графика по неговия календар."

Прав е, и грешката е наша.  Числото 558 излезе от анализ, който наложи
5-дневна седмица върху график, който върви 7/7 — и оттам се роди изводът, че
сме „с 92 дни над еталона".  На обща основа сме със 130 дни ПОД него.

Изводът се обръща, затова сравнението не бива да остава разказ в документ.
Тук то е сметка, която може да се пусне:

    python tools/compare_calendars.py "<човешкият.xml>" "<нашият.xml>"

За всеки график се изважда каквото ФАЙЛЪТ казва за себе си — календар,
работни дни от седмицата, Duration в часове — и чак после се смятат
производните.  Нормализираният 5-дневен брой се показва като ДИАГНОСТИКА и е
изрично наименуван, за да не бъде взет пак за продължителност.
"""

from __future__ import annotations

import argparse
import re
import sys
import xml.etree.ElementTree as ET
from datetime import date, datetime, timedelta
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

NS = "{http://schemas.microsoft.com/project}"
ЧАСОВЕ_В_ДЕН = 8

#: MSPDI номерира дните от 1=неделя до 7=събота.
_ИМЕНА = {1: "нд", 2: "пн", 3: "вт", 4: "ср", 5: "чт", 6: "пт", 7: "сб"}


def _дата(стойност: str | None) -> date | None:
    try:
        return datetime.strptime((стойност or "")[:10], "%Y-%m-%d").date()
    except ValueError:
        return None


def _часове(duration: str | None) -> float:
    """PT6240H0M0S → 6240.0"""
    съвпадение = re.match(r"PT(?:(\d+)H)?(?:(\d+)M)?", duration or "")
    if not съвпадение:
        return 0.0
    часове = float(съвпадение.group(1) or 0)
    return часове + float(съвпадение.group(2) or 0) / 60


def _избери_календар(корен: dict, календари: dict, проектен: str | None) -> tuple[dict, str]:
    """Кой календар важи за графика — по UID, не „първият с дни".

    НЕЗАВИСИМ ОДИТ 18.08.2026, P0.5: „Скриптът не избира календара по
    project/root CalendarUID.  Той прави `next(calendar with weekdays)`.  Това
    работи СЛУЧАЙНО, ако първият календар е правилният project calendar."

    Прав е.  За еталонния график резултатът е същият, защото „Standard" е
    първи — но при файл с няколко календара инструментът би сравнил грешния
    и никой не би
    разбрал.  А целият му смисъл е да предпазва точно от такова мълчаливо
    разминаване.

    Редът е договорен: задачата бие проекта, освен когато казва „-1", което в
    MSPDI значи „по проектния".  Падането към първия календар остава, но вече
    се съобщава.

    Returns:
        (календар, как е избран) — вторият низ влиза в отчета.
    """
    от_корена = str(корен.get("calendar") or "").strip()
    кандидати = [(от_корена, "root task CalendarUID"),
                 (str(проектен or "").strip(), "Project CalendarUID")]
    for уид, как in кандидати:
        if уид and уид != "-1" and уид in календари:
            return календари[уид], f"{как} = {уид}"

    първи = next((uid for uid, c in календари.items() if c["days"]), None)
    if първи is None:
        return {"name": None, "days": {}}, "НЯМА календар във файла"
    return (календари[първи],
            f"⚠ по подразбиране: първият календар с работни дни (UID {първи}) — "
            "нито проектът, нито коренът сочат валиден UID")


def прочети(път: Path) -> dict:
    """Каквото файлът казва за себе си — стрийм-парсър, файлът е голям."""
    корен: dict = {}
    календари: dict[str, dict] = {}
    проектен: str | None = None
    дълбочина = 0

    for събитие, елемент in ET.iterparse(път, events=("start", "end")):
        етикет = елемент.tag.replace(NS, "")
        if етикет == "CalendarUID" and събитие == "end" and проектен is None:
            # Първият CalendarUID е на ПРОЕКТА: той стои в главата на
            # документа, преди Tasks и Calendars.
            проектен = (елемент.text or "").strip()
        if етикет == "Task":
            if събитие == "start":
                дълбочина += 1
                continue
            дълбочина -= 1
            if дълбочина == 0 and not корен:
                уид = елемент.findtext(f"{NS}UID")
                ниво = елемент.findtext(f"{NS}OutlineLevel")
                if уид == "0" or ниво == "0":
                    корен = {
                        "name": (елемент.findtext(f"{NS}Name") or "").strip(),
                        "start": _дата(елемент.findtext(f"{NS}Start")),
                        "finish": _дата(елемент.findtext(f"{NS}Finish")),
                        "hours": _часове(елемент.findtext(f"{NS}Duration")),
                        "calendar": елемент.findtext(f"{NS}CalendarUID"),
                    }
            елемент.clear()
        elif етикет == "Calendar" and събитие == "end":
            дни = {}
            for ден in елемент.iter(f"{NS}WeekDay"):
                тип, работен = (ден.findtext(f"{NS}DayType"),
                                ден.findtext(f"{NS}DayWorking"))
                if тип and работен is not None:
                    дни[int(тип)] = работен == "1"
            календари[елемент.findtext(f"{NS}UID")] = {
                "name": елемент.findtext(f"{NS}Name"), "days": дни}
            елемент.clear()

    основен, как = _избери_календар(корен, календари, проектен)
    return {"root": корен, "calendars": календари, "base": основен,
            "calendar_source": как}


def обобщи(път: Path) -> dict:
    данни = прочети(път)
    корен, основен = данни["root"], данни["base"]
    начало, край = корен.get("start"), корен.get("finish")
    работни = sorted(n for n, вкл in (основен.get("days") or {}).items() if вкл)

    календарни = ((край - начало).days + 1) if начало and край else 0
    делници = 0
    if начало and край:
        делници = sum(1 for i in range(календарни)
                      if (начало + timedelta(days=i)).weekday() < 5)

    return {
        "файл": път.name,
        "начало": начало, "край": край,
        "календар": основен.get("name"),
        "избран_по": данни.get("calendar_source", ""),
        "работни_дни_от_седмицата": [_ИМЕНА[n] for n in работни],
        "работни_на_седмица": len(работни),
        "часове": корен.get("hours", 0.0),
        "дни_по_MSPDI": round(корен.get("hours", 0.0) / ЧАСОВЕ_В_ДЕН, 1),
        "календарен_обхват": календарни,
        "normalized_5d_weekdays": делници,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("графики", nargs="+", help="MSPDI файлове (.xml)")
    args = parser.parse_args()

    редове = []
    for име in args.графики:
        път = Path(име)
        if not път.exists():
            print(f"няма такъв файл: {път}")
            return 2
        редове.append(обобщи(път))

    for р in редове:
        print(f"\n=== {р['файл']} ===")
        print(f"  {р['начало']} → {р['край']}")
        print(f"  избран по: {р['избран_по']}")
        print(f"  календар: {р['календар']} — работни дни: "
              f"{', '.join(р['работни_дни_от_седмицата'])} "
              f"({р['работни_на_седмица']}/7)")
        print(f"  Duration по MSPDI: {р['часове']:.0f} ч = "
              f"{р['дни_по_MSPDI']:.0f} работни дни")
        print(f"  календарен обхват: {р['календарен_обхват']} дни")
        print(f"  normalized_5d_weekdays: {р['normalized_5d_weekdays']} "
              f"(ДИАГНОСТИКА — не е продължителност)")

    if len(редове) < 2:
        return 0

    print("\n" + "=" * 66)
    основи = {р["работни_на_седмица"] for р in редове}
    if len(основи) > 1:
        print("ВНИМАНИЕ: графиците са на РАЗЛИЧНИ календари "
              f"({sorted(основи)} работни дни/седмица).")
        print("Сравнявай ПО КАЛЕНДАРЕН ОБХВАТ или приведи двата към един "
              "календар.\nНикога не сравнявай ден-индекс от единия с "
              "делнични дни от другия.")
    else:
        print(f"Двата графика са на еднакъв календар "
              f"({редове[0]['работни_на_седмица']}/7) — сравними са пряко.")

    a, b = редове[0], редове[1]
    print(f"\n{'':34s}{a['файл'][:14]:>16s}{b['файл'][:14]:>16s}")
    for ключ, етикет in (("дни_по_MSPDI", "дни по MSPDI"),
                         ("календарен_обхват", "календарен обхват"),
                         ("normalized_5d_weekdays", "5-дневни делници")):
        print(f"{етикет:34s}{a[ключ]:>16.0f}{b[ключ]:>16.0f}")
    разлика = b["календарен_обхват"] - a["календарен_обхват"]
    print(f"\nразлика по календарен обхват: {разлика:+d} дни "
          f"({'вторият е по-дълъг' if разлика > 0 else 'вторият е по-кратък'})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
