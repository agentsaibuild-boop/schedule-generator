#: Работните програми се разпознават по името си — в папката има и образци на
#: възложителя, декларации и указания, които не са наш текст.
_ИМЕНА = ("работна програма", "предложение за изпълнение", "приложение 1",
          "приложение № 1")

#: Абзац, по-къс от това, е заглавие на списък, а не описание.
_МИН_ОПИСАНИЕ = 120


def _работни_програми(корен: Path) -> list[Path]:
    намерени = []
    for път in корен.rglob("*.docx"):
        име = път.name.lower()
        if име.startswith("~$"):
            continue
        if any(дума in име for дума in _ИМЕНА):
            намерени.append(път)
    return sorted(намерени, key=lambda p: -p.stat().st_size)


def _нормализирай(заглавие: str) -> str:
    """Ключът на операцията: без пунктуация, без бройки, с малки букви."""
    т = заглавие.lower().strip()
    т = re.sub(r"[.,;:!?]+$", "", т)
    т = re.sub(r"\s+", " ", т)
    return т


def извади(път: Path) -> list[dict]:
    """Операциите и описанията им от една работна програма."""
    import docx

    d = docx.Document(str(път))
    записи: list[dict] = []
    текущо: str | None = None
    тяло: list[str] = []

    def затвори() -> None:
        if текущо and тяло:
            текст = "\n".join(тяло).strip()
            if len(текст) >= _МИН_ОПИСАНИЕ:
                записи.append({
                    "операция": текущо,
                    "ключ": _нормализирай(текущо),
                    "текст": текст,
                    "знаци": len(текст),
                    "източник": път.name,
                })

    for абзац in d.paragraphs:
        т = абзац.text.strip()
        if not т:
            continue
        удебелен = any(r.bold for r in абзац.runs if r.bold is not None)
        # Заглавие: удебелен и достатъчно къс, за да е заглавие, а не изречение.
        if удебелен and len(т) <= 160:
            затвори()
            текущо, тяло = т, []
        elif текущо:
            тяло.append(т)
    затвори()
    return записи


def сглоби(корен: Path) -> dict:
    програми = _работни_програми(корен)
    всички: list[dict] = []
    по_файл: dict[str, int] = {}
    for път in програми:
        try:
            записи = извади(път)
        except Exception as exc:              # повреден или чужд формат
            print(f"  ПРОПУСНАТ {път.name}: {str(exc)[:60]}")
            continue
        всички.extend(записи)
        по_файл[път.name] = len(записи)
        print(f"  {len(записи):>4} операции · {sum(з['знаци'] for з in записи):>8,} зн"
              f"  {път.name[:64]}")

    # Една операция, описана в няколко програми — пазим НАЙ-ПОДРОБНОТО описание,
    # но броим в колко източника се среща: това е мярката колко е устойчива.
    по_ключ: dict[str, dict] = {}
    for з in всички:
        ако = по_ключ.get(з["ключ"])
        if ако is None:
            по_ключ[з["ключ"]] = {**з, "източници": [з["източник"]]}
        else:
            ако["източници"].append(з["източник"])
            if з["знаци"] > ако["знаци"]:
                ако.update({k: з[k] for k in ("операция", "текст", "знаци")})
    return {"програми": по_файл, "операции": list(по_ключ.values())}


